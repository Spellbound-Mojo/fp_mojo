"""Native admission for traversal policies shared by Iter and free calls."""
from combinator_docs import document_first_methods
from operation_specs import TRAVERSALS
from native_signatures import MD, callable_protocol, callable_metadata, native_adapter, callback as described_callback, native_factories, admissions, closure, defaulted, split_explicit, error_probe, probed
START='# --- traversal conveniences (generated) ---\n'
END='# --- end traversal conveniences ---\n'
HEADER='# Generated by scripts/generate_traversal_syntax.py; execution stays in algebra._traversal and families.\n'


def pointer_methods():
    """Copy plain functions into the ordinary owned traversal callback.

    Iter knows its element, so the plain-function forms come from the shared
    callback catalog with that element: they compete with closure borrows by
    value, and deferred target families such as IO can keep them.
    """
    out = []
    element = f'downcast[Self.I.Element, {MD}]'
    for name in ('traverse', 'traverse_void'):
        for form in admissions('owned', [element], library=False, view=False, names={'X': 'E'}):
            if form.kind != 'thin':
                continue
            params = list(form.parameters) + ['//', 'G: Applicative = _InferredApplicative[R]']
            cb = form.type
            conditions = list(form.conditions)
            if name == 'traverse':
                result = f'G.Collected[Self.I, {cb}]'
                raised = f'G.CollectError[Self.I, {cb}]'
                conditions += [f'G.CollectCompatible[Self.I, {cb}]']
            else:
                params += ['X: AnyType = _InferError']
                rule = f'_Discard[G.Element[{cb}.Out]]'
                result = f'G._Looped[Self.I, {cb}, {rule}]'
                raised = f'_EntryError[X, G._LoopError[Self.I, {cb}, {rule}]]'
                conditions += ['_CarrierCompatible[G, R]', f'G._LoopCompatible[Self.I, {cb}, {rule}]']
            assertion = ''
            if form.raising:
                # Name the native error through a probe so it reduces without X=.
                raised, assertion = probed(raised, cb, error_probe('owned', ('NoneType',), form.result, form.error))
                assertion = f'        {assertion}\n'
            call = (f'_traverse_as[ListFamily, G, Self.I, {cb}, {raised}]' if name == 'traverse' else
                    f'_traverse_void[Self.I, {cb}, G, {raised}]')
            out.append(f'''
    def {name}[{', '.join(params)}](deinit self, {form.argument}) raises {raised} -> {result} where {' and '.join(conditions)}:
        """Copy a plain function into the existing traversal owner."""
{assertion}        return {call}({form.build}, self._iterator^)
''')
    return ''.join(out)


def parallel_methods():
    """Iter's accumulating traversals through ValidationFamily[S].

    The Semigroup defaults to concatenating list-valued stored errors.
    """
    out = []
    target_family = 'ValidationFamily[S]'
    for kind in ('pure', 'raising', 'library', 'view'):
        native = kind in ('pure', 'raising')
        params = ([f'A: {MD}', f'R: {MD}', 'o: ImmOrigin'] if native else
                  ['F: _UnaryViewable', 'o: ImmOrigin'] if kind == 'view' else [f'F: {callable_protocol("owned")} & {MD}'])
        target = 'R' if native else 'F._View[o].Out' if kind == 'view' else 'F.Out'
        if native:
            form = closure('owned', kind == 'raising', names={'C': 'F', 'X': 'E', 'in0': 'A'})
            params += list(form.explicit)
        params += ['//', f'S: Semigroup = _ListErrors[{target}]']
        elem = 'A' if native else 'F._View[o].Arg' if kind == 'view' else 'F.Arg'
        callback = form.type if native else 'F._View[o]' if kind == 'view' else 'F'
        build = form.build if native else 'function._unary_view()' if kind == 'view' else 'function^'
        args = f'{target_family}, Self.I, {callback}'
        condition = (f'Self.I.Element == {elem} and ListFamily.TargetCompatible[{args}]'
                     f' and _CarrierCompatible[{target_family}, {target}]')
        out.append(f'''
    def par_traverse[{', '.join(params)}](deinit self, {'ref[o] function: F' if native or kind == 'view' else 'var function: F'}) raises ListFamily.TraverseError[{args}] -> ListFamily.Traversed[{args}] where {condition}:
        """Apply par_traverse through the carrier's Traversable capability."""
        return ListFamily.traverse[{target_family}]({build}, self._iterator^)
''')
    elem = f'downcast[Self.I.Element, {MD}]'
    cb = f'_Same[{elem}]'
    args = f'{target_family}, Self.I, {cb}'
    # Identity cannot raise; only multi-element sources can invoke S. Spell that
    # exact effect for generic callers; the traversal adapter checks it.
    out.append(f'''
    def par_sequence[S: Semigroup = _ListErrors[{elem}]](deinit self) raises S.Error -> ListFamily.Traversed[{args}] where Self.I.Element == {elem} and ListFamily.TargetCompatible[{args}] and _CarrierCompatible[{target_family}, {elem}]:
        """Derive par_sequence through traverse, preserving the family's semantics."""
        return _traverse_as[ListFamily, {target_family}, Self.I, {cb}, S.Error]({cb}(), self._iterator^)
''')
    # After the Validation forms, which keep the first, documented overload.
    out.append(parallel_family_methods())
    return ''.join(out)


def parallel_family_methods():
    """Iter's concurrent traversals: a callback returning a carrier of a `Parallel` family, such as IO, selects its `Par`.

    These forms and the Validation forms above are exclusive: a Result
    carrier's family has no `Parallel`, and these require it.
    """
    out = []
    for kind in ('pure', 'raising', 'library', 'view'):
        native = kind in ('pure', 'raising')
        params = ([f'A: {MD}', f'R: {MD}', 'o: ImmOrigin'] if native else
                  ['F: _UnaryViewable', 'o: ImmOrigin'] if kind == 'view' else [f'F: {callable_protocol("owned")} & {MD}'])
        target = 'R' if native else 'F._View[o].Out' if kind == 'view' else 'F.Out'
        if native:
            form = closure('owned', kind == 'raising', names={'C': 'F', 'X': 'E', 'in0': 'A'})
            params += list(form.explicit)
        params += ['//']
        family = f'_InferredParallel[{target}].Par'
        elem = 'A' if native else 'F._View[o].Arg' if kind == 'view' else 'F.Arg'
        callback = form.type if native else 'F._View[o]' if kind == 'view' else 'F'
        build = form.build if native else 'function._unary_view()' if kind == 'view' else 'function^'
        args = f'{family}, Self.I, {callback}'
        condition = (f'conforms_to(_NativeFamily[{target}], Parallel) and Self.I.Element == {elem}'
                     f' and ListFamily.TargetCompatible[{args}] and _CarrierCompatible[{family}, {target}]')
        out.append(f'''
    def par_traverse[{', '.join(params)}](deinit self, {'ref[o] function: F' if native or kind == 'view' else 'var function: F'}) raises ListFamily.TraverseError[{args}] -> ListFamily.Traversed[{args}] where {condition}:
        """Run every element's effect concurrently through its family's Par, such as IO's AsyncPar."""
        return ListFamily.traverse[{family}]({build}, self._iterator^)
''')
    # Plain functions are copied into an owned callback, as Iter.traverse
    # does, so a deferred family such as IO can keep them.
    element = f'downcast[Self.I.Element, {MD}]'
    for form in admissions('owned', [element], library=False, view=False, names={'X': 'E'}):
        if form.kind != 'thin':
            continue
        cb = form.type
        family = f'_InferredParallel[R].Par'
        args = f'{family}, Self.I, {cb}'
        raised = f'ListFamily.TraverseError[{args}]'
        assertion = ''
        if form.raising:
            raised, assertion = probed(raised, cb, error_probe('owned', ('NoneType',), form.result, form.error))
            assertion = f'        {assertion}\n'
        conditions = [*form.conditions, 'conforms_to(_NativeFamily[R], Parallel)', f'ListFamily.TargetCompatible[{args}]', f'_CarrierCompatible[{family}, R]']
        out.append(f'''
    def par_traverse[{', '.join(list(form.parameters) + ['//'])}](deinit self, {form.argument}) raises {raised} -> ListFamily.Traversed[{args}] where {' and '.join(conditions)}:
        """Copy a plain function and run every element's effect concurrently through its family's Par."""
{assertion}        return _traverse_as[ListFamily, {family}, Self.I, {cb}, {raised}]({form.build}, self._iterator^)
''')
    elem = f'downcast[Self.I.Element, {MD}]'
    family = f'_InferredParallel[{elem}].Par'
    cb = f'_Same[{elem}]'
    args = f'{family}, Self.I, {cb}'
    out.append(f'''
    def par_sequence(deinit self) raises ListFamily.TraverseError[{args}] -> ListFamily.Traversed[{args}] where conforms_to(_NativeFamily[{elem}], Parallel) and Self.I.Element == {elem} and ListFamily.TargetCompatible[{args}] and _CarrierCompatible[{family}, {elem}]:
        """Run every element's effect concurrently through its family's Par, such as IO's AsyncPar."""
        return _traverse_as[ListFamily, {family}, Self.I, {cb}, ListFamily.TraverseError[{args}]]({cb}(), self._iterator^)
''')
    return ''.join(out)


def free_traverse(parallel=False):
    """Value-first native admission for the free traverse; G.collect executes.

    With `parallel`, the same forms of par_traverse: the family is any I whose
    conformance includes `Parallel` and the target its `_ParOf[I]`, through
    the same shared entry; the constraint leads the admission.
    """
    out = []
    element = f'downcast[_Source[V].Element, {MD}]'
    G = '_ParOf[I]' if parallel else 'G'
    name = 'par_traverse' if parallel else 'traverse'
    for form in admissions('owned', [element], library=False, names={'X': 'E', 'C': 'F', 'in0': 'A'}):
        D = form.type
        if parallel:
            target = '_ViewFamily[F, o]' if form.kind == 'view' else f'_NativeFamily[{form.result}]'
            family = f'I: Functor = {target}'
        else:
            target = '_ViewTarget[F, o]' if form.kind == 'view' else f'_InferredApplicative[{form.result}]'
            family = f'G: Applicative = {target}'
        params = [*form.parameters, f'V: {MD}', '//', family, *defaulted(form.explicit)]
        guards = [*form.conditions, f'{G}.CollectCompatible[V, {D}]']
        if parallel:
            guards.insert(0, 'conforms_to(I, Parallel)')
        if form.kind == 'view':
            guards.insert(1 if parallel else 0, f'_Source[V].Element == {D}.Arg')
            raised = f'{G}.CollectError[V, {D}]'
        else:
            # A defaulted target's error must reduce in the raises clause; the
            # probe names only the callback's result and error (see algebra).
            probe_input = 'NoneType' if form.kind == 'thin' else form.inputs[0]
            raised = f'{G}.CollectError[V, _ErrorProbe[{probe_input}, {form.result}, {form.error}]]'
        out.append(f'''
def {name}[{', '.join(params)}](var source: V, {form.argument}) raises {raised} -> {G}.Collected[V, {D}] where {' and '.join(guards)}:
    """Traverse with a {form.kind} callback; {G}.collect executes."""
    comptime assert {G}.CollectError[V, {D}] == {raised}
    return _traverse_as[ListFamily, {G}, V, {D}, {raised}]({form.build}, source^)
''')
    return ''.join(out)


def methods(mode, parallel=False):
    out=[]
    for name, operation in TRAVERSALS.items():
        if parallel and name != 'traverse_void':
            continue
        if parallel:
            # par_traverse_void: traverse_void with a Parallel family's Par.
            name = 'par_traverse_void'
        filtering, borrowing = operation.filtering, operation.borrowing
        discard, sequence = operation.discard, operation.sequence
        flatten, compact = operation.flatten, operation.compact
        post = bool(operation.finish)
        kinds = ('identity',) if sequence else ('library','pure','raising')
        if mode == 'iter' and name in ('traverse_void', 'flat_traverse', 'traverse_filter'):
            kinds += ('view',)
        variants = [(kind, None) for kind in kinds]
        if mode == 'free' and not sequence:
            # Free calls are value-first: the source fixes the element, and
            # every callback form comes from the shared catalog.
            element = '_Source[V].Element' if borrowing else f'downcast[_Source[V].Element, {MD}]'
            variants = [('catalog', form) for form in admissions(
                'borrow' if borrowing else 'owned', [element], view=False,
                names={'X': 'E', 'C': 'F', 'L': 'C' if borrowing else 'F', 'in0': 'P' if borrowing else 'A'})]
        for kind, factory in variants:
            native=kind in ('pure','raising') or (kind == 'catalog' and factory.kind != 'library')
            error='E' if kind=='raising' else 'Never'
            if sequence:
                params=[]
                elem=f'downcast[_Source[{"V" if mode=="free" else "Self.I"}].Element, {MD}]'
                cb=f'_Same[{elem}]';build=f'{cb}()';arg=''
            elif kind == 'view':
                view = described_callback('owned', 'view').renamed({'C': 'F'})
                params = list(view.parameters)
                elem, cb, build, arg = view.payload, view.type, view.build, view.argument
                metadata = callable_metadata('owned', cb)
            elif kind == 'catalog':
                form = factory
                params = list(form.parameters)
                cb, build, arg = form.type, form.build, form.argument
                metadata = callable_metadata('borrow' if borrowing else 'owned', cb)
                elem = (f'downcast[{metadata.inputs[0]}, {MD}]' if borrowing else metadata.inputs[0]) if form.kind == 'library' else (
                    f'downcast[_Source[V].Element, {MD}]')
            elif native:
                # Iter closures come from the shared catalog; the surface relates the input.
                form = closure('borrow' if borrowing else 'owned', kind == 'raising',
                               names={'C': 'F', 'X': 'E', 'in0': 'P' if borrowing else 'A'})
                params=list(form.parameters)
                elem=f'downcast[P, {MD}]' if borrowing else 'A'
                cb,build,arg=form.type,form.build,form.argument
            else:
                params=[f'C: {callable_protocol("borrow")} & {MD}' if borrowing else f'F: {callable_protocol("owned")} & {MD}']
                cb='C' if borrowing else 'F';build='function^';arg=f'var function: {cb}'
                metadata=callable_metadata('borrow' if borrowing else 'owned', cb)
                elem=f'downcast[{metadata.inputs[0]}, {MD}]' if borrowing else metadata.inputs[0]
            if mode=='free': params += [f'V: {MD}']
            target = '_ParOf[I]' if parallel else 'G'
            native_params = ([f'E: {MD}'] if kind == 'raising' else [])
            if kind == 'catalog': native_params = list(factory.explicit)
            elif native: native_params = list(form.explicit)
            # The families default, so the callback parameters after them
            # default to their own bounds.
            lead, native_params = split_explicit(native_params)
            params += lead
            if params: params += ['//']
            # Each target defaults: a view to its declared family, sequence
            # to its elements' and others to the callback result's.
            family_parameter = 'G: Applicative'
            if kind == 'view':
                family_parameter += ' = _ViewTarget[F, o]'
            elif sequence:
                family_parameter += f' = _InferredApplicative[{elem}]'
            elif mode == 'free':
                family_parameter += f' = _InferredApplicative[{factory.result}]'
            else:
                family_parameter += f' = _InferredApplicative[{"R" if native else metadata.result}]'
            if parallel:
                family_parameter = family_parameter.replace('G: Applicative', 'I: Functor').replace(
                    '_ViewTarget', '_ViewFamily').replace('_InferredApplicative', '_NativeFamily')
            params += [family_parameter, *native_params, 'X: AnyType = _InferError']
            callback=operation.retained(elem, 'G', cb) if borrowing else cb
            callback_value=f'{callback}({build})' if borrowing else build
            source='V' if mode=='free' else 'Self.I'
            value='source^' if mode=='free' else 'self._iterator^'
            condition=f'_Source[{source}].Element == {elem}'
            if kind == 'catalog' and factory.kind != 'library':
                # The catalog relates closure inputs; plain functions spell the element.
                condition = ' and '.join(factory.conditions) or 'True'
            if not discard:
                family='ListFamily'
                result=f'G.Collected[{source}, {callback}]';raised=f'G.CollectError[{source}, {callback}]'
                raised=f'_EntryError[X, {raised}]'
                call=f'_traverse_as[ListFamily, G, {source}, {callback}, {raised}]({callback_value}, {value})'
            if discard:
                rule=f'_Discard[{target}.Element[{cb}.Out]]'
                result=f'{target}._Looped[{source}, {cb}, {rule}]';raised=f'{target}._LoopError[{source}, {cb}, {rule}]'
                raised=f'_EntryError[X, {raised}]'
                call=f'_traverse_void[{source}, {cb}, {target}, {raised}]({callback_value}, {value})'
            if post:
                plan=operation.postprocess(family, 'G', source, callback)
                raised=f'_EntryError[X, {plan.error}]'
                result=plan.result
                call=plan.invoke(family, 'G', source, callback, raised, callback_value, value)
                # Admission follows construction errors. Deferred target families
                # retain predicate errors in the produced computation.
                condition += f' and _ErrorCompatible[{raised}, {plan.before}]'
                payload=f'G.Element[{"R" if native and not filtering else callback + ".Out"}]'
                if filtering: condition += f' and G.Element[{"R" if native else metadata.result}] == Bool'
                if compact:
                    condition += f' and {payload} == Optional[_ListElement[{payload}]]'
                else:
                    condition += f' and {payload} == List[_ListElement[{payload}]]'
            # Native Result effects must keep their stored-error origins even
            # when the target family is explicit. A late family assertion is
            # insufficient on Mojo 1.1; compare the native shape at admission.
            # Probe the target's neutral carrier: non-Result targets must not
            # require a generic callback's opaque return type to be resolved.
            effect='R' if native else callable_metadata('borrow' if borrowing else 'owned', cb).result
            condition += f' and _CarrierCompatible[{target}, {effect}]'
            if discard:
                condition += f' and {target}._LoopCompatible[{source}, {cb}, {rule}]'
            else:
                condition += f' and {family}.TargetCompatible[G, {source}, {callback}]'
            assertion = ''
            raising_form = factory if kind == 'catalog' else form if kind == 'raising' else None
            if raising_form is not None and raising_form.raising and raising_form.kind != 'library':
                # Name the native error through a probe so it reduces without X=.
                inputs = ('NoneType',) if raising_form.kind == 'thin' else raising_form.inputs[:1]
                probe = error_probe('borrow' if borrowing else 'owned', inputs, raising_form.result, raising_form.error)
                spelled, assertion = probed(raised, cb, probe)
                call, condition = call.replace(raised, spelled), condition.replace(raised, spelled)
                raised = spelled
            if parallel:
                condition = f'conforms_to(I, Parallel) and {condition}'
            indent='' if mode=='free' else '    '
            args=', '.join(x for x in (('var source: V', arg) if mode=='free' else ('deinit self', arg)) if x)
            summary=("Run effects concurrently through the family's Par, without retaining successful outputs." if parallel else operation.summary)
            prelude = f'{indent}    {assertion}\n' if assertion else ''
            out.append(f'''\n{indent}def {name}[{', '.join(params)}]({args}) raises {raised} -> {result} where {condition}:
{indent}    """{summary}"""
{prelude}{indent}    return {call}
''')
    if mode == 'free' and not parallel:
        out.append(free_traverse())
        out.append(methods('free', parallel=True))
        out.append(free_traverse(parallel=True))
        return document_first_methods(''.join(out))
    if mode == 'iter':
        out.append(pointer_methods())
        out.append(parallel_methods())
    return document_first_methods(''.join(out))
