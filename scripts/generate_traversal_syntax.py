def pointer_methods():
    """Copy plain functions into the ordinary owned traversal callback.

    Iter knows its element, so the plain-function forms come from the shared
    callback catalog with that element: they compete with closure borrows by
    value, and deferred target families such as IO can keep them.
    """
    out = []
    element = f'downcast[Self.I.Element, {MD}]'
    for name in ('traverse', 'traverse_void'):
        for form in admissions('owned', [element], library=False, view=False, names={'X': 'E'}):
            if form.kind != 'thin':
                continue
            params = list(form.parameters) + ['//', 'G: Applicative = _InferredApplicative[R]']
            cb = form.type
            conditions = list(form.conditions)
            if name == 'traverse':
                result = f'G.Collected[Self.I, {cb}]'
                raised = f'G.CollectError[Self.I, {cb}]'
                conditions += [f'G.CollectCompatible[Self.I, {cb}]']
                binding = 'G'
            else:
                params += ['X: AnyType = _InferError']
                rule = f'_Discard[G.Element[{cb}.Out]]'
                result = f'G._Looped[Self.I, {cb}, {rule}]'
                raised = f'_EntryError[X, G._LoopError[Self.I, {cb}, {rule}]]'
                conditions += ['_CarrierCompatible[G, R]', f'G._LoopCompatible[Self.I, {cb}, {rule}]']
                binding = 'G, X=X'
            out.append(f'''
    def {name}[{', '.join(params)}](deinit self, {form.argument}) raises {raised} -> {result} where {' and '.join(conditions)}:
        """Copy a plain function into the existing traversal owner."""
        return self^.{name}[{binding}]({form.build})
''')
    return ''.join(out)


def free_traverse():
    """Value-first native admission for the free traverse; G.collect executes."""
    out = []
    element = f'downcast[_Source[V].Element, {MD}]'
    for form in admissions('owned', [element], library=False, names={'X': 'E', 'C': 'F', 'in0': 'A'}):
        D = form.type
        target = '_ViewTarget[F, o]' if form.kind == 'view' else f'_InferredApplicative[{form.result}]'
        params = [*form.parameters, f'V: {MD}', '//', f'G: Applicative = {target}', *defaulted(form.explicit)]
        guards = [*form.conditions, f'G.CollectCompatible[V, {D}]']
        if form.kind == 'view':
            guards.insert(0, f'_Source[V].Element == {D}.Arg')
            raised = f'G.CollectError[V, {D}]'
        else:
            # A defaulted target's error must reduce in the raises clause; the
            # probe names only the callback's result and error (see algebra).
            probe_input = 'NoneType' if form.kind == 'thin' else form.inputs[0]
            raised = f'G.CollectError[V, _ErrorProbe[{probe_input}, {form.result}, {form.error}]]'
        out.append(f'''
def traverse[{', '.join(params)}](var source: V, {form.argument}) raises {raised} -> G.Collected[V, {D}] where {' and '.join(guards)}:
    """Traverse with a {form.kind} callback; G.collect executes."""
    comptime assert G.CollectError[V, {D}] == {raised}
    return _traverse_as[ListFamily, G, V, {D}, {raised}]({form.build}, source^)
''')
    return ''.join(out)


def methods(mode, carrier=None, *, discard_only=False):
    out=[]
    for name, operation in TRAVERSALS.items():
        filtering, borrowing = operation.filtering, operation.borrowing
        discard, sequence = operation.discard, operation.sequence
        flatten, compact = operation.flatten, operation.compact
        post = bool(operation.finish)
        if discard_only and not discard: continue
        if mode=='piped':
            if carrier:
                if not discard and 'traverse' not in carrier.capabilities: continue
                if flatten and 'flat_map' not in carrier.capabilities: continue
                if compact and 'filter_map' not in carrier.capabilities: continue
                if discard and carrier.name not in ('List','Array','Deque','LinkedList','Optional','Result'): continue
            elif discard: continue
        kinds = ('identity',) if sequence else ('library','pure','raising')
        if mode == 'iter' and name in ('traverse_void', 'flat_traverse', 'traverse_filter'):
            kinds += ('view',)
        variants = [(kind, None) for kind in kinds]
        if mode == 'free' and not sequence:
            # Free calls are value-first: the source fixes the element, and
            # every callback form comes from the shared catalog.
            element = '_Source[V].Element' if borrowing else f'downcast[_Source[V].Element, {MD}]'
            variants = [('catalog', form) for form in admissions(
                'borrow' if borrowing else 'owned', [element], view=False,
                names={'X': 'E', 'C': 'F', 'L': 'C' if borrowing else 'F', 'in0': 'P' if borrowing else 'A'})]
        for kind, factory in variants:
            native=kind in ('pure','raising') or (kind == 'catalog' and factory.kind != 'library')
            error='E' if kind=='raising' else 'Never'
            if sequence:
                params=[f'T: {MD}'] if carrier else []
                elem='T' if carrier else ('S.Element[Self.Value]' if mode=='piped' else f'downcast[_Source[{"V" if mode=="free" else "Self.I"}].Element, {MD}]')
                cb=f'_Same[{elem}]';build=f'{cb}()';arg=''
            elif kind == 'view':
                view = described_callback('owned', 'view').renamed({'C': 'F'})
                params = list(view.parameters)
                elem, cb, build, arg = view.payload, view.type, view.build, view.argument
                metadata = callable_metadata('owned', cb)
            elif kind == 'catalog':
                form = factory
                params = list(form.parameters)
                cb, build, arg = form.type, form.build, form.argument
                metadata = callable_metadata('borrow' if borrowing else 'owned', cb)
                elem = (f'downcast[{metadata.inputs[0]}, {MD}]' if borrowing else metadata.inputs[0]) if form.kind == 'library' else (
                    f'downcast[_Source[V].Element, {MD}]')
            elif native:
                # Iter and Piped closures come from the shared catalog; the surface relates the input.
                form = closure('borrow' if borrowing else 'owned', kind == 'raising',
                               names={'C': 'F', 'X': 'E', 'in0': 'P' if borrowing else 'A'})
                params=list(form.parameters)
                elem=f'downcast[P, {MD}]' if borrowing else 'A'
                cb,build,arg=form.type,form.build,form.argument
            else:
                params=[f'C: {callable_protocol("borrow")} & {MD}' if borrowing else f'F: {callable_protocol("owned")} & {MD}']
                cb='C' if borrowing else 'F';build='function^';arg=f'var function: {cb}'
                metadata=callable_metadata('borrow' if borrowing else 'owned', cb)
                elem=f'downcast[{metadata.inputs[0]}, {MD}]' if borrowing else metadata.inputs[0]
            if mode=='free': params += [f'V: {MD}']
            if carrier: params += list(carrier.parameters)
            target = 'G'
            native_params = ([f'E: {MD}'] if kind == 'raising' else [])
            if kind == 'catalog': native_params = list(factory.explicit)
            elif native: native_params = list(form.explicit)
            if mode in ('free', 'iter') or (mode == 'piped' and not carrier):
                # The families default, so the callback parameters after them
                # default to their own bounds.
                lead, native_params = split_explicit(native_params)
                params += lead
                if params: params += ['//']
            elif params: params += ['//']
            piped_source = 'S: Traversable' + (' & ' + operation.source_capability if post else '')
            if mode=='piped' and not carrier:
                # Target first; the source defaults to the held value's family.
                piped_source += ' = ' + source_default('Traversable' + (' & ' + operation.source_capability if post else ''), 'Self.Value')
            # Each target defaults: a view to its declared family, sequence
            # to its elements' and others to the callback result's.
            family_parameter = 'G: Applicative'
            if mode == 'piped' and carrier:
                pass
            elif kind == 'view':
                family_parameter += ' = _ViewTarget[F, o]'
            elif sequence and mode == 'piped':
                family_parameter += f' = _InferredApplicative[{elem.replace("S.Element", source_default("Traversable", "Self.Value") + ".Element")}]'
            elif sequence:
                family_parameter += f' = _InferredApplicative[{elem}]'
            elif mode == 'free':
                family_parameter += f' = _InferredApplicative[{factory.result}]'
            else:
                family_parameter += f' = _InferredApplicative[{"R" if native else metadata.result}]'
            params += [family_parameter, *([piped_source] if mode == 'piped' and not carrier else []), *native_params, 'X: AnyType = _InferError']
            retained_error = discard and carrier and carrier.name == 'Result'
            callback=operation.retained(elem, 'G', cb) if borrowing else cb
            if retained_error: callback=f'Composition[False, 1, {cb}, _EffectVoid[G, {cb}.Out]]'
            callback_value=f'{callback}({build})' if borrowing else build
            if retained_error: callback_value=f'{callback}({build}, _EffectVoid[G, {cb}.Out]())'
            if mode=='piped':
                source=carrier.value(elem) if carrier else 'Self.Value'
                value=f'rebind_var[{source}](self.value^)' if carrier else 'self.value^'
                condition=f'Self.Value == {source}' if carrier else f'S.Element[Self.Value] == {elem}'
                if not carrier:
                    condition += ' and ((S.Mapped[Self.Value, _Same[S.Element[Self.Value]]] == Self.Value) if conforms_to(Self.Value, _ResultType) else True)'
                if not discard or retained_error:
                    family=carrier.instance(elem) if carrier else 'S'
                    result=f'{family}.Traversed[G, {source}, {callback}]'
                    raised=f'{family}.TraverseError[G, {source}, {callback}]'
                    raised=f'_EntryError[X, {raised}]'
                    call=f'_traverse_as[{family}, G, {source}, {callback}, {raised}]({callback_value}, {value})'
            else:
                source='V' if mode=='free' else 'Self.I'
                value='source^' if mode=='free' else 'self._iterator^'
                condition=f'_Source[{source}].Element == {elem}'
                if kind == 'catalog' and factory.kind != 'library':
                    # The catalog relates closure inputs; plain functions spell the element.
                    condition = ' and '.join(factory.conditions) or 'True'
                if not discard:
                    family='ListFamily'
                    result=f'G.Collected[{source}, {callback}]';raised=f'G.CollectError[{source}, {callback}]'
                    raised=f'_EntryError[X, {raised}]'
                    call=f'_traverse_as[ListFamily, G, {source}, {callback}, {raised}]({callback_value}, {value})'
            if discard and not retained_error:
                if carrier and carrier.name=='Array':
                    source=f'List[{elem}]';value=f'_take_array({value})'
                rule=f'_Discard[{target}.Element[{cb}.Out]]'
                result=f'{target}._Looped[{source}, {cb}, {rule}]';raised=f'{target}._LoopError[{source}, {cb}, {rule}]'
                raised=f'_EntryError[X, {raised}]'
                call=f'_traverse_void[{source}, {cb}, {target}, {raised}]({callback_value}, {value})'
            if post:
                plan=operation.postprocess(family, 'G', source, callback)
                raised=f'_EntryError[X, {plan.error}]'
                result=plan.result
                call=plan.invoke(family, 'G', source, callback, raised, callback_value, value)
                # Admission follows construction errors. Deferred target families
                # retain predicate errors in the produced computation.
                condition += f' and _ErrorCompatible[{raised}, {plan.before}]'
                payload=f'G.Element[{"R" if native and not filtering else callback + ".Out"}]'
                if filtering: condition += f' and G.Element[{"R" if native else metadata.result}] == Bool'
                if compact:
                    condition += f' and {payload} == Optional[_ListElement[{payload}]]'
                elif carrier:
                    condition += f' and {payload} == {carrier.value(f"{family}.Element[{payload}]")}'
                elif mode!='piped':
                    condition += f' and {payload} == List[_ListElement[{payload}]]'
                else:
                    # Mojo 1.1 can erase mismatched embedded origins in a late
                    # ResultFamily assertion. Explicit family selection must
                    # preserve the same native Result boundary as inference.
                    # Other source representations retain their own contracts.
                    condition += f' and (({payload} == Result[downcast[{payload}, _ResultType].Value, downcast[Self.Value, _ResultType].Error]) if conforms_to(Self.Value, _ResultType) else True)'
            # Native Result effects must keep their stored-error origins even
            # when the target family is explicit. A late family assertion is
            # insufficient on Mojo 1.1; compare the native shape at admission.
            # Probe the target's neutral carrier: non-Result targets must not
            # require a generic callback's opaque return type to be resolved.
            effect='R' if native else callable_metadata('borrow' if borrowing else 'owned', cb).result
            condition += f' and _CarrierCompatible[{target}, {effect}]'
            if discard and not retained_error:
                condition += f' and {target}._LoopCompatible[{source}, {cb}, {rule}]'
            else:
                condition += f' and {family}.TargetCompatible[G, {source}, {callback}]'
            if mode=='piped': result=f'Piped[{result}]';call=f'Piped({call})'
            indent='' if mode=='free' else '    '
            args=', '.join(x for x in (('var source: V', arg) if mode=='free' else ('deinit self', arg)) if x)
            summary=operation.summary
            out.append(f'''\n{indent}def {name}[{', '.join(params)}]({args}) raises {raised} -> {result} where {condition}:
{indent}    """{summary}"""
{indent}    return {call}
''')
    if mode == 'free':
        out.append(free_traverse())
    if mode == 'iter':
        out.append(pointer_methods())
        from generate_pipeline_syntax import algebra_methods
        out.append(algebra_methods(iteration=True))
    return document_first_methods(''.join(out))
