"""Native boundaries for shared effectful folds and conditional composition."""
from itertools import product
from combinator_docs import document_first_methods
from native_signatures import MD, callable_protocol, callable_metadata, native_adapter, admissions, closure, source_default, split_explicit, error_probe, probed
from operation_specs import EFFECT_REDUCTIONS, EffectChoice

START = '# --- effect syntax (generated) ---\n'
END = '# --- end effect syntax ---\n'
HEADER = '# Generated by scripts/generate_effect_syntax.py; execution lives in algebra._effect_combinators.\n'
ELEMENT = '_Source[V].Element'


def variants(mode, operation, elements, *, error):
    """Iter and Piped keep their kinds; free calls are value-first and take
    every callback form from the shared catalog, keeping the public parameter
    names (F for native callbacks, C for borrowing library callbacks, A or P
    for inputs, B for a fold element)."""
    if mode != 'free':
        return [(kind, None) for kind in ('library', 'pure', 'raising')]
    borrowing = operation.mode == 'borrow'
    names = {'X': error, 'C': 'F', 'L': 'C' if borrowing else 'F'}
    names.update({'in0': 'A0', 'in1': 'B'} if operation.mode == 'binary' else {'in0': 'P' if borrowing else 'A'})
    return [('catalog', form) for form in admissions(
        operation.mode, elements, view=False, repeatable=borrowing, names=names)]


def _probe_contract(kind, factory, form, mode, callback, contract, raised, condition):
    """Spell a raising native callback's contract error through a probe.

    Mojo does not reduce the contract's error alias for a stored native
    callback, chiefly a plain function's, so the declared error, its
    admission and the execution use the probe spelling; the body asserts both
    spellings agree. Library callbacks and non-raising forms are unchanged.
    """
    native = factory if kind == 'catalog' else form
    if native is None or not native.raising or native.kind == 'library':
        return '', raised, condition
    inputs = tuple('NoneType' for _ in native.inputs) if native.kind == 'thin' else native.inputs
    if mode == 'binary' and native.kind == 'thin':
        inputs = native.inputs
    probe = error_probe(mode, inputs, native.result, native.error)
    spelled, assertion = probed(raised, callback, probe)
    return assertion, spelled, condition.replace(raised, spelled)


def folds(mode, array=False):
    out = []
    for name in ('fold_effect', 'any_effect', 'all_effect'):
        operation = EFFECT_REDUCTIONS[name]
        fold = operation.seeded
        element = f'downcast[{ELEMENT}, {MD}]'
        for kind, factory in variants(mode, operation, ['A', element] if fold else [ELEMENT], error='X' if fold else 'E'):
            native = kind in ('pure', 'raising')
            params = []
            if kind == 'catalog':
                # Value-first: the accumulator comes from initial, the element from the source.
                params = ([f'A: {MD}'] if fold else []) + list(factory.parameters)
                cb, build, arg = factory.type, factory.build, factory.argument
                # Plans name the callback's own inputs; where relates them to the source.
                elem = factory.inputs[1] if fold else f'downcast[{factory.inputs[0]}, {MD}]'
                effect = factory.result
                if factory.kind == 'library':
                    metadata = callable_metadata(operation.mode, cb)
            elif native:
                # Iter and Piped closures come from the shared catalog.
                form = closure(operation.mode, kind == 'raising', names=(
                    {'C': 'F', 'X': 'X', 'in0': 'A', 'in1': 'B'} if fold else {'C': 'F', 'X': 'E', 'in0': 'P'}))
                params = list(form.parameters)
                error = form.error
                elem = 'B' if fold else f'downcast[P, {MD}]'
                cb, build, arg = form.type, form.build, form.argument
                effect = 'R'
            else:
                params = [f'F: {callable_protocol("binary")} & {MD}' if fold else f'C: {callable_protocol("borrow", repeatable=True)}']
                cb = 'F' if fold else 'C'
                metadata = callable_metadata(operation.mode, cb)
                elem = metadata.inputs[1] if fold else f'downcast[{metadata.inputs[0]}, {MD}]'
                build, arg = 'function^', f'var function: {cb}'
                effect = metadata.result
            acc = ('A' if kind != 'library' else metadata.inputs[0]) if fold else 'Bool'
            initial = 'initial^'
            if kind == 'catalog' and fold:
                # initial is typed A; the callback's first input is related to it in where.
                acc = factory.inputs[0]
                initial = 'initial^' if acc == 'A' else f'rebind_var[{acc}](initial^)'
            if mode == 'free': params += [f'V: {MD}']
            if array: params += ['N: Int']
            if mode in ('free', 'piped', 'iter'):
                # The target Monad defaults to the callback result's family; the
                # callback parameters after it default to their own bounds.
                explicit = factory.explicit if kind == 'catalog' else form.explicit if native else ()
                lead, trail = split_explicit(explicit)
                params += [*lead, '//', 'G: Monad = ' + source_default('Monad', effect), *trail]
            else:
                params += ['//', 'G: Monad']
                if kind == 'catalog': params += list(factory.explicit)
                if native: params += list(form.explicit)
            hint = 'Z' if fold else 'X'
            params += [f'{hint}: AnyType = _InferError']
            source = 'V' if mode == 'free' else 'Self.I' if mode == 'iter' else 'Self.Value'
            value = 'source^' if mode == 'free' else 'self._iterator^' if mode == 'iter' else 'self.value^'
            condition = f'_Source[{source}].Element == {elem}'
            if array:
                condition = f'Self.Value == Array[{elem}, N]'
                source = f'List[{elem}]'
                value = f'_take_array(rebind_var[Array[{elem}, N]]({value}))'
            plan = operation.bind('G', source, elem, cb, build, effect,
                                  accumulator=acc, initial=initial)
            contract = plan.contract
            error = f'{contract}.Error'
            raised = f'_EntryError[{hint}, {error}]'
            condition = (condition + ' and ' if array else '') + f'{contract}.Compatible'
            condition += f' and _ErrorCompatible[{raised}, {error}]'
            if kind == 'catalog':
                relations = list(factory.conditions)
                if factory.kind == 'library' and fold:
                    relations.append(f'{metadata.inputs[0]} == A')
                condition = ' and '.join([*relations, condition])
            result = f'{contract}.Out'
            assertion, raised, condition = _probe_contract(kind, factory, form if native else None, operation.mode, cb, contract, raised, condition)
            call = plan.invoke(raised, value)
            if mode == 'free':
                args = ['var source: V'] + (['var initial: A'] if fold else []) + [arg]
            else:
                args = ['deinit self', arg] + ([f'var initial: {acc}'] if fold else [])
            if mode == 'piped': result, call = f'Piped[{result}]', f'Piped({call})'
            indent = '' if mode == 'free' else '    '
            doc = ('Fold in order with an effectful accumulator step; empty input returns the initial value in the effect.' if fold else
                   'Test elements with an effectful borrowing predicate, stopping each branch at its decisive Bool result.')
            prelude = f'{indent}    {assertion}\n' if assertion else ''
            out.append(f'\n{indent}def {name}[{", ".join(params)}]({", ".join(args)}) raises {raised} -> {result} where {condition}:\n{indent}    """{doc}"""\n{prelude}{indent}    return {call}\n')
    return document_first_methods(''.join(out))


def conditional(mode, family=None):
    out = []
    sides = [[(kind, None) for kind in ('library', 'pure', 'raising')] for _ in range(2)]
    if mode == 'free':
        # Value-first: both factories take every form from the shared catalog.
        sides = [[('catalog', form) for form in admissions('thunk', [], arg=label, names=names)]
                 for label, names in (('on_true', {'C': 'L', 'R': 'U', 'X': 'Y', 'o': 'o'}),
                                      ('on_false', {'C': 'R', 'R': 'W', 'X': 'D', 'o': 'q'}))]
    for (left, left_factory), (right, right_factory) in product(*sides):
        # A plain function beside a closure keeps the borrowed pair.
        kinds = {getattr(left_factory, 'kind', left), getattr(right_factory, 'kind', right)}
        if 'closure' in kinds and 'thin' in kinds:
            continue
        params, explicit, args, types, values, results, errors, guards = [], [], [], [], [], [], [], []
        for kind, factory, label, typ, result, error, origin in ((left, left_factory, 'on_true', 'L', 'U', 'Y', 'o'), (right, right_factory, 'on_false', 'R', 'W', 'D', 'q')):
            if kind == 'catalog':
                params += list(factory.parameters)
                explicit += list(factory.explicit)
                args += [factory.argument]
                types.append(factory.type); values.append(factory.build); results.append(factory.result)
                errors.append(factory.error)
                guards += factory.conditions
            elif kind == 'library':
                params += [f'{typ}: {callable_protocol("thunk")} & {MD}']
                args += [f'var {label}: {typ}']
                types.append(typ); values.append(label+'^'); results.append(typ+'.Out'); errors.append(typ+'.Error')
            else:
                form = closure('thunk', kind == 'raising', arg=label,
                               names={'C': typ, 'R': result, 'X': error, 'o': origin})
                params += list(form.parameters)
                errors.append(form.error)
                explicit += list(form.explicit)
                types.append(form.type); values.append(form.build); results.append(result)
                args += [form.argument]
        if mode == 'free': params += [f'V: {MD}']
        if family == 'Result': params += [f'Failure: {MD}']
        g = f'ResultFamily[Self.E]' if mode == 'result' else f'ResultFamily[Failure]' if family == 'Result' else family+'Family' if family else 'G'
        if mode in ('free', 'piped') and not family:
            # The condition's family is the default; the factory parameters follow it.
            source_value = 'V' if mode == 'free' else 'Self.Value'
            lead, trail = split_explicit(explicit)
            params += [*lead, '//', 'G: Monad = ' + source_default('Monad', source_value), *trail, 'X: AnyType = _InferError']
        else:
            params += ['//']
            if not family and mode != 'result': params += ['G: Monad']
            params += explicit + ['X: AnyType = _InferError']
        source = 'V' if mode == 'free' else 'Result[Self.T, Self.E]' if mode == 'result' else f'Result[Bool, Failure]' if family == 'Result' else f'{family}[Bool]' if family else 'Self.Value'
        value = 'condition^' if mode == 'free' else 'self^' if mode == 'result' else f'rebind_var[{source}](self.value^)' if family else 'self.value^'
        # Spell native error evidence directly, as the algebra entry points do.
        # A generic caller cannot reduce the continuation's associated Error.
        plan = EffectChoice(g, source, *types, *results, *errors)
        actual = plan.error
        raised = f'_EntryError[X, {actual}]'
        result = plan.result
        cond = 'Self.T == Bool' if mode == 'result' else f'Self.Value == {source}' if family else f'{g}.Element[{source}] == Bool'
        cond += f' and {g}.Element[{results[0]}] == {g}.Element[{results[1]}] and _ErrorCompatible[{raised}, {actual}]'
        for effect in [source] + results:
            cond += f' and _CarrierCompatible[{g}, {effect}]'
        cond = ' and '.join([*guards, cond])
        # Preserve legacy generic admission; the complete contract remains
        # available to wrappers and selected pipelines.
        if getattr(left_factory, 'kind', left) == getattr(right_factory, 'kind', right) == 'library':
            actual = plan.contract + '.Error'
            raised = f'_EntryError[X, {actual}]'
            result = plan.contract + '.Out'
            source_binding = ('Self.T == Bool and ' if mode == 'result' else
                              f'Self.Value == {source} and ' if family else '')
            cond = (source_binding + plan.contract + '.ShapeCompatible'
                    + f' and _ErrorCompatible[{raised}, {actual}]')
        call = plan.invoke(raised, value, *values)
        if mode == 'piped': result, call = f'Piped[{result}]', f'Piped({call})'
        args.insert(0, 'var condition: V' if mode == 'free' else 'deinit self')
        indent = '' if mode == 'free' else '    '
        out.append(f'\n{indent}def if_effect[{", ".join(params)}]({", ".join(args)}) raises {raised} -> {result} where {cond}:\n{indent}    """Run the factory selected by an effectful Bool, skipping both factories on failure or absence."""\n{indent}    return {call}\n')
    return document_first_methods(''.join(out))


def methods(mode):
    if mode == 'result': return conditional(mode)
    if mode == 'conditional': return conditional('free')
    out = folds(mode) + searches(mode)
    if mode == 'piped':
        # Native carriers infer their family through the generic conditional.
        out += folds(mode, True) + searches(mode, True) + conditional(mode)
    return out


def searches(mode, array=False):
    out=[]
    for name in ('find_effect','find_map_effect','fold_map_effect'):
        operation = EFFECT_REDUCTIONS[name]
        borrowing, folding = operation.borrowing, operation.mapped
        element = ELEMENT if borrowing else f'downcast[{ELEMENT}, {MD}]'
        for kind, factory in variants(mode, operation, [element], error='E'):
            native=kind in ('pure','raising'); error='E' if kind=='raising' else 'Never'
            if kind=='catalog':
                params=list(factory.parameters)
                cb,build,arg=factory.type,factory.build,factory.argument
                elem=f'downcast[{factory.inputs[0]}, {MD}]' if borrowing else factory.inputs[0]
                effect,fe=factory.result,factory.error
                if factory.kind=='library':
                    metadata=callable_metadata(operation.mode, cb)
            elif native:
                form=closure(operation.mode, kind=='raising', names={'C': 'F', 'X': 'E', 'in0': 'P' if borrowing else 'A'})
                params=list(form.parameters)
                elem=f'downcast[P, {MD}]' if borrowing else 'A'
                cb,build,arg=form.type,form.build,form.argument;effect='R';fe=error
            else:
                params=[f'C: {callable_protocol("borrow", repeatable=True)}'] if borrowing else [f'F: {callable_protocol("owned")} & {MD}']
                cb='C' if borrowing else 'F';build='function^';arg=f'var function: {cb}'
                metadata=callable_metadata(operation.mode, cb)
                elem=f'downcast[{metadata.inputs[0]}, {MD}]' if borrowing else metadata.inputs[0]
                effect=metadata.result;fe=metadata.error
            if mode=='free':params+=[f'V: {MD}']
            if array:params+=['N: Int']
            if mode in ('free','piped','iter'):
                # The Monoid cannot be inferred, so it precedes the defaulted target.
                explicit=factory.explicit if kind=='catalog' else form.explicit if native else ()
                lead,trail=split_explicit(explicit)
                params+=[*lead,'//']+(['M: Monoid'] if folding else [])+['G: Monad = '+source_default('Monad', effect), *trail]
            else:
                params+=['//','G: Monad']+(['M: Monoid'] if folding else [])
                if kind=='catalog':params+=list(factory.explicit)
                if native:params+=list(form.explicit)
            params+=['X: AnyType = _InferError']
            source='V' if mode=='free' else 'Self.I' if mode=='iter' else 'Self.Value'
            value='source^' if mode=='free' else 'self._iterator^' if mode=='iter' else 'self.value^'
            condition=f'_Source[{source}].Element == {elem}'
            if array:
                condition=f'Self.Value == Array[{elem}, N]';source=f'List[{elem}]'
                value=f'_take_array(rebind_var[Array[{elem}, N]]({value}))'
            plan = operation.bind('G', source, elem, cb, build, effect,
                                  monoid='M' if folding else '',
                                  retained=f'_EffectRetain[{elem}, G, {cb}, True]' if borrowing else '')
            contract = plan.contract
            actual = contract + '.Error'
            raised=f'_EntryError[X, {actual}]'
            condition = (condition + ' and ' if array else '') + contract + '.Compatible'
            # Generic forwarding can prove the native callback error directly;
            # deferred families instead admit their construction error. The
            # shared fold boundary checks every actual family error.
            condition+=f' and (_ErrorCompatible[{raised}, {fe}] or _ErrorCompatible[{raised}, {actual}])'
            if kind=='catalog':condition=' and '.join([*factory.conditions, condition])
            if folding: condition+=f' and _ErrorCompatible[{raised}, M.Error]'
            assertion, raised, condition = _probe_contract(kind, factory, form if native else None, operation.mode, cb, contract, raised, condition)
            call = plan.invoke(raised, value)
            result = contract + '.Out'
            args=['var source: V', arg] if mode=='free' else ['deinit self', arg]
            if mode=='piped':result=f'Piped[{result}]';call=f'Piped({call})'
            ind='' if mode=='free' else '    '
            summary={'find_effect':'Find the first original element selected by an effectful borrowing predicate in each live branch.','find_map_effect':'Find the first present Optional produced inside the selected Monad in each live branch.','fold_map_effect':'Map each element into the selected Monad and combine its values in order with an explicit Monoid.'}[name]
            prelude=f'{ind}    {assertion}\n' if assertion else ''
            out.append(f'\n{ind}def {name}[{", ".join(params)}]({", ".join(args)}) raises {raised} -> {result} where {condition}:\n{ind}    """{summary}"""\n{prelude}{ind}    return {call}\n')
    return document_first_methods(''.join(out))
