"""Native Piped admission signatures, used by generate_plain_overloads.py.

The carrier table owns native type shapes, extra parameters and capabilities.
Operation templates own forwarding signatures; Mojo owns all execution. Keeping
this separate from the stage-count generator makes adding a derived operation
independent of the supported container count.
"""
import re
from dataclasses import dataclass
from combinator_docs import document_first_methods
from native_signatures import MD, callable_protocol, native_adapter, callback, closure, source_default, admissions, defaulted

START = '    # --- container methods (generated) ---\n'
END = '    # --- end container methods ---\n'
HEADER = '''    # Generated by scripts/generate_plain_overloads.py from
    # scripts/generate_pipeline_syntax.py. Edit the templates, not this block.
    # Native receiver signatures recover container parameters at admission.
    # Where clauses preserve origins; nominal checks precede rebinds because
    # Mojo 1.1 does not carry that evidence into bodies. Execution, callback
    # adaptation and construction remain in the algebra operations/families.
'''


@dataclass(frozen=True)
class Carrier:
    name: str
    shape: str
    family: str
    parameters: tuple[str, ...] = ()
    capabilities: frozenset[str] = frozenset({'map', 'filter', 'filter_map', 'fold'})

    def value(self, element):
        return self.shape.format(element=element)

    def instance(self, element):
        return self.family.format(element=element)


CARRIERS = (
    Carrier('List', 'List[{element}]', 'ListFamily', capabilities=frozenset({'map', 'filter', 'filter_map', 'fold', 'flat_map', 'traverse', 'combine'})),
    Carrier('Array', 'Array[{element}, N]', '_ArrayFamily[N]', ('N: Int',), frozenset({'map', 'fold'})),
    Carrier('Deque', 'Deque[{element}]', '_DequeFamily'),
    Carrier('LinkedList', 'LinkedList[{element}]', '_LinkedListFamily'),
    Carrier('Dict', 'Dict[K, {element}, H]', '_DictFamily[K, {element}, H]', ('K: KeyElement & Deinitable', 'H: Hasher & Defaultable & Deinitable')),
    Carrier('StringDict', 'StringDict[{element}]', '_StringDictFamily[{element}]'),
    Carrier('Optional', 'Optional[{element}]', 'OptionalFamily', capabilities=frozenset({'map', 'filter', 'filter_map', 'fold', 'flat_map', 'traverse', 'combine'})),
    Carrier('Result', 'Result[{element}, Failure]', 'ResultFamily[Failure]', (f'Failure: {MD}',), frozenset({'map', 'flat_map', 'traverse', 'combine'})),
)

# Carriers whose family _SourceFamily recognizes use the generic methods, whose
# family defaults to the carrier's; the others keep native carrier methods.
COLLAPSED = frozenset({'List', 'Optional', 'Deque', 'LinkedList', 'Result'})


def piped_family(trait, name='I'):
    """The Piped capability parameter, defaulting to the held value's family."""
    return f'{name}: {trait} = {source_default(trait, "Self.Value")}'


# Explicit element selection shares the native carrier shapes above. Non-empty
# lists use their existing family, whose filtering may change the carrier.
SEQUENCE_CARRIERS = tuple(c for c in CARRIERS if c.name in ('List', 'Array', 'Deque', 'LinkedList')) + (
    Carrier('NonEmptyList', 'NonEmptyList[{element}]', 'NonEmptyListFamily',
            capabilities=frozenset({'map', 'filter', 'filter_map', 'fold', 'traverse'})),
)


def forward(name, parameters, argument, result, source, operation, callback, doc, error='', condition=''):
    """Only native admission and nominal type recovery belong in this body."""
    effect = f' raises {error}' if error else ''
    where = condition or f'Self.Value == {source}'
    value = f'rebind_var[{source}](self.value^)'
    # Free operations are value-first; family primitives keep their own order.
    call = f'{operation}({value}, {callback})' if operation.startswith('_family_') else f'{operation}({callback}, {value})'
    return f'''
    def {name}[{', '.join(parameters)}](
        deinit self, {argument}
    ){effect} -> Piped[{result}] where {where}:
        """{doc}"""
        comptime assert Self.Value == {source}
        return Piped({call})
'''


def map_methods(carrier):
    out = []
    source, result, family = carrier.value('T'), carrier.value('U'), carrier.instance('T')
    for raising in (False, True):
        parameters = [f'T: {MD}', f'U: {MD}', *carrier.parameters, '//']
        parameters += closure('owned', raising, names={'C': 'F', 'X': 'E', 'in0': 'T', 'R': 'U'}).explicit
        operation = f'_family_map[{family}' + (', X=E]' if raising else ']')
        out.append(forward('map', parameters, 'ref function: F', result, source,
                           operation, 'function', f'Map {carrier.name} payloads immediately, preserving the native container.',
                           'E' if raising else ''))
    source, result, family = carrier.value('F.Arg'), carrier.value('F.Out'), carrier.instance('F.Arg')
    admission = f'Self.Value == {source}'
    # The exact native carrier and callback input are already fixed here.
    # Delegate to its primitive, as List does, without re-projecting those
    # types through the generic map entry's symbolic constraint.
    operation = f'{family}.map'
    if carrier.name == 'List':
        # This signature fixes the exact carrier/payload and receiver mode.
        # Forward to its primitive without re-projecting generic input types.
        admission += ' and RepeatableUnary[F]'
    else:
        # Forward the same family proof required by the generic map entry.
        admission += f' and _MapCompatible[{family}, {source}, F]'
    out.append(forward('map', [f'F: {callable_protocol("owned")} & {MD}', *carrier.parameters],
                       'var function: F', result, source, operation, 'function^',
                       f'Map {carrier.name} payloads with an owned library callback.', 'F.Error',
                       admission))
    source, result, family = carrier.value('F._View[o].Arg'), carrier.value('F._View[o].Out'), carrier.instance('F._View[o].Arg')
    out.append(forward('map', ['F: _UnaryViewable', 'o: ImmOrigin', *carrier.parameters],
                       'ref[o] function: F', result, source, f'_family_map[{family}]', 'function._unary_view()',
                       f'Map {carrier.name} payloads with a borrowed callable view.', 'F._View[o].Error'))
    return ''.join(out)


def filter_methods(carrier, name, description):
    out = []
    source, family = carrier.value('T'), carrier.instance('T')
    for raising in (False, True):
        parameters = [f'T: {MD}', f'R: {MD}', *carrier.parameters, '//']
        parameters += closure('borrow', raising, names={'C': 'F', 'X': 'E', 'in0': 'T'}).explicit
        operation = f'_family_{name}[{family}' + ']'
        out.append(forward(name, parameters, 'ref predicate: F', source, source,
                           operation, 'predicate', f'{description} {carrier.name} payloads immediately, preserving their container.',
                           'E' if raising else '', f'R == Bool and Self.Value == {source}'))
    for kind in ('library', 'view'):
        cb = callback('borrow', kind, 'predicate')
        parameters = [f'C: BorrowCallContract & {MD}'] if kind == 'library' else cb.parameters
        element = f'downcast[{cb.payload}, {MD}]'
        source, family = carrier.value(element), carrier.instance(element)
        condition = f'conforms_to({cb.payload}, {MD}) and Self.Value == {source} and {cb.result} == Bool'
        if kind == 'library':
            condition += ' and RepeatableBorrow[C]'
        receiver = 'an owned' if kind == 'library' else 'a shared'
        out.append(forward(name, [*parameters, *carrier.parameters], cb.argument, source, source,
                           f'_family_{name}[{family}]', cb.build, f'{description} {carrier.name} payloads with {receiver} library predicate.',
                           cb.error, condition))
    return ''.join(out)


def container_methods():
    from generate_error_syntax import methods as error_methods
    from generate_sequencing_syntax import methods as sequencing_methods
    from generate_combinator_syntax import terminal_methods
    from generate_traversal_syntax import methods as traversal_methods
    from generate_applicative_syntax import methods as combine_methods
    from generate_nary_syntax import methods as nary_methods
    # A collapsed carrier keeps only the methods without a generic twin: the
    # parallel traversals, discarding traversals and the terminals.
    native = tuple(c for c in CARRIERS if c.name not in COLLAPSED)
    out = []
    out.append(error_methods())
    out.append(sequencing_methods())
    for carrier in native:
        if 'flat_map' in carrier.capabilities:
            out.append(sequencing_methods(carrier))
    for carrier in native:
        if 'map' in carrier.capabilities:
            out.append(map_methods(carrier))
    for name, description in (('filter', 'Retain accepted'), ('filter_not', 'Retain rejected')):
        for carrier in native:
            if 'filter' in carrier.capabilities:
                out.append(filter_methods(carrier, name, description))
    out.extend((transform_methods(), observe_methods(), algebra_methods(), plain_methods(), combine_methods(), nary_methods(explicit=True), nary_methods(), nary_methods(parallel=True)))
    for carrier in native:
        if "combine" in carrier.capabilities:
            out.append(combine_methods(carrier))
    for carrier in CARRIERS:
        if 'map' not in carrier.capabilities:
            continue
        if carrier.name in COLLAPSED:
            out.append(algebra_methods(carrier, parallel_only=True))
        else:
            out.extend((transform_methods(carrier), observe_methods(carrier), algebra_methods(carrier)))
    for carrier in CARRIERS:
        if 'fold' in carrier.capabilities:
            out.append(terminal_methods('piped', carrier))
    out.append(traversal_methods('piped'))
    for carrier in CARRIERS:
        out.append(traversal_methods('piped', carrier, discard_only=carrier.name in COLLAPSED))
    return document_first_methods(''.join(out) + '\n')


def plain_methods():
    """Owned plain-function forms of the generic capability methods.

    A plain function is copied into an owned NativeUnary, so a deferred family
    such as IO can keep it, as the free operations do. Each error is named
    through the probe so a defaulted family's error reduces.
    """
    out = []
    for name, trait, result_alias, error_alias, admission in (
        ('map', 'Functor', 'Mapped', 'MapError', '_MapCompatible[I, Self.Value, {D}]'),
        ('flat_map', 'Monad', 'Bound', 'BindError', '_BindCompatible[I, Self.Value, {D}]'),
        ('filter_map', 'FunctorFilter', 'MapFiltered', 'MapFilterError', ''),
        ('traverse', 'Traversable', 'Traversed', 'TraverseError', 'I.TargetCompatible[G, Self.Value, {D}]'),
    ):
        traverse = name == 'traverse'
        for form in admissions('owned', ['I.Element[Self.Value]'], library=False, view=False,
                               names={'X': 'E', 'C': 'F', 'in0': 'A'}):
            if form.kind != 'thin':
                continue
            D = form.type
            families = ([f'G: Applicative = _InferredApplicative[{form.result}]'] if traverse else []) + [piped_family(trait)]
            shape = 'G, Self.Value, {}' if traverse else 'Self.Value, {}'
            probe = f'_ErrorProbe[NoneType, {form.result}, {form.error}]'
            raised = f'I.{error_alias}[{shape.format(probe)}]'
            result = f'I.{result_alias}[{shape.format(D)}]'
            guards = [*form.conditions] + ([admission.format(D=D)] if admission else [])
            where = f' where {" and ".join(guards)}' if guards else ''
            entry = (f'_traverse_as[I, G, Self.Value, {D}, {raised}]' if traverse else
                     {'map': '_map_as', 'flat_map': '_flat_map_as', 'filter_map': '_filter_map_as'}[name] + f'[{raised}, I]')
            out.append(f'''
    def {name}[{', '.join([*form.parameters, '//', *families])}](deinit self, {form.argument}) raises {raised} -> Piped[{result}]{where}:
        """Apply {name} with a plain function, copied so deferred families can keep it."""
        comptime assert I.{error_alias}[{shape.format(D)}] == {raised}
        return Piped({entry}({form.build}, self.value^))
''')
    return ''.join(out)


# Each transformation has one callback implementation. These are only native
# admission signatures; explicit families and Iter use the same callbacks.
TRANSFORMS = (
    ('fill', 'T: Movable & Deinitable', ('U: Movable & Deinitable',),
     'var value: U', 'U', '_Fill[T, U]', 'value^', 'Replace payloads with value, moving it for a single call or copying for repeated calls.'),
    ('replace', 'T: Copyable & Equatable & Deinitable', (),
     'var old: T, var new: T', 'T', '_Replace[T]', 'old^, new^', 'Replace equal payloads, moving unmatched values unchanged.'),
    ('void', 'T: Movable & Deinitable', (),
     '', 'NoneType', '_Fill[T, NoneType]', 'None', 'Discard payloads while preserving their container shape.'),
    ('tuple_left', 'T: Movable & Deinitable', ('U: Movable & Deinitable',),
     'var value: U', 'Tuple[U, T]', '_TupleWith[T, U, True]', 'value^', 'Attach value on the left, moving it for a single call or copying for repeated calls.'),
    ('tuple_right', 'T: Movable & Deinitable', ('U: Movable & Deinitable',),
     'var value: U', 'Tuple[T, U]', '_TupleWith[T, U, False]', 'value^', 'Attach value on the right, moving it for a single call or copying for repeated calls.'),
)


def transform_methods(carrier=None):
    out = []
    for name, bound, extra, argument, element, callback, args, doc in TRANSFORMS:
        if not carrier:
            # The element comes from the defaulted family; a separate T could
            # only be related in where, which Mojo does not infer from.
            traits = bound.split(': ', 1)[1]
            payload = f'downcast[I.Element[Self.Value], {traits}]'
            argument, element, callback = (re.sub(r'\bT\b', payload, x) for x in (argument, element, callback))
            bound = None
        params = [*([bound] if bound else []), *extra, *(carrier.parameters if carrier else ('//', piped_family('Functor')))]
        if params[0] == '//': params = params[1:]
        source = carrier.value('T') if carrier else 'Self.Value'
        family = carrier.instance('T') if carrier else 'I'
        result = carrier.value(element) if carrier else f'I.Mapped[Self.Value, {callback}]'
        condition = f'Self.Value == {source}' if carrier else f'conforms_to(I.Element[Self.Value], {traits})'
        if not carrier: condition += f' and _MapCompatible[I, Self.Value, {callback}]'
        elif name in ('fill', 'tuple_left', 'tuple_right'):
            # The callback's shared receiver exists only for Copyable constants.
            # Let each native family's existing map policy admit repetition.
            condition += f' and _MapCompatible[{family}, {source}, {callback}]'
        effect = '' if carrier else f' raises I.MapError[Self.Value, {callback}]'
        nominal = f'        comptime assert Self.Value == {source}\n' if carrier else ''
        value = f'rebind_var[{source}](self.value^)' if carrier else 'self.value^'
        arg = ', ' + argument if argument else ''
        out.append(f'''
    def {name}[{', '.join(params)}](deinit self{arg}){effect} -> Piped[{result}] where {condition}:
        """{doc}"""
{nominal}        return Piped({family}.map({callback}({args}), {value}))
''')
    return ''.join(out)


def observe_methods(carrier=None):
    out = []
    for name, paired in (('pair_with', 'True'), ('tap_each', 'False')):
        for kind in ('pure', 'raising', 'library'):
            native = kind != 'library'
            # Native borrowing admits AnyType; only the retained carrier payload
            # needs the movable witness. Choose both spellings before rendering
            # so the native adapter never receives the downcast payload type.
            payload = f'downcast[P, {MD}]' if native else 'T'
            projected = 'R' if native else 'C.Result'
            element = f'Tuple[{payload}, {projected}]' if paired == 'True' else payload
            params = ['P: AnyType' if native else f'T: {MD}']
            if native:
                params += [f'R: {MD}', *(carrier.parameters if carrier else ()), 'o: ImmOrigin']
                form = closure('borrow', kind == 'raising', names={'C': 'F', 'X': 'E', 'in0': 'P'})
                if carrier:
                    params += ['//', *form.explicit]
                else:
                    # The family defaults; the callback parameters follow it.
                    params += ['//', piped_family('Functor'), *defaulted(form.explicit)]
                error, bridge, arg, build = form.error, form.type, form.argument, form.build
            else:
                params += [f'C: {callable_protocol("borrow")} & {MD}', *(carrier.parameters if carrier else ('//', piped_family('Functor')))]
                error, bridge, arg, build = 'C.Failure', 'C', 'var function: C', 'function^'
            source = carrier.value(payload) if carrier else 'Self.Value'
            family = carrier.instance(payload) if carrier else 'I'
            callback = f'_Observe[{payload}, {bridge}, {paired}]'
            result = carrier.value(element) if carrier else f'I.Mapped[Self.Value, {callback}]'
            effect = error if carrier else f'I.MapError[Self.Value, {callback}]'
            condition = f'Self.Value == {source}' if carrier else f'I.Element[Self.Value] == {payload}'
            if not carrier: condition += f' and _MapCompatible[I, Self.Value, {callback}]'
            if not native:
                condition += ' and C.Payload == T and RepeatableBorrow[C]'
            nominal = f'        comptime assert Self.Value == {source}\n' if carrier else ''
            value = f'rebind_var[{source}](self.value^)' if carrier else 'self.value^'
            call = f'{family}.map({callback}({build}), {value})'
            if not carrier and kind == 'raising':
                # A defaulted family's error must reduce in the raises clause:
                # name it through the probe, as the free map does.
                probe = f'_ErrorProbe[{payload}, {element}, {error}]'
                effect = f'I.MapError[Self.Value, {probe}]'
                nominal = f'        comptime assert I.MapError[Self.Value, {callback}] == {effect}\n'
                call = f'_map_as[{effect}, I]({callback}({build}), {value})'
            out.append(f'''
    def {name}[{', '.join(params)}](deinit self, {arg}) raises {effect} -> Piped[{result}] where {condition}:
        """Borrow each payload for {'projection and retain it beside the result' if paired == 'True' else 'inspection and retain it unchanged'}."""
{nominal}        return Piped({call})
''')
    return ''.join(out)


def algebra_methods(carrier=None, *, iteration=False, parallel_only=False):
    """Expose the existing capability operations, with one native bridge shape."""
    out = []
    for name, trait, result_alias, error_alias in (
        ('filter_map', 'FunctorFilter', 'MapFiltered', 'MapFilterError'),
        ('flat_map', 'Monad', 'Bound', 'BindError'),
        ('traverse', 'Traversable', 'Traversed', 'TraverseError'),
        ('par_traverse', 'Traversable', 'Traversed', 'TraverseError'),
    ):
        parallel = name == 'par_traverse'
        if parallel_only and not parallel: continue
        if iteration and not parallel: continue
        if parallel and not carrier and not iteration: continue
        operation = 'traverse' if parallel else name
        if carrier and operation not in carrier.capabilities:
            continue
        for kind in ('pure', 'raising', 'library', 'view'):
            native = kind in ('pure', 'raising')
            params = ([f'A: {MD}', f'R: {MD}', 'o: ImmOrigin'] if native else
                      ['F: _UnaryViewable', 'o: ImmOrigin'] if kind == 'view' else [f'F: {callable_protocol("owned")} & {MD}'])
            params += list(carrier.parameters if carrier else ()) + ['//']
            if not carrier and not iteration:
                params.append(f'I: {trait}')
            if parallel:
                target = 'R' if native else 'F._View[o].Out' if kind == 'view' else 'F.Out'
                params.append(f'S: Semigroup = _ListErrors[{target}]')
            elif name == 'traverse':
                params.append('G: Applicative')
            error = 'E' if kind == 'raising' else 'Never'
            if native:
                form = closure('owned', kind == 'raising', names={'C': 'F', 'X': 'E', 'in0': 'A'})
                params += list(form.explicit)
            generic = not carrier and not iteration and not parallel
            if generic:
                # Families default: the source to the held value's, a traverse
                # target to the callback result's. Callback parameters follow.
                fixed = [p for p in params if p == '//' or p.startswith(('I:', 'G:'))]
                explicit = list(form.explicit) if native else []
                params = [p for p in params if p not in fixed and p not in explicit]
                target = ('_ViewTarget[F, o]' if kind == 'view' else
                          f'_InferredApplicative[{"R" if native else "F.Out"}]')
                params += ['//'] + ([f'G: Applicative = {target}'] if operation == 'traverse' else []) + [piped_family(trait)] + defaulted(explicit)
            if parallel:
                params = [p for p in params if p != '//' and not p.startswith('S:')] + ['//', f'S: Semigroup = _ListErrors[{target}]']
            elem = 'A' if native else 'F._View[o].Arg' if kind == 'view' else 'F.Arg'
            source = carrier.value(elem) if carrier else 'Self.I' if iteration else 'Self.Value'
            family = carrier.instance(elem) if carrier else 'ListFamily' if iteration else 'I'
            callback = form.type if native else 'F._View[o]' if kind == 'view' else 'F'
            build = form.build if native else 'function._unary_view()' if kind == 'view' else 'function^'
            target_family = 'ValidationFamily[S]' if parallel else 'G'
            args = f'{target_family}, {source}, {callback}' if operation == 'traverse' else f'{source}, {callback}'
            result = f'{family}.{result_alias}[{args}]'
            raised = f'{family}.{error_alias}[{args}]'
            condition = f'Self.Value == {source}' if carrier else f'I.Element[Self.Value] == {elem}'
            if iteration: condition = f'Self.I.Element == {elem}'
            if operation == 'flat_map' and not carrier:
                condition += f' and _BindCompatible[{family}, {source}, {callback}]'
            if operation == 'traverse':
                condition += f' and {family}.TargetCompatible[{target_family}, {source}, {callback}]'
            if parallel: condition += f' and _CarrierCompatible[{target_family}, {target}]'
            nominal = f'        comptime assert Self.Value == {source}\n' if carrier else ''
            value = f'rebind_var[{source}](self.value^)' if carrier else 'self._iterator^' if iteration else 'self.value^'
            call = f'{family}.{operation}' + (f'[{target_family}]' if operation == 'traverse' else '')
            expr = f'{call}({build}, {value})'
            if generic and kind == 'raising':
                # Name a defaulted family's error through the probe so it reduces.
                probe_args = args.replace(callback, '_ErrorProbe[A, R, E]')
                actual = raised
                raised = f'{family}.{error_alias}[{probe_args}]'
                nominal = f'        comptime assert {actual} == {raised}\n'
                bridge = {'filter_map': f'_filter_map_as[{raised}, I]', 'flat_map': f'_flat_map_as[{raised}, I]',
                          'traverse': f'_traverse_as[I, G, Self.Value, {callback}, {raised}]'}[operation]
                expr = f'{bridge}({build}, {value})'
            result = result if iteration else f'Piped[{result}]'
            expr = expr if iteration else f'Piped({expr})'
            out.append(f'''
    def {name}[{', '.join(params)}](deinit self, {'ref[o] function: F' if native or kind == 'view' else 'var function: F'}) raises {raised} -> {result} where {condition}:
        """Apply {name} through the carrier's {trait} capability."""
{nominal}        return {expr}
''')
    for name, trait, operation, result_alias, error_alias in (
        ('compact', 'FunctorFilter', 'filter_map', 'MapFiltered', 'MapFilterError'),
        ('flatten', 'Monad', 'flat_map', 'Bound', 'BindError'),
        ('sequence', 'Traversable', 'traverse', 'Traversed', 'TraverseError'),
        ('par_sequence', 'Traversable', 'traverse', 'Traversed', 'TraverseError'),
    ):
        parallel = name == 'par_sequence'
        if parallel_only and not parallel: continue
        if iteration and not parallel: continue
        if parallel and not carrier and not iteration: continue
        if carrier and operation not in carrier.capabilities:
            continue
        params = ([f'T: {MD}', *carrier.parameters, '//'] if carrier else [] if iteration else [piped_family(trait)])
        if name == 'sequence':
            if carrier or iteration:
                params.append('G: Applicative')
            else:
                # Target first: it defaults to the family of the held elements.
                element = f'downcast[{source_default("Traversable", "Self.Value")}.Element[Self.Value], {MD}]'
                params.insert(0, f'G: Applicative = _InferredApplicative[{element}]')
        elem = ('Optional[T]' if name == 'compact' else carrier.value('T') if name == 'flatten' else 'T') if carrier else 'I.Element[Self.Value]'
        if iteration: elem = f'downcast[Self.I.Element, {MD}]'
        if parallel: params.append(f'S: Semigroup = _ListErrors[{elem}]')
        source = carrier.value(elem) if carrier else 'Self.I' if iteration else 'Self.Value'
        family = carrier.instance(elem) if carrier else 'ListFamily' if iteration else 'I'
        cb = f'_Same[{elem}]'
        target_family = 'ValidationFamily[S]' if parallel else 'G'
        args = f'{target_family}, {source}, {cb}' if operation == 'traverse' else f'{source}, {cb}'
        condition = f' where Self.Value == {source}' if carrier else ''
        if iteration: condition = f' where Self.I.Element == {elem}'
        if operation == 'flat_map' and not carrier:
            condition += (' and ' if condition else ' where ') + f'_BindCompatible[{family}, {source}, {cb}]'
        if operation == 'traverse':
            condition += (' and ' if condition else ' where ') + f'{family}.TargetCompatible[{target_family}, {source}, {cb}]'
        if parallel: condition += f' and _CarrierCompatible[{target_family}, {elem}]'
        nominal = f'        comptime assert Self.Value == {source}\n' if carrier else ''
        value = f'rebind_var[{source}](self.value^)' if carrier else 'self._iterator^' if iteration else 'self.value^'
        call = f'{family}.{operation}' + (f'[{target_family}]' if operation == 'traverse' else '')
        result = f'{family}.{result_alias}[{args}]'
        raised = f'{family}.{error_alias}[{args}]'
        expr = f'{call}({cb}(), {value})'
        if parallel:
            # Identity cannot raise. Only multi-element sources can invoke S;
            # spell that exact effect at the native boundary for generic callers.
            # The shared traversal adapter checks the family's computed effect.
            raised = 'S.Error' if iteration or carrier.name == 'List' else 'Never'
            expr = f'_traverse_as[{family}, {target_family}, {source}, {cb}, {raised}]({cb}(), {value})'
        if not iteration:
            result, expr = f'Piped[{result}]', f'Piped({expr})'
        out.append(f'''
    def {name}[{', '.join(params)}](deinit self) raises {raised} -> {result}{condition}:
        """Derive {name} through {operation}, preserving the family's semantics."""
{nominal}        return {expr}
''')
    return ''.join(out)
