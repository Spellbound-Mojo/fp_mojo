MD = 'Movable & Deinitable'
MAX = 8
START = '# --- plain-function overloads (generated) ---\n'
END = '# --- end plain-function overloads ---\n'
MATCH_MAX = 16
MATCH_START = '# --- match overloads (generated) ---\n'
MATCH_END = '# --- end match overloads ---\n'
MATCH_HEADER = '''# Generated by scripts/generate_plain_overloads.py; edit the generator, not this
# block. A clause's signature is known only at a parameter of its function type,
# so each clause count spells one thin signature per clause. A clause's error is
# inferred as AnyType: under a value bound a pure function's error is not Never
# (see _NativeError). _Result<n> and _Error<n> spell the match's types over the
# clause types (see _match). The one-clause overload of each form carries the
# documentation.
'''
APPEND_START = '    # --- composition append admission (generated) ---\n'
APPEND_END = '    # --- end composition append admission ---\n'
APPEND_HEADER = '    # Native admission delegates to the same consuming append owner.\n'
HEADER = '''# Generated by scripts/generate_plain_overloads.py; edit the generator, not this
# block. A plain function's signature is known only at a parameter of its function
# type; a variadic pack keeps the type but not the signature, so a stage's result
# cannot be inferred from it. Each stage count therefore spells one thin
# signature per stage and delegates to the variadic form. Later stages name their
# own input type (P1, P2, ...), so a mismatched call reaches the per-stage check.
# Closures use as_unary.
'''


def stage(first_arity, index):
    """Thin signature and stored _ThinFunction type of stage `index`, in run order."""
    if index == 0 and first_arity == 0:
        return 'def() raises E0 thin -> A1', '_Thin0F[A1, E0]'
    if index == 0 and first_arity == 2:
        return 'def(var B0, var B1) raises E0 thin -> A1', '_Thin2F[B0, B1, A1, E0]'
    parameter = 'A0' if index == 0 else 'P%d' % index
    return ('def(var %s) raises E%d thin -> A%d' % (parameter, index, index + 1),
            '_Thin1F[%s, A%d, E%d]' % (parameter, index + 1, index))


def decls(n, first_arity):
    names = ['B0', 'B1'] if first_arity == 2 else []
    names += ['A%d' % i for i in range(0 if first_arity == 1 else 1, n + 1)]
    names += ['P%d' % i for i in range(1, n)]
    names += ['E%d' % i for i in range(n)]
    return ', '.join('%s: %s' % (name, MD) for name in names)


def common(n):
    error = 'E0'
    for i in range(1, n):
        error = '_CommonError[%s, E%d]' % (error, i)
    return error


def pipe_overloads():
    out = []
    for n in range(2, MAX + 1):
        params = ', '.join('f%d: %s' % (i, stage(1, i)[0]) for i in range(n))
        wrapped = ', '.join('%s(f%d)' % (stage(1, i)[1], i) for i in range(n))
        out.append('\n\ndef pipe[%s, //](\n    var value: A0, %s\n) raises %s -> A%d:\n'
                   '    """Apply %d plain functions in order."""\n    return pipe[E=%s](value^, %s)\n'
                   % (decls(n, 1), params, common(n), n, n, common(n), wrapped))
    return ''.join(out) + mixed_pipe_overloads()


def mixed_pipe_overloads():
    """Borrow a shared library stage beside one admitted native pointer."""
    out = []
    for native_first in (True, False):
        for factory in native_factories('owned', ['A'], error='X'):
            parameters = [('V', MD), *factory.parameters, ('F', 'Unary'), *factory.pointer.parameters]
            declarations = [f'{p}: {bound}' for p, bound in parameters] + ['//']
            arguments = [factory.argument, 'stage: F']
            types = [factory.adapter, 'F']
            values = [factory.adapter + '(function)', 'stage']
            if not native_first:
                arguments.reverse()
                types.reverse()
                values.reverse()
            plan = '_Plan[' + ', '.join(types) + ']'
            conditions = factory.pointer.conditions
            where = ' where ' + ' and '.join(conditions) if conditions else ''
            out.append(f'\n\ndef pipe[{", ".join(declarations)}](\n'
                       f'    var value: V, {", ".join(arguments)}\n'
                       f') raises {plan}.Failure -> {plan}.Result{where}:\n'
                       '    """Apply a plain function or stored pointer beside one borrowed library stage."""\n'
                       f'    return pipe(value^, {", ".join(values)})\n')
    return ''.join(out)


def composition_overloads():
    out = []
    for name, reverse in (('flow', False), ('compose', True)):
        for first_arity in (1, 0, 2):
            for n in range(2, MAX + 1):
                order = list(range(n))[::-1] if reverse else list(range(n))
                params = ', '.join('f%d: %s' % (i, stage(first_arity, i)[0]) for i in order)
                types = ', '.join(stage(first_arity, i)[1] for i in order)
                wrapped = ', '.join('%s(f%d)' % (stage(first_arity, i)[1], i) for i in order)
                direction = 'right to left' if reverse else 'left to right'
                out.append('\n\ndef %s[%s, //](\n    %s\n) -> Composition[%s, %d, %s]:\n'
                           '    """Store %d plain functions, applied %s."""\n    return %s(%s)\n'
                           % (name, decls(n, first_arity), params, reverse, first_arity, types,
                              n, direction, name, wrapped))
    return ''.join(out) + mixed_composition_overloads()


def mixed_composition_overloads():
    """Normalize one thin stage in a two-stage composition, then use its owner.

    The library stage keeps its receiver capabilities. A spelled native
    signature supplies the metadata that Mojo cannot recover from a type pack.
    Factory ABI evidence is shared with as_unary; no callback is executed here.
    """
    out = []
    for name, reverse in (('flow', False), ('compose', True)):
        for native_first, arities in ((True, (0, 1, 2)), (False, (1,))):
            for arity in arities:
                payloads = ['A', 'B'][:arity]
                mode = ('thunk', 'owned', 'binary')[arity]
                for factory in native_factories(mode, payloads):
                    parameters = [*factory.parameters, ('F', MD), *factory.pointer.parameters]
                    declarations = [f'{p}: {bound}' for p, bound in parameters] + ['//']
                    arguments = [factory.argument, 'var stage: F']
                    types = [factory.adapter, 'F']
                    values = [factory.adapter + '(function)', 'stage^']
                    if native_first == reverse:
                        arguments.reverse()
                        types.reverse()
                        values.reverse()
                    result = f'Composition[{reverse}, {arity if native_first else "_Arity[F]"}, {", ".join(types)}]'
                    conditions = ['_Once[F]', *factory.pointer.conditions]
                    out.append(f'\n\ndef {name}[{", ".join(declarations)}](\n'
                               f'    {", ".join(arguments)}\n) -> {result} where {" and ".join(conditions)}:\n'
                               '    """Compose a plain function or stored pointer with one library stage."""\n'
                               f'    return {result}({", ".join(values)})\n')
    return ''.join(out)


def composition_append_methods():
    out = []
    for factory in native_factories('owned', ['A']):
        declarations = [f'{p}: {bound}' for p, bound in (*factory.parameters, *factory.pointer.parameters)] + ['//']
        conditions = factory.pointer.conditions
        where = ' where ' + ' and '.join(conditions) if conditions else ''
        out.append(f'\n    def then[{", ".join(declarations)}](\n'
                   f'        deinit self, {factory.argument}\n'
                   f'    ) -> Self._WithNext[{factory.adapter}]{where}:\n'
                   '        """Append a plain function or stored pointer without invoking it."""\n'
                   f'        return self^.then({factory.adapter}(function))\n')
    return ''.join(out) + '\n'


