def clause_parts(form, n):
    """Type-parameter declarations, function parameters, result and error of `n` clauses."""
    letters = MATCH_FORMS[form]
    decls, functions = [], []
    for i in range(n):
        params = ['%s%d' % (letter, i) for letter in letters]
        decls.append(', '.join(['%s: AnyType' % p for p in params] + ['O%d: Value' % i, 'E%d: AnyType' % i]))
        functions.append('f%d: def(%s) raises E%d thin -> O%d' % (i, ', '.join(params), i, i))
    result = '_Result%d[%s]' % (n, ', '.join('O%d' % i for i in range(n)))
    error = '_Error%d[%s]' % (n, ', '.join('E%d' % i for i in range(n)))
    return decls, functions, result, error


def match_aliases():
    """The result and error of `n` clauses, spelled over the clause types."""
    out = []
    for n in range(1, MATCH_MAX + 1):
        result, error = '_NoResult', 'Never'
        for i in reversed(range(n)):
            result = '_Pick[O%d, %s]' % (i, result)
            error = '_CommonError[_NativeError[E%d], %s]' % (i, error)
        out.append('comptime _Result%d[%s]: Value = %s\n' % (n, ', '.join('O%d: Value' % i for i in range(n)), result))
        out.append('comptime _Error%d[%s]: Value = %s\n' % (n, ', '.join('E%d: AnyType' % i for i in range(n)), error))
    return '\n' + ''.join(out)


def match_overloads():
    out = [match_aliases()]
    for form in MATCH_FORMS:
        full, short = MATCH_DOCS[form]
        for n in range(1, MATCH_MAX + 1):
            decls, functions, result, error = clause_parts(form, n)
            push = '_Nil()'
            for i in reversed(range(n)):
                push = '_push%d(f%d, %s)' % (len(MATCH_FORMS[form]), i, push)
            subjects, leading, trailing, returns = 'subject: S', ['S: AnyType'], '', result
            if form == 'single':
                call = '_match[%s, %s](subject, %s, _Absent())' % (result, error, push)
            elif form == 'context':
                leading.append('X: AnyType')
                trailing = ',\n    *,\n    context: X'
                call = '_match[%s, %s](subject, %s, context)' % (result, error, push)
            elif form == 'pair':
                subjects, leading = 'subjects: Tuple[S0, S1]', ['S0: Movable', 'S1: Movable']
                call = '_match_all[%s, %s](subjects[0], subjects[1], _Absent(), %s)' % (result, error, push)
            elif form == 'triple':
                subjects, leading = 'subjects: Tuple[S0, S1, S2]', ['S0: Movable', 'S1: Movable', 'S2: Movable']
                call = '_match_all[%s, %s](subjects[0], subjects[1], subjects[2], %s)' % (result, error, push)
            else:
                subjects, leading, returns = 'subject: Node[F]', ['F: Data'], 'Node[F]'
                call = '_rewrite[%s](subject, %s)' % (error, push)
            name = 'rewrite' if form == 'rewrite' else '`match`'
            doc = full if n == 1 else short % n
            out.append('\n\ndef %s[\n    %s,\n    %s,\n    //\n](\n    %s,\n    %s%s\n) raises %s -> %s:\n'
                       '    """%s"""\n    return %s\n'
                       % (name, ', '.join(leading), ',\n    '.join(decls), subjects, ',\n    '.join(functions),
                          trailing, error, returns, doc, call))
    return ''.join(out) + '\n\n'


def spliced(path, text, start_marker=START, end_marker=END, header=HEADER):
    return splice_source(path.read_text(), text, start_marker, end_marker, header)


def splice_source(source, text, start_marker=START, end_marker=END, header=HEADER):
    start = source.index(start_marker)
    end = source.index(end_marker, start) + len(end_marker)
    return source[:start] + start_marker + header + text + end_marker + source[end:]


def pipeline_source(path):
    source = splice_source(spliced(path, pipe_overloads()), pipeline_syntax.container_methods(),
                           pipeline_syntax.START, pipeline_syntax.END, pipeline_syntax.HEADER)
    return splice_source(source, result_syntax.methods(piped=True), result_syntax.START, result_syntax.END, result_syntax.HEADER)


def composition_source(path):
    return splice_source(spliced(path, composition_overloads()), composition_append_methods(),
                         APPEND_START, APPEND_END, APPEND_HEADER)


def main():
    import generate_sequencing_syntax as sequencing_syntax
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the sources differ from the generator')
    args = parser.parse_args()
    stale = []
    for name, expected_of in (
        ('functions/pipeline.mojo', pipeline_source),
        ('callables/_nary.mojo', lambda path: nary_syntax.native()),
        ('algebra/_nary.mojo', lambda path: spliced(path, nary_syntax.types(), nary_syntax.START, nary_syntax.END, nary_syntax.HEADER)),
        ('iteration/effectful.mojo', lambda path: path.read_text()),
        ('iteration/prefixes.mojo', lambda path: path.read_text()),
        ('iteration/indexed.mojo', lambda path: path.read_text()),
        ('iteration/terminals.mojo', lambda path: path.read_text()),
        ('iteration/branching.mojo', lambda path: path.read_text()),
        ('iteration/alignment.mojo', lambda path: path.read_text()),
        ('iteration/scans.mojo', lambda path: path.read_text()),
        ('algebra/conditional.mojo', lambda path: path.read_text()),
        ('data/_result.mojo', lambda path: spliced(path, result_syntax.methods(), result_syntax.START, result_syntax.END, result_syntax.HEADER)),
        ('iteration/reductions.mojo', lambda path: spliced(path, combinator_syntax.terminal_methods('free'), combinator_syntax.START, combinator_syntax.END, combinator_syntax.HEADER)),
        ('iteration/chaining.mojo', lambda path: splice_source(spliced(path, combinator_syntax.terminal_methods('iter'), '    '+combinator_syntax.START, '    '+combinator_syntax.END, '    '+combinator_syntax.HEADER), traversal_syntax.methods('iter'), '    '+traversal_syntax.START, '    '+traversal_syntax.END, '    '+traversal_syntax.HEADER)),
        ('iteration/derived.mojo', lambda path: spliced(path, traversal_syntax.methods('free'), traversal_syntax.START, traversal_syntax.END, traversal_syntax.HEADER)),
        ('functions/composition.mojo', composition_source),
        ('matching/matcher.mojo', lambda path: spliced(path, match_overloads(), MATCH_START, MATCH_END, MATCH_HEADER)),
    ):
        path = ROOT / 'src/fp' / name
        expected = expected_of(path)
        if name in ('iteration/prefixes.mojo', 'iteration/indexed.mojo', 'iteration/terminals.mojo', 'iteration/branching.mojo', 'iteration/alignment.mojo', 'iteration/scans.mojo'):
            generate = {'iteration/prefixes.mojo': iterator_syntax.prefixes, 'iteration/indexed.mojo': iterator_syntax.indexed, 'iteration/terminals.mojo': iterator_syntax.terminals, 'iteration/branching.mojo': iterator_syntax.branching, 'iteration/alignment.mojo': iterator_syntax.alignment, 'iteration/scans.mojo': iterator_syntax.scans}[name]
            expected = splice_source(expected, generate('free'), iterator_syntax.START, iterator_syntax.END, iterator_syntax.HEADER)
        if name == 'iteration/chaining.mojo':
            expected = splice_source(expected, iterator_syntax.methods(), '    '+iterator_syntax.START, '    '+iterator_syntax.END, '    '+iterator_syntax.HEADER)
            expected = splice_source(expected, sequencing_syntax.methods(iteration=True), sequencing_syntax.START, sequencing_syntax.END, sequencing_syntax.HEADER)
        effect_mode = {'functions/pipeline.mojo': 'piped', 'iteration/chaining.mojo': 'iter', 'iteration/effectful.mojo': 'free', 'algebra/conditional.mojo': 'conditional'}.get(name)
        if effect_mode:
            indent = '' if effect_mode in ('free', 'conditional') else '    '
            expected = splice_source(expected, effect_syntax.methods(effect_mode), indent+effect_syntax.START, indent+effect_syntax.END, indent+effect_syntax.HEADER)
        if path.read_text() != expected:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(expected)
    if args.check and stale:
        print('Out of date with scripts/generate_plain_overloads.py:', ', '.join(stale))
        return 1
    print('checked' if args.check else 'updated' if stale else 'unchanged', ', '.join(stale))
    return 0


if __name__ == '__main__':
    sys.exit(main())
