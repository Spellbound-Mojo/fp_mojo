"""Generate the plain-function overloads of pipe, flow and compose (two to eight
stages), match and rewrite (one to sixteen clauses), and native Piped methods.

Mojo 1.1 reads a plain function's signature only at a parameter of its function
type, so each stage or clause count spells one thin signature per function. Run
from the repository root; `--check` reports whether the sources match instead of
writing.

Names: `A0`...`An` are the values passing through the chain, `P1`... the parameter
types that later stages declare, `B0` and `B1` a binary first stage's arguments,
and `E0`... the stages' errors. A later stage names its own input type, so a
mismatched call still selects these overloads and reaches the pipeline's
per-stage check, which names the stage and both types.
"""
