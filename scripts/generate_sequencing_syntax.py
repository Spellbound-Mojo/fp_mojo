"""Fluent sequencing admission; bind, mapping and receiver adapters own execution."""
from generate_result_syntax import callback

MD = 'Movable & Deinitable'
START = '    # --- sequencing conveniences (generated) ---\n'
END = '    # --- end sequencing conveniences ---\n'
HEADER = '    # Generated by scripts/generate_sequencing_syntax.py; execution stays in shared continuations.\n'


def methods(carrier=None, *, iteration=False):
    out = []
    for name in ('flat_tap', 'flat_pair_with', 'followed_by', 'before'):
        factory = name in ('followed_by', 'before')
        retain = name != 'followed_by'
        paired = name == 'flat_pair_with'
        for kind in (('library', 'pure') if iteration else ('library', 'pure', 'raising')):
            native = kind != 'library'
            cb = callback('thunk' if factory else 'borrow', kind)
            params = ([f'T: {MD}'] if carrier else []) + cb.parameters
            if carrier: params += list(carrier.parameters)
            if params: params += ['//']
            if not carrier and not iteration: params += ['I: Monad']
            params += cb.explicit
            elem = 'T' if carrier else f'downcast[Self.I.Element, {MD}]' if iteration else 'I.Element[Self.Value]'
            family = carrier.instance(elem) if carrier else '_IteratorMap' if iteration else 'I'
            source = carrier.value(elem) if carrier else 'Self.I' if iteration else 'Self.Value'
            value = f'rebind_var[{source}](self.value^)' if carrier else 'self._iterator^' if iteration else 'self.value^'
            condition = f'Self.Value == {source}' if carrier else f'Self.I.Element == {elem}' if iteration else 'True'
            if not factory: condition += f' and {cb.payload} == {elem}'
            prelude = ''
            if native:
                if iteration:
                    adapter = f'_NativeBorrowMut[{elem if factory else cb.payload}, R, C, {factory}]'
                    build = f'{adapter}(function^)'
                else:
                    payload = elem if factory else cb.payload
                    if factory:
                        thunk = f'_NativeThunkRef[R, {cb.error}, C, {kind == "raising"}, o]'
                        adapter = f'_IgnoreInput[{elem}, {thunk}]'
                        build = f'{adapter}({thunk}(Pointer(to=function)))'
                    else:
                        adapter = f'_NativeBorrowRef[{payload}, R, {cb.error}, C, {kind == "raising"}, o, True, _borrow_ref_call_x[{payload}, R, {cb.error}, C, {kind == "raising"}]]'
                        build = f'{adapter}(Pointer(to=function))'
            else:
                adapter = f'_IgnoreInput[{elem}, C]' if factory else 'C'
                build = f'{adapter}(function^)' if factory else 'function^'
            retention_args = ', False, True' if paired else ''
            continuation = f'_EffectRetain[{elem}, {family}, {adapter}{retention_args}]' if retain else f'_BorrowedUnary[{elem}, {adapter}]'
            if iteration:
                condition += f' and {cb.error} == Never' if native else f' and {"C.Error" if factory else "C.Failure"} == Never'
                if native:
                    params.remove('o: ImmOrigin')
                result = f'Iter[FlatMapIterator[{elem}, {continuation}.Out, Self.I, {continuation}]]'
                error = 'Never'
                expr = f'Iter(_bind_iterator({continuation}({build}), {value}))'
            else:
                condition += f' and _ResultCarrierCompatible[{family}, {cb.result}]'
                result = f'Piped[{family}.Bound[{source}, {continuation}]]'
                error = cb.error if carrier else f'{family}.BindError[{source}, {continuation}]'
                if carrier:
                    prelude += f'        comptime assert Self.Value == {source}\n'
                    prelude += f'        comptime assert _ErrorCompatible[{error}, {family}.BindError[{source}, {continuation}]]\n'
                expr = f'Piped(_flat_map_as[{error}, {family}, {source}, {continuation}]({continuation}({build}), {value}))'
            # These declarations only adapt native signatures and source shape.
            # The family/iterator checks repeated invocation and branch copying.
            summary = {'flat_tap':'Sequence a borrowing effectful callback and retain each original value.',
                       'flat_pair_with':'Sequence a borrowing effectful projection and pair each success with its original.',
                       'followed_by':'Sequence a zero-argument factory and keep its produced values.',
                       'before':'Sequence a zero-argument factory and retain each original value.'}[name]
            doc = summary
            if kind == 'library':
                if paired:
                    doc += '\n\n        Each successful projection emits (original, projected). Projected values\n        are moved; only retained originals need Copyable when effects branch.\n'
                doc += '\n\n        Branches follow bind: no output skips the continuation; each produced\n        success emits one output. Retained values must be Copyable for branching\n        families. Single-use families move them. Native errors keep their types.\n'
                doc += '\n        Parameters:\n'
                if carrier:
                    doc += '            T: The source payload type, including origins.\n'
                doc += '            C: The callback, with its exact receiver and effect type.\n'
                if carrier and carrier.name == 'Result': doc += '            Failure: The stored Result error type.\n'
                if not carrier and not iteration: doc += '            I: The Monad family, including its timing, branching and error semantics.\n'
                doc += '\n        Args:\n            function: The callback, consumed; repeatable wherever the source can branch.\n'
                doc += '\n        Returns:\n            '+('A lazy iterator over the sequenced outputs; construction pulls nothing.' if iteration else 'A pipeline holding the family result; deferred families retain callbacks until execution.')+'\n'
                doc += '\n        Raises:\n            '+('Never; lazy callbacks must not raise.' if iteration else 'The exact callback or family construction error.')+'\n        '
            arg = 'var function: C' if iteration or not native else 'ref[o] function: C'
            out.append(f'\n    def {name}[{", ".join(params)}](deinit self, {arg}) raises {error} -> {result} where {condition}:\n        """{doc}"""\n{prelude}        return {expr}\n')
    return ''.join(out)
