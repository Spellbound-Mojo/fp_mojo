"""Generate selected-context admission; Result and algebra own execution."""

from pathlib import Path
from itertools import product
import re
from api_docs import parse_signature
from generate_result_syntax import DOCS, OUTCOMES
from generate_plain_overloads import splice_source
from generate_nary_syntax import MAX
from generate_pipeline_syntax import TRANSFORMS

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/fp/functions/context.mojo"
MD = "Movable & Deinitable"
START = "    # --- selected context methods (generated) ---\n"
END = "    # --- end selected context methods ---\n"
HEADER = "    # Generated by scripts/generate_context.py; callbacks adapt signatures only.\n"


def methods(*, fold_stage=False):
    body = []
    fold_body = []
    # One descriptor owns native callback admission for family and Result methods.
    # Thin pointers are owned; native closures retain a borrow with its exact origin.
    # No operation body reimplements execution, error handling, or traversal.
    T = "_Success[Self.V]"
    Err = "_Failure[Self.V]"
    Source = f"Result[{T}, {Err}]"

    def callback(mode, kind, payload, arg, second=False, repeatable=False):
        C, R, o = ("G", "S", "q") if second else ("C", "R", "o")
        if kind == "library":
            trait = {
                "owned": "UnaryContract",
                "borrow": "BorrowCallContract",
                "thunk": "ThunkContract",
                "binary": "BinaryContract",
                "nary": "UnaryContract",
            }[mode]
            if repeatable:
                trait = "Binary" if mode == "binary" else "BorrowCallable"
            return dict(
                params=[f"{C}: {trait}" + ("" if repeatable else f" & {MD}")],
                argument=f"var {arg}: {C}",
                adapter_type=C,
                build=arg + "^",
                result=C + (".Result" if mode == "borrow" else ".Out"),
                error=C + (".Failure" if mode == "borrow" else ".Error"),
                conditions=(
                    [f"{C}.Arg == Tuple[{', '.join(payload)}]"]
                    if mode == "nary"
                    else (
                        [f"{C}.First == {payload[0]}", f"{C}.Second == {payload[1]}"]
                        if mode == "binary"
                        else (
                            []
                            if mode == "thunk"
                            else [
                                C + (".Payload" if mode == "borrow" else ".Arg") + " == " + payload
                            ]
                        )
                    )
                ),
            )
        E = "Self.E" if kind in ("raising", "thin_raising") else "Never"
        raising = kind not in ("pure", "thin_pure")
        native = (
            ", ".join("var " + p for p in payload)
            if mode in ("binary", "nary")
            else ("var " if mode == "owned" else "") + payload if mode != "thunk" else ""
        )
        signature = (
            f"def({native})"
            + (" raises " + E if raising else "")
            + (" thin" if kind.startswith("thin_") else "")
            + " -> "
            + R
        )
        adapter = {
            "owned": "_NativeUnaryRef",
            "borrow": "_NativeBorrowRef",
            "thunk": "_NativeThunkRef",
            "binary": "_NativeBinaryRef",
            "nary": f"_NativeNary{len(payload)}",
        }[mode]
        native_type = "type_of(" + arg + ")" if kind.startswith("thin_") else C
        origin = o
        cb = (
            adapter
            + "["
            + (
                ", ".join(payload) + ", "
                if mode in ("binary", "nary")
                else payload + ", " if mode != "thunk" else ""
            )
            + f"{R}, {E}, {native_type}, {raising}, {origin}]"
        )
        if kind.startswith("thin_"):
            if mode == "borrow":
                cb = f"_NativeBorrow[{payload}, {R}, {E}, {signature}, {raising}]"
            elif mode == "owned":
                cb = f"NativeUnary[{payload}, {R}, {E}, {signature}, {raising}]"
            elif mode == "binary":
                cb = f"_NativeBinary[{', '.join(payload)}, {R}, {E}, {signature}, {raising}]"
            else:
                cb = f"_NativeThunk[{R}, {E}, {signature}, {raising}]"
        return dict(
            params=(
                [f"{R}: {MD}", "//"]
                if kind.startswith("thin_")
                else [f"{R}: {MD}", f"{o}: ImmOrigin", "//", f"{C}: {signature}"]
            ),
            argument=f"{arg}: {signature}" if kind.startswith("thin_") else f"ref[{o}] {arg}: {C}",
            build=f"{cb}({arg})" if kind.startswith("thin_") else f"{cb}(Pointer(to={arg}))",
            adapter_type=cb,
            prelude="",
            result=R,
            error=E,
            conditions=["Self.E != Never"] if kind == "never" else [],
        )

    kinds = ("library", "pure", "thin_pure", "raising", "never", "thin_never")

    def borrowing_callbacks(payload, arg, repeatable=True):
        for kind in ("library", "pure", "raising", "never"):
            yield callback("borrow", kind, payload, arg, repeatable=repeatable)
        # Stored thin pointers cannot be converted between register and memory
        # argument/result conventions. Spell their native ABI in the signature;
        # every variant still uses the same borrowing adapter and invocation.
        # Read arguments use registers only for trivial types; return values
        # also include nontrivial RegisterPassable types such as Optional[Bool].
        for kind in ("thin_pure", "thin_raising", "thin_never"):
            for register_arg, register_result in product((False, True), repeat=2):
                cb = callback("borrow", kind, "P" if register_arg else payload, arg)
                if register_arg:
                    cb["params"].insert(0, "P: TrivialRegisterPassable")
                    cb["conditions"] += [f"P == {payload}"]
                else:
                    cb["conditions"] += [f"not conforms_to({payload}, TrivialRegisterPassable)"]
                if register_result:
                    cb["params"] = [
                        "R: RegisterPassable & Deinitable" if p == f"R: {MD}" else p
                        for p in cb["params"]
                    ]
                else:
                    cb["conditions"] += ["not conforms_to(R, RegisterPassable)"]
                if kind == "thin_raising":
                    cb["conditions"] += ["Self.E != Never"]
                yield cb

    def owning_callbacks(mode, payload, arg):
        for kind in ("library", "pure", "raising", "never"):
            yield callback(mode, kind, payload, arg)
        operands = payload if mode == "binary" else (payload,)
        for kind in ("thin_pure", "thin_raising", "thin_never"):
            for registers in product((False, True), repeat=len(operands) + 1):
                native = tuple(f"P{i}" if registers[i] else t for i, t in enumerate(operands))
                cb = callback(mode, kind, native if mode == "binary" else native[0], arg)
                for i, actual in enumerate(operands):
                    if registers[i]:
                        cb["params"].insert(i, f"P{i}: RegisterPassable & Deinitable")
                        cb["conditions"] += [f"P{i} == {actual}"]
                    else:
                        cb["conditions"] += [f"not conforms_to({actual}, RegisterPassable)"]
                if registers[-1]:
                    cb["params"] = ["R: RegisterPassable & Deinitable" if p == f"R: {MD}" else p for p in cb["params"]]
                else:
                    cb["conditions"] += ["not conforms_to(R, RegisterPassable)"]
                if kind == "thin_raising":
                    cb["conditions"] += ["Self.E != Never"]
                yield cb

    def thunk_callbacks(arg, second=False):
        for kind in ("library", "pure", "raising", "never"):
            yield callback("thunk", kind, "", arg, second=second)
        for kind in ("thin_pure", "thin_raising", "thin_never"):
            for register_result in (False, True):
                cb = callback("thunk", kind, "", arg, second=second)
                result = cb["result"]
                if register_result:
                    cb["params"] = [f"{result}: RegisterPassable & Deinitable" if p == f"{result}: {MD}" else p for p in cb["params"]]
                else: cb["conditions"] += [f"not conforms_to({result}, RegisterPassable)"]
                if kind == "thin_raising": cb["conditions"] += ["Self.E != Never"]
                yield cb

    def emit(name, cb, params, arguments, result, error, family, conditions, expr, summary):
        if params and params[0] == "//":
            params = params[1:]
        target = f"Pipeline[{family}, {result}, Self.E]"
        receiver = "deinit self, " if arguments else "deinit self"
        prelude = cb.get("prelude", "")
        constraints = " where " + " and ".join(conditions) if conditions else ""
        body.append(
            f"\n    @always_inline\n    def {name}{('[' + ', '.join(params) + ']') if params else ''}({receiver}{arguments}) raises {error} -> {target}{constraints}:\n"
            f'        """{summary}"""\n{prelude}        return {target}({expr})\n'
        )

    # Borrowing observation keeps the existing shared receiver contract. The
    # whole-value tap runs once now; payload observers belong to the family's
    # map, which may defer evaluation and retain the native callback borrow.
    for name in ("tap", "tap_each", "pair_with"):
        payload = "Self.V" if name == "tap" else "Self.I.Element[Self.V]"
        for cb in borrowing_callbacks(payload, "function"):
            observer = f"_Observe[{payload}, {cb['adapter_type']}, {name == 'pair_with'}]"
            built = f"{observer}({cb['build']})"
            conditions = cb["conditions"]
            if name == "tap":
                result, error = "Self.V", cb["error"]
                expr = f"call_once({built}, self.value^)"
                summary = "Inspect the whole value once now and retain it unchanged."
            else:
                conditions += [f"_MapCompatible[Self.I, Self.V, {observer}]"]
                result = f"Self.I.Mapped[Self.V, {observer}]"
                error = f"Self.I.MapError[Self.V, {observer}]"
                expr = f"Self.I.map({built}, self.value^)"
                summary = (
                    "Borrow each payload and retain it beside the projection result."
                    if name == "pair_with"
                    else "Inspect each payload through the family and discard observer results."
                )
            emit(name, cb, cb["params"], cb["argument"], result, error,
                 "Self.I", conditions, expr, summary)

    # Whole-value stages reselect the output family. The optional family comes
    # after the inference barrier, so then[Family](f) is also available.
    for kind in kinds:
        cb = callback("owned", kind, "Self.V", "function")
        params = [p for p in cb["params"] if p != "//"]
        params += ["//", f"J: Functor = _NativeFamily[{cb['result']}]"]
        emit(
            "then",
            cb,
            params,
            cb["argument"],
            cb["result"],
            cb["error"],
            "J",
            cb["conditions"],
            f"call_once({cb['build']}, rebind_var[{cb['adapter_type']}.Arg](self.value^))",
            "Consume the whole value with one stage and select its output family.",
        )

    # Folds share the existing source normalization and terminal drivers. Their
    # callbacks need a shared Binary receiver, matching the standalone folds.
    for name in ("fold_left", "reduce_optional", "fold_until"):
        element = "_FoldElement[Self.V]"
        initial = name != "reduce_optional"
        accumulator = "A" if initial else element
        for kind in ("library", "pure", "raising", "never"):
            cb = callback("binary", kind, (accumulator, element), "step", repeatable=True)
            result = "A" if initial else f"Optional[{cb['result']}]"
            expected = accumulator
            if name == "fold_until":
                result = expected = "ControlFlow[B, A]"
                if kind != "library":
                    cb = {
                        k: (
                            [
                                "B: " + MD if p == "R: " + MD else re.sub(r"\bR\b", result, p)
                                for p in v
                            ]
                            if k == "params"
                            else re.sub(r"\bR\b", result, v) if isinstance(v, str) else v
                        )
                        for k, v in cb.items()
                    }
                else:
                    cb["params"] += ["//", f"B: {MD}"]
            args = cb["argument"] + (", var initial: A" if initial else "")
            params = ([f"A: {MD}"] if initial else []) + cb["params"]
            build = "step" if kind == "library" else cb["build"]
            entry = f"_context_{name}" + ("[B=B]" if name == "fold_until" else "")
            expr = f"{entry}({build}, " + ("initial^, " if initial else "") + "self.value^)"
            emit(
                name,
                cb,
                params,
                args,
                result,
                cb["error"],
                f"_NativeFamily[{result}]",
                cb["conditions"] + [f"{cb['result']} == {expected}"],
                expr,
                "Consume the source in order through the canonical terminal fold.",
            )

    # The selected Monad owns branching and retains the factories if deferred.
    family = "_Binding[Self.I]"
    for left, right in product(thunk_callbacks("on_true"), thunk_callbacks("on_false", second=True)):
        callbacks = (left,right)
        params, explicit = [], []
        for cb in callbacks:
            split = cb["params"].index("//") if "//" in cb["params"] else len(cb["params"])
            params += cb["params"][:split]
            explicit += cb["params"][split+1:]
        params += ["//"] + explicit
        l,r = left["adapter_type"],right["adapter_type"]
        le,reffect = left["error"],right["error"]
        common = reffect if le == "Never" else le if reffect == "Never" else f"_CommonError[{le}, {reffect}]"
        composed = f"_IfEffect[{family}, {l}, {r}]"
        probe = f"_ErrorProbe[Bool, {family}._Joined[{left['result']}, {right['result']}], {common}]"
        result = f"{family}.Bound[Self.V, {composed}]"
        error = f"{family}.BindError[Self.V, {probe}]"
        conditions = ["conforms_to(Self.I, Monad)", "Self.I.Element[Self.V] == Bool"] + left["conditions"] + right["conditions"]
        conditions += [f"{family}.Element[{left['result']}] == {family}.Element[{right['result']}]",
                       f"_ErrorCompatible[{common}, {le}]", f"_ErrorCompatible[{common}, {reffect}]",
                       f"_BindCompatible[{family}, Self.V, {composed}]"]
        conditions += [f"_CarrierCompatible[{family}, {v}]" for v in ("Self.V",left["result"],right["result"])]
        emit("if_effect", {}, params, left["argument"] + ", " + right["argument"], result, error, "Self.I", conditions,
             f"_if_effect[{family}, Self.V, {l}, {r}, {error}](self.value^, {left['build']}, {right['build']})",
             "Invoke only the factory selected by an effectful Bool through the selected Monad.")

    # Structural conveniences share their transforms with legacy fluent APIs.
    for name, bound, extra, arguments, _, c, built, summary in TRANSFORMS:
        emit(name, {}, [bound, *extra, "//"], arguments,
             f"Self.I.Mapped[Self.V, {c}]", f"Self.I.MapError[Self.V, {c}]", "Self.I",
             ["T == Self.I.Element[Self.V]", f"_MapCompatible[Self.I, Self.V, {c}]"],
             f"Self.I.map({c}({built}), self.value^)", summary)
    element = "Self.I.Element[Self.V]"
    identity = f"Identity[{element}]"
    for name, family, capability, result_alias, error_alias in (
        ("compact", "_Compacting[Self.I]", "FunctorFilter", "MapFiltered", "MapFilterError"),
        ("flatten", "_Binding[Self.I]", "Monad", "Bound", "BindError"),
    ):
        conditions = [f"conforms_to(Self.I, {capability})", f"_MapCompatible[Self.I, Self.V, {identity}]"]
        if name == "compact": conditions += [f"{element} == Optional[_ListElement[{element}]]"]
        else: conditions += [f"_CarrierCompatible[{family}, {element}]", f"_BindCompatible[{family}, Self.V, {identity}]"]
        result, error = f"{family}.{result_alias}[Self.V, {identity}]", f"{family}.{error_alias}[Self.V, {identity}]"
        emit(name, {}, [], "", result, error, "Self.I", conditions,
             f"_context_{name}[{family}](self.value^)", "Remove one admitted inner layer through the selected source family.")
    family = "_Combining[Self.I]"
    function = f"_Function[{family}, Self.V]"
    apply = f"_Apply[{function}]"
    types = f"Self.V, {apply}, _ValueThunk[W]"
    emit("ap", {}, [f"W: {MD}", "//"], "var values: W",
         f"{family}.Combined[{types}]", f"{family}.CombineError[{types}]", "Self.I",
         ["conforms_to(Self.I, Applicative)", f"conforms_to({element}, UnaryContract & Movable & Deinitable)",
          f"_CombineCompatible[{family}, {types}]", f"_CarrierCompatible[{family}, Self.V]",
          f"_CarrierCompatible[{family}, W]", f"{family}.Element[W] == {function}.Arg"],
         f"_context_ap[{family}](self.value^, values^)",
         "Apply the stored library callables through the selected Applicative.")

    # Pure reductions select their result family after one canonical source pass.
    element = "_FoldElement[Self.V]"
    for name in ("find_map", "fold_map", "sum_by", "min_by", "max_by"):
        borrowed = name in ("min_by", "max_by")
        for numeric in (("int", "simd") if name == "sum_by" else (None,)):
            callbacks = borrowing_callbacks(element, "function") if borrowed else owning_callbacks("owned", element, "function")
            for cb in callbacks:
                c, result, error = cb["adapter_type"], cb["result"], cb["error"]
                params = list(cb["params"])
                conditions = list(cb["conditions"])
                if "//" not in params: params += ["//"]
                if borrowed:
                    conditions += [f"conforms_to({result}, Comparable & Movable & Deinitable)"]
                    result = f"Optional[{element}]"
                    expr = f"_extremum[Self.V, {element}, {c}, {name == 'min_by'}]({cb['build']}, self.value^)"
                elif name == "find_map":
                    conditions += [f"{result} == Optional[_ListElement[{result}]]", f"RepeatableUnary[{c}]"]
                    expr = f"_find_map({cb['build']}, self.value^)"
                else:
                    monoid = "M" if name == "fold_map" else ("_IntSum" if numeric == "int" else "_SIMDSum[dtype, size]")
                    if name == "fold_map": params.insert(params.index("//") + 1, "M: Monoid")
                    if numeric == "simd": params[params.index("//") + 1:params.index("//") + 1] = ["dtype: DType", "size: SIMDLength"]
                    conditions += [f"{result} == {monoid}.Value", f"RepeatableUnary[{c}]"]
                    if numeric == "simd": conditions += [f"{monoid}.Admitted"]
                    error = f"_CommonError[{error}, {monoid}.Error]"
                    conditions += [f"_ErrorCompatible[{error}, {monoid}.Error]", f"_ErrorCompatible[{error}, {cb['error']}]"]
                    result = f"{monoid}.Value"
                    expr = f"_fold_map[Self.V, {c}, {monoid}, {error}]({cb['build']}, self.value^)"
                emit(name, cb, params, cb["argument"], result, error, f"_NativeFamily[{result}]", conditions, expr,
                     "Reduce the consumed source in order through the canonical terminal driver.")
    for name, monoid, params in (("combine_all", "M", ["M: Monoid"]), ("sum", "_IntSum", []),
                                 ("sum", "_SIMDSum[dtype, size]", ["dtype: DType", "size: SIMDLength"])):
        result = f"{monoid}.Value"
        emit(name, {}, params, "", result, f"{monoid}.Error", f"_NativeFamily[{result}]",
             [f"{element} == {result}"] + ([f"{monoid}.Admitted"] if monoid.startswith("_SIMDSum") else []),
             f"_fold_map[M={monoid}, E={monoid}.Error](Identity[{result}](), self.value^)",
             "Combine source elements in order, returning the identity for empty input.")

    # Effectful terminals consume the native source, independently of its
    # selected Functor. The target Monad owns ordering, stopping and deferral.
    for name in ("all_effect", "any_effect", "find_effect", "find_map_effect", "fold_effect", "fold_map_effect"):
        borrowing = name in ("all_effect", "any_effect", "find_effect")
        folding = name == "fold_effect"
        mapped_fold = name == "fold_map_effect"
        element = "_FoldElement[Self.V]"
        callbacks = (
            borrowing_callbacks(element, "function") if borrowing else
            owning_callbacks("binary" if folding else "owned",
                             ("Self.A", element) if folding else element, "function")
        )
        for cb in callbacks:
            params = list(cb["params"])
            if "//" not in params:
                params += ["//"]
            if not folding:
                params[params.index("//") + 1:params.index("//") + 1] = (
                    ["J: Monad", "M: Monoid"] if mapped_fold else ["J: Monad"]
                )
            c, result = cb["adapter_type"], cb["result"]
            conditions = cb["conditions"] + [f"_CarrierCompatible[J, {result}]"]
            built = cb["build"]
            if name in ("all_effect", "any_effect"):
                step = f"_PredicateStep[{c}]"
                policy = f"_BoolLive[{name == 'all_effect'}]"
                initial = str(name == "all_effect")
                built = f"{step}({built})"
                conditions += [f"J.Element[{result}] == Bool"]
            elif name in ("find_effect", "find_map_effect"):
                selected = element if borrowing else f"_ListElement[J.Element[{result}]]"
                retained = f"_TraverseTap[{element}, J, {c}, True]" if borrowing else c
                step = f"_SearchStep[{selected}, {retained}]"
                policy, initial = f"_FirstPresent[{selected}]", f"Optional[{selected}]()"
                built = f"{step}({retained}({built}))" if borrowing else f"{step}({built})"
                conditions += [f"J.Element[{result}] == " + ("Bool" if borrowing else f"Optional[{selected}]"),
                               f"RepeatableUnary[{retained}]"]
            elif folding:
                step, policy, initial = c, "_AllLive[Self.A]", "self.initial^"
                conditions += [f"J.Element[{result}] == Self.A", f"RepeatableBinary[{c}]"]
            else:
                step, policy = f"_FoldMappedStep[J, M, {c}]", "_AllLive[M.Value]"
                conditions += [f"J.Element[{result}] == M.Value", f"RepeatableUnary[{c}]",
                               f"_MapCompatible[J, {result}, _BindFirst[_AccumulatePair[_Combine[M]]]]",
                               f"_ErrorCompatible[_CommonError[{cb['error']}, M.Error], M.Error]"]
            plan = f"_EffectFold[J, Self.V, {step}, {policy}]"
            error = f"_CommonError[M.Error, {plan}.Error]" if mapped_fold else f"{plan}.Error"
            expr = (f"_fold_map_effect[J, M, Self.V, {c}, {error}]({built}, self.value^)" if mapped_fold else
                    f"_fold_effect[J, Self.V, {step}, {policy}, {error}]({built}, {initial}, self.value^)")
            emit("run" if folding else name, cb, params, cb["argument"],
                 f"{plan}.Out", error, "J", conditions, expr,
                 "Consume the source through the target Monad's ordered effectful reduction.")
            if folding:
                fold_body.append(re.sub(r"\bJ\b", "Self.J", body.pop()))
        if folding:
            body.append('''
    def fold_effect[A: Movable & Deinitable, //, J: Monad](deinit self, var initial: A) -> _EffectFoldStage[J, Self.V, A, Self.E]:
        """Bind the initial accumulator; run(step) admits the effectful callback."""
        return _EffectFoldStage[J, Self.V, A, Self.E](self.value^, initial^)
''')


    for kind in kinds:
        cb = callback("owned", kind, "Self.I.Element[Self.V]", "function")
        params = list(cb["params"])
        if "//" not in params:
            params += ["//"]
        params.insert(params.index("//") + 1, "J: Applicative")
        family = "_Traversing[Self.I]"
        result = f"{family}.Traversed[J, Self.V, {cb['adapter_type']}]"
        error = f"{family}.TraverseError[J, Self.V, {cb['adapter_type']}]"
        conditions = ["conforms_to(Self.I, Traversable)"] + cb["conditions"]
        conditions += [
            f"_CollectCompatible[J, Self.V, {cb['adapter_type']}]",
            f"_CarrierCompatible[J, {cb['result']}]",
        ]
        emit(
            "traverse",
            cb,
            params,
            cb["argument"],
            result,
            error,
            "J",
            conditions,
            f"{family}.traverse[J]({cb['build']}, self.value^)",
            "Traverse into the selected target effect and continue in that family.",
        )

    # Retention and compaction are the existing traversal policies. Source and
    # target carrier admission precede any body assertion or origin rebind.
    for name in ("traverse_tap", "filter_effect"):
        filtering = name == "filter_effect"
        family = "_SelectingTraversal[Self.I]" if filtering else "_Traversing[Self.I]"
        for cb in borrowing_callbacks("Self.I.Element[Self.V]", "function", repeatable=False):
            params = list(cb["params"])
            if "//" not in params:
                params += ["//"]
            params.insert(params.index("//") + 1, "J: Applicative")
            retained = f"_TraverseTap[Self.I.Element[Self.V], J, {cb['adapter_type']}, {filtering}]"
            built = f"{retained}({cb['build']})"
            traversed = f"{family}.Traversed[J, Self.V, {retained}]"
            before = f"{family}.TraverseError[J, Self.V, {retained}]"
            result, error = traversed, before
            conditions = ["conforms_to(Self.I, Traversable)"] + cb["conditions"]
            conditions += [
                "_MapCompatible[Self.I, Self.V, Identity[Self.I.Element[Self.V]]]",
                f"_CarrierCompatible[J, {cb['result']}]",
                f"_CollectCompatible[J, Self.V, {retained}]",
            ]
            expr = f"_traverse_as[{family}, J, Self.V, {retained}, {error}]({built}, self.value^)"
            summary = "Traverse borrowed effects and retain each original payload on success."
            if filtering:
                finish = f"_CompactAfter[{family}, J.Element[{traversed}]]"
                after = f"J.MapError[{traversed}, {finish}]"
                error = f"_CommonError[{before}, {after}]"
                result = f"J.Mapped[{traversed}, {finish}]"
                conditions += [
                    "conforms_to(Self.I, FunctorFilter)",
                    f"J.Element[{cb['result']}] == Bool",
                    f"J.Element[{retained}.Out] == Optional[Self.I.Element[Self.V]]",
                    f"_MapCompatible[J, {traversed}, {finish}]",
                ]
                expr = f"_traverse_then[{family}, J, Self.V, {retained}, {finish}, {error}]({built}, self.value^, {finish}())"
                summary = "Traverse borrowing Bool effects and retain accepted original payloads."
            emit(name, cb, params, cb["argument"], result, error, "J", conditions, expr, summary)

    # Traversal postprocessing stays inside the target effect.
    for name in ("traverse_filter", "sequence_filter", "flat_traverse", "flat_sequence"):
        sequence = name in ("sequence_filter", "flat_sequence")
        compact = name in ("traverse_filter", "sequence_filter")
        family = "_SelectingTraversal[Self.I]" if compact else "_FlatteningTraversal[Self.I]"
        element = "Self.I.Element[Self.V]"
        identity = f"Identity[{element}]"
        callbacks = ([dict(params=[],argument="",adapter_type=identity,build=f"{identity}()",result=element,error="Never",conditions=[])]
                     if sequence else owning_callbacks("owned", element, "function"))
        for cb in callbacks:
            params = list(cb["params"])
            if "//" not in params: params += ["//"]
            params.insert(params.index("//") + 1, "J: Applicative")
            c, result = cb["adapter_type"], cb["result"]
            traversed = f"{family}.Traversed[J, Self.V, {c}]"
            finish = f"{'_CompactAfter' if compact else '_FlattenAfter'}[{family}, J.Element[{traversed}]]"
            error = f"_CommonError[{family}.TraverseError[J, Self.V, {c}], J.MapError[{traversed}, {finish}]]"
            conditions = ["conforms_to(Self.I, Traversable)",
                          "conforms_to(Self.I, FunctorFilter)" if compact else "conforms_to(Self.I, Monad)"] + cb["conditions"]
            conditions += ["_MapCompatible[Self.I, Self.V, Identity[Self.I.Element[Self.V]]]",
                           f"_CollectCompatible[J, Self.V, {c}]", f"_CarrierCompatible[J, {result}]",
                           f"_MapCompatible[J, {traversed}, {finish}]"]
            if compact:
                conditions += [f"J.Element[{result}] == Optional[_ListElement[J.Element[{result}]]]"]
            else:
                conditions += [f"_CarrierCompatible[{family}, J.Element[{result}]]",
                               f"_BindCompatible[{family}, J.Element[{traversed}], Identity[{family}.Element[J.Element[{traversed}]]]]"]
            expr = f"_traverse_then[{family}, J, Self.V, {c}, {finish}, {error}]({cb['build']}, self.value^, {finish}())"
            emit(name, cb, params, cb["argument"], f"J.Mapped[{traversed}, {finish}]", error,
                 "J", conditions, expr, "Traverse and finish inside the selected target effect.")

    # Native sources discard successful output; Result traversal retains its
    # source error layer through the existing composition/void policy.
    for name in ("traverse_void", "sequence_void"):
        for retained_error in (False, True):
            element = "Self.I.Element[Self.V]" if retained_error else "_FoldElement[Self.V]"
            identity = f"Identity[{element}]"
            callbacks = ([dict(params=[],argument="",adapter_type=identity,build=f"{identity}()",result=element,error="Never",conditions=[])]
                         if name == "sequence_void" else owning_callbacks("owned", element, "function"))
            for cb in callbacks:
                params = list(cb["params"])
                if "//" not in params: params += ["//"]
                params.insert(params.index("//") + 1, "J: Applicative")
                c, result = cb["adapter_type"], cb["result"]
                conditions = [("" if retained_error else "not ") + "conforms_to(Self.V, _ResultType)"] + cb["conditions"]
                conditions += [f"_CarrierCompatible[J, {result}]"]
                if retained_error:
                    family = "_Traversing[Self.I]"
                    discard = f"_EffectVoid[J, {result}]"
                    composed = f"Composition[False, 1, {c}, {discard}]"
                    out = f"{family}.Traversed[J, Self.V, {composed}]"
                    error = f"{family}.TraverseError[J, Self.V, {composed}]"
                    # Native Result traversal depends only on callback metadata.
                    # Avoid projecting generic errors through Composition's stored
                    # type pack; the execution driver checks the actual error.
                    # Custom families retain their own callback-dependent aliases.
                    filled = f"_Fill[J.Element[{result}], NoneType]"
                    probe = f"_ErrorProbe[{element}, J.Mapped[{result}, {filled}], _CommonError[{cb['error']}, J.MapError[{result}, {filled}]]]"
                    error = f"(ResultFamily[_Failure[Self.V]].TraverseError[J, Self.V, {probe}] if Self.I == ResultFamily[_Failure[Self.V]] else {error})"
                    conditions += ["conforms_to(Self.I, Traversable)",
                                   "_MapCompatible[Self.I, Self.V, Identity[Self.I.Element[Self.V]]]",
                                   f"_CollectCompatible[J, Self.V, {composed}]",
                                   f"_MapCompatible[J, {result}, _Fill[J.Element[{result}], NoneType]]"]
                    expr = f"_traverse_as[{family}, J, Self.V, {composed}, {error}]({composed}({cb['build']}, {discard}()), self.value^)"
                else:
                    policy = f"_Discard[J.Element[{result}]]"
                    out = f"J._Looped[Self.V, {c}, {policy}]"
                    error = f"J._LoopError[Self.V, {c}, {policy}]"
                    conditions += [f"RepeatableUnary[{c}]", f"_CollectCompatible[J, Self.V, {c}]"]
                    expr = f"_traverse_void[Self.V, {c}, J, {error}]({cb['build']}, self.value^)"
                emit(name, cb, params, cb["argument"], out, error, "J", conditions, expr,
                     "Traverse effects and discard successful payloads, retaining source Result errors.")

    for kind in ("library", "pure", "raising", "never"):
        family = "_Combining[Self.I]"
        cb = callback("binary", kind, ("Self.I.Element[Self.V]", "Self.I.Element[W]"), "function")
        types = f"Self.V, {cb['adapter_type']}, _ValueThunk[W]"
        result, error = f"{family}.Combined[{types}]", f"{family}.CombineError[{types}]"
        conditions = ["conforms_to(Self.I, Applicative)"] + cb["conditions"]
        conditions += [
            f"_CombineCompatible[{family}, {types}]",
            f"_CarrierCompatible[{family}, Self.V]",
            f"_CarrierCompatible[{family}, W]",
        ]
        emit(
            "map2",
            cb,
            [f"W: {MD}"] + cb["params"],
            f"var other: W, {cb['argument']}",
            result,
            error,
            "Self.I",
            conditions,
            f"_map2_as[{family}, X={error}]({cb['build']}, self.value^, other^)",
            "Combine two evaluated carriers through the selected Applicative family.",
        )

    family = "_Combining[Self.I]"
    pair = "_Pair[Self.I.Element[Self.V], Self.I.Element[W]]"
    types = f"Self.V, {pair}, _ValueThunk[W]"
    error, result = f"{family}.CombineError[{types}]", f"{family}.Combined[{types}]"
    emit(
        "product",
        {},
        [f"W: {MD}"],
        "var other: W",
        result,
        error,
        "Self.I",
        [
            "conforms_to(Self.I, Applicative)",
            f"_CombineCompatible[{family}, {types}]",
            f"_CarrierCompatible[{family}, Self.V]",
            f"_CarrierCompatible[{family}, W]",
        ],
        f"_map2_as[{family}, X={error}]({pair}(), self.value^, other^)",
        "Combine two evaluated carriers into pairs using the selected family.",
    )

    family = "_Traversing[Self.I]"
    identity = "Identity[Self.I.Element[Self.V]]"
    types = f"J, Self.V, {identity}"
    result, error = f"{family}.Traversed[{types}]", f"{family}.TraverseError[{types}]"
    target = f"Pipeline[J, {result}, Self.E]"
    body.append(
        f"\n    def sequence[J: Applicative](deinit self) raises {error} -> {target} where conforms_to(Self.I, Traversable) and _CollectCompatible[J, Self.V, {identity}] and _CarrierCompatible[J, Self.I.Element[Self.V]]:\n"
        f'        """Sequence existing effects and continue in the target family."""\n'
        f"        return {target}({family}.traverse[J]({identity}(), self.value^))\n"
    )

    # A selected family fixes every operand payload before the native function
    # is admitted. Only the native signatures are arity-specific; the existing
    # Applicative product runner owns evaluation, errors and partial cleanup.
    family = "_Combining[Self.I]"
    run = f"_ProductRun[{family}, Self.V, *Ws]"
    product_type = f"_ProductTypes[{family}, Self.V, *Ws]"
    target = f"Pipeline[Self.I, {product_type}.Out, Self.E]"
    conditions = f"conforms_to(Self.I, Applicative) and Ws.length < {MAX} and {run}.AdmittedInputs"
    body.append(
        f"\n    def product_n[*Ws: {MD}](deinit self, var others: Tuple[*Ws]) raises {product_type}.Error -> {target} where {conditions}:\n"
        '        """Combine up to eight evaluated carriers into flat tuples."""\n'
        f"        return {target}({run}.run[{product_type}.Out, {product_type}.Error](self.value^, others^))\n"
    )
    cb = callback("owned", "library", f"{run}.Payload", "function")
    mapped = f"_MapNTypes[{family}, Self.V, C, *Ws]"
    emit(
        "map_n",
        cb,
        cb["params"] + [f"*Ws: {MD}"],
        f"var others: Tuple[*Ws], {cb['argument']}",
        mapped + ".Out",
        mapped + ".Error",
        "Self.I",
        [conditions] + cb["conditions"],
        f"_map_n_as[{family}, {product_type}.Out, {mapped}.Out, {mapped}.Error](function^, self.value^, others^)",
        "Combine up to eight carriers and consume each tuple through a library callback.",
    )
    for n in range(1, MAX + 1):
        carriers = [f"W{i}" for i in range(n - 1)]
        tail = ", " + ", ".join(carriers) if carriers else ""
        operands = f"Self.V{tail}"
        product_type = f"_ProductTypes[{family}, {operands}]"
        run = f"_ProductRun[{family}, {operands}]"
        payloads = [f"Self.I.Element[{v}]" for v in ["Self.V"] + carriers]
        for kind in ("pure", "raising", "never"):
            cb = callback("nary", kind, payloads, "function")
            mapped = f"_MapNTypes[{family}, Self.V, {cb['adapter_type']}{tail}]"
            params = [f"{w}: {MD}" for w in carriers] + cb["params"]
            emit(
                "map_n",
                cb,
                params,
                f"var others: Tuple[{', '.join(carriers)}], {cb['argument']}",
                mapped + ".Out",
                mapped + ".Error",
                "Self.I",
                ["conforms_to(Self.I, Applicative)", f"{run}.AdmittedInputs"] + cb["conditions"],
                f"_map_n_as[{family}, {product_type}.Out, {mapped}.Out, {mapped}.Error]({cb['build']}, self.value^, others^)",
                f"Combine {n} carriers and call the native function with their separate payloads.",
            )

    # The family and its input type are known before callback admission. Reuse
    # the exact native view/owned thin-pointer boundary used by Result methods.
    for name, trait, family, result_alias, error_alias in (
        ("map", "Functor", "Self.I", "Mapped", "MapError"),
        ("filter", "Filterable", "_Filtering[Self.I]", "Filtered", "FilterError"),
        ("filter_not", "Filterable", "_Filtering[Self.I]", "Filtered", "FilterError"),
        ("flat_map", "Monad", "_Binding[Self.I]", "Bound", "BindError"),
        ("filter_map", "FunctorFilter", "_Compacting[Self.I]", "MapFiltered", "MapFilterError"),
    ):
        filtering = name in ("filter", "filter_not")
        mode = "borrow" if filtering else "owned"
        arg = "predicate" if filtering else "function"
        callbacks = (
            borrowing_callbacks("Self.I.Element[Self.V]", arg)
            if name == "filter_not"
            else (callback(mode, kind, "Self.I.Element[Self.V]", arg, repeatable=filtering) for kind in kinds)
        )
        for cb in callbacks:
            params = cb["params"]
            cbtype = cb["adapter_type"]
            conditions = [f"conforms_to(Self.I, {trait})"] + cb["conditions"]
            if filtering:
                conditions.append(cb["result"] + " == Bool")
            if name == "map":
                conditions.append(f"_MapCompatible[Self.I, Self.V, {cbtype}]")
            if name == "flat_map":
                conditions.append(f"_BindCompatible[{family}, Self.V, {cbtype}]")
            if name == "filter_not":
                cbtype = f"_FilterPredicate[{cbtype}, True]"
            result = f"{family}.{result_alias}[Self.V, {cbtype}]"
            error = f"{family}.{error_alias}[Self.V, {cbtype}]"
            target = f"Pipeline[Self.I, {result}, Self.E]"
            expr = f"{family}.{name}({cb['build']}, self.value^)"
            if name == "filter_not":
                expr = f"_filter_with[Self.V, {cb['adapter_type']}, {family}, True]({cb['build']}, self.value^)"
            prelude = cb.get("prelude", "")
            body.append(
                f"\n    @always_inline\n    def {name}{('[' + ', '.join(params) + ']') if params else ''}(deinit self, {cb['argument']}) raises {error} -> {target} where {' and '.join(conditions)}:\n        \"\"\"Apply {name} through the selected family's {trait} capability.\"\"\"\n{prelude}        return {target}({expr})\n"
            )

    for name, (summary, detail) in (DOCS | OUTCOMES).items():
        two = name in ("ensure", "recover_if", "or_else_if") or name in OUTCOMES
        for first, second in (
            product(("library", "pure", "thin_pure", "raising", "never", "thin_never"), repeat=2)
            if two
            else (
                (k, None)
                for k in ("library", "pure", "thin_pure", "raising", "never", "thin_never")
            )
        ):
            mode = (
                "owned"
                if name in ("recover", "map_err", "or_else") or name in OUTCOMES
                else "thunk" if name in ("before", "followed_by") else "borrow"
            )
            payload = (
                T
                if name in ("flat_tap", "flat_pair_with", "ensure") or name in OUTCOMES
                else Source if name == "attempt_tap" else Err
            )
            arg = "on_ok" if name in OUTCOMES else "predicate" if two else "function"
            a = callback(mode, first, payload, arg)
            callbacks = [a]
            if two:
                mode2 = "borrow" if name == "ensure" else "owned"
                arg2 = (
                    "on_err"
                    if name in OUTCOMES
                    else "make_error" if name == "ensure" else "function"
                )
                callbacks += [callback(mode2, second, T if name == "ensure" else Err, arg2, True)]
            conditions = [f"conforms_to(Self.V, _ResultType)", f"Self.V == {Source}"] + sum(
                (c["conditions"] for c in callbacks), []
            )
            R = a["result"]
            result = Source
            if name == "recover":
                conditions += [f"{R} == {T}"]
            if name in (
                "flat_tap",
                "flat_pair_with",
                "flat_tap_err",
                "attempt_tap",
                "before",
                "followed_by",
            ):
                conditions += [f"{R} == Result[_Success[{R}], {Err}]"]
            if name == "flat_pair_with":
                result = f"Result[Tuple[{T}, _Success[{R}]], {Err}]"
            if name == "followed_by":
                result = R
            if name == "map_err":
                result = f"Result[{T}, {R}]"
            if name == "or_else":
                conditions += [f"{R} == Result[{T}, _Failure[{R}]]"]
                result = R
            if two:
                S = callbacks[1]["result"]
                ex = a["error"]
                ey = callbacks[1]["error"]
                if name in OUTCOMES:
                    if name == "map_both":
                        result = f"Result[{R}, {S}]"
                    else:
                        conditions += [f"{R} == {S}"]
                        result = R if name == "redeem_with" else f"Result[{R}, {Err}]"
                    if name == "redeem_with":
                        conditions += [f"{R} == Result[_Success[{R}], _Failure[{R}]]"]
                else:
                    conditions += [
                        f"{R} == Bool",
                        f"{S} == "
                        + (Err if name == "ensure" else T if name == "recover_if" else Source),
                    ]
                conditions += [f"({ex} == Never or {ey} == Never or {ex} == {ey})"]
                effect = (
                    ey
                    if first == "pure"
                    else ex if second == "pure" else f"_CommonError[{ex}, {ey}]"
                )
            else:
                effect = a["error"]
            params = []
            explicit = []
            for c in callbacks:
                if "//" in c["params"]:
                    split = c["params"].index("//")
                    params += c["params"][:split]
                    explicit += c["params"][split + 1 :]
                else:
                    params += c["params"]
            if explicit:
                params += ["//"] + explicit
            family = f"ResultFamily[_Failure[{result}]]"
            target = f"Pipeline[{family}, {result}, Self.E]"
            expr = (
                f"rebind_var[{Source}](self.value^).{name}("
                + ", ".join(c["build"] for c in callbacks)
                + ")"
            )
            prelude = "".join(c.get("prelude", "") for c in callbacks)
            body += [
                f'\n    def {name}[{", ".join(params)}](deinit self, {", ".join(c["argument"] for c in callbacks)}) raises {effect} -> {target} where '
                + " and ".join(conditions)
                + f':\n        """{summary}"""\n{prelude}        return {target}({expr})\n'
            ]
    return "".join(fold_body if fold_stage else body)


def documented(source):
    """Document the primary overload of each family of public methods."""
    seen = set()
    params = {
        "A": "The accumulator type, inferred from the initial value and preserved by every step.",
        "M": "The Monoid used for the identity and ordered combination of mapped values.",
        "P": "The borrowed payload type, including its origins.",
        "P0": "The first native register operand type, including its origins.",
        "P1": "The second native register operand type, including its origins.",
        "R": "The first callback result type, inferred from the callback.",
        "S": "The second callback result type, inferred from the callback.",
        "T": "The carrier payload type.",
        "U": "The copied value type, including its origins.",
        "V": "The complete carrier type.",
        "E": "The stored Result error type; independent of the selected native error.",
        "I": "The explicit Functor family, including its evaluation and error semantics.",
        "F": "The native or library callback type, retaining its receiver and origins.",
        "C": "The first library callback type, retaining its receiver and origins.",
        "G": "The second library callback type, retaining its receiver and origins.",
        "o": "The first callback origin, inferred from the borrowed callback.",
        "q": "The second callback origin, inferred from the borrowed callback.",
        "J": "The output family; inferred for whole-value stages, explicit for traversal.",
        "W": "The second carrier type, including its origins.",
        "B": "The early termination payload, including its origins.",
        "Ws": "The additional carrier types, including their origins; at most seven.",
    }
    args = {
        "function": "The callback; native callbacks are borrowed, library callbacks consumed.",
        "predicate": "The borrowing Bool predicate.",
        "make_error": "The borrowed-payload factory of a stored Result error.",
        "on_true": "The factory invoked only for a true payload; native closures are borrowed.",
        "on_false": "The factory invoked only for a false payload; native closures are borrowed.",
        "on_ok": "The success handler, consuming the success payload.",
        "on_err": "The error handler, consuming the stored error payload.",
        "value": "The carrier, consumed.",
        "step": "The fold step; native callbacks are borrowed, library Binary steps consumed.",
        "initial": "The initial accumulator, consumed.",
        "other": "The already evaluated second carrier, consumed.",
        "old": "The payload to compare against, consumed.",
        "new": "The replacement payload, copied into matching positions.",
        "values": "The already evaluated carrier of arguments, consumed.",
        "others": "The tuple of already evaluated additional carriers, consumed.",
    }
    summaries = {
        "map": "Map payloads through the selected family.",
        "filter": "Keep payloads accepted by a borrowing Bool predicate.",
        "pipeline": "Select the carrier family before admitting any callback.",
    }
    # Headers may wrap over more than two lines; scan declarations by indentation.
    lines = source.splitlines(keepends=True)
    out = []
    i = 0
    while i < len(lines):
        match = re.match(r"^(    )?def (\w+)", lines[i])
        if not match:
            out.append(lines[i])
            i += 1
            continue
        name = match[2]
        indent = "        " if match[1] else "    "
        header = []
        while i < len(lines):
            header.append(lines[i])
            i += 1
            if header[-1].rstrip().endswith(":"):
                break
        out += header
        if name in seen or name in ("raising", "get"):
            if name in summaries and (i == len(lines) or not lines[i].lstrip().startswith('"""')):
                out.append(indent + '"""' + summaries[name] + '"""\n')
            continue
        seen.add(name)
        summary = summaries.get(name)
        if i < len(lines) and lines[i].lstrip().startswith('"""'):
            summary = lines[i].strip().strip('"')
            single = lines[i].count('"""') == 2
            i += 1
            if not single:
                while i < len(lines):
                    closing = '"""' in lines[i]
                    i += 1
                    if closing:
                        break
        spec = parse_signature(" ".join(x.strip() for x in header))
        doc = [indent + '"""' + summary + "\n"]
        if spec["parameters"]:
            doc += ["\n" + indent + "Parameters:\n"]
            doc += [
                indent + "    " + p["name"] + ": " + params[p["name"]] + "\n"
                for p in spec["parameters"]
            ]
        if spec["arguments"]:
            doc += ["\n" + indent + "Args:\n"]
            doc += [
                indent + "    " + a["name"] + ": " + (
                    "The value consumed here and copied into each payload position."
                    if a["name"] == "value" and name in ("fill", "tuple_left", "tuple_right")
                    else args[a["name"]]
                ) + "\n"
                for a in spec["arguments"]
            ]
        doc += [
            "\n"
            + indent
            + "Returns:\n"
            + indent
            + ("    An owning fold stage; run(step) returns the target pipeline.\n" if name == "fold_effect" else
               "    The pipeline containing the operation result, retaining its selected native error.\n")
        ]
        if spec["error"]:
            doc += [
                "\n"
                + indent
                + "Raises:\n"
                + indent
                + "    The exact callback or family error; it never becomes a stored Result error.\n"
            ]
        doc += [indent + '"""\n']
        out += doc
    return "".join(out)


def source(path=OUTPUT):
    value = splice_source(path.read_text(), methods(), START, END, HEADER)
    value = splice_source(value, methods(fold_stage=True),
                          "    # --- effect fold admission (generated) ---\n",
                          "    # --- end effect fold admission ---\n", HEADER)
    return documented(value)


