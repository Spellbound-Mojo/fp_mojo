"""Result combinator admission and Piped forwarding; no execution is generated."""
from itertools import product
from native_signatures import callback, native_adapter, Operand, variants, argument as native_argument
from operation_specs import RESULT_DOCS as DOCS, RESULT_OUTCOMES as OUTCOMES, RESULT_OPERATIONS, RESULT_TERMINALS, SEQUENCING

MD = 'Movable & Deinitable'
START = '    # --- Result combinators (generated) ---\n'
END = '    # --- end Result combinators ---\n'
HEADER = '    # Generated by scripts/generate_result_syntax.py; execution stays in Result and shared callable adapters.\n'


def methods(piped=False):
    out = []
    t, e = ('T', 'Failure') if piped else ('Self.T', 'Self.E')
    source = f'Result[{t}, {e}]'
    for name, (summary, detail) in DOCS.items():
        operation = RESULT_OPERATIONS[name]
        primary = operation.callbacks[0]
        if piped and operation.sequence:
            continue
        if not piped and name in ('map_err', 'or_else'):
            continue
        conditional, selective = operation.conditional, operation.selective
        mode = primary.mode
        kinds = ('library', 'pure', 'raising')
        combinations = product(kinds, kinds) if conditional else ((k, None) for k in kinds)
        for kind, other in combinations:
            t, e = ('T', 'Failure') if piped else ('Self.T', 'Self.E')
            cb = callback(mode, kind, primary.argument)
            if piped and name == 'or_else' and kind != 'library':
                cb.explicit.append(f'U: {MD} = downcast[R, _ResultType].Error')
            inferred_recovery = piped and name == 'recover' and kind != 'library'
            if inferred_recovery:
                t, e = cb.result, cb.payload
            source = f'Result[{t}, {e}]'
            if name in ('attempt_tap', 'flat_tap_err') and kind != 'library':
                # Infer the whole native result on Mojo 1.2, then check the
                # stored error and its origins at admission. Keep U available
                # by name, without changing the existing C/X positions.
                cb.parameters = [f'R: {MD}', 'o: ImmOrigin']
                cb.payload, cb.result = (source if name == 'attempt_tap' else e), 'R'
                raises = f' raises {cb.error}' if kind == 'raising' else ''
                cb.explicit[-1] = f'C: def({cb.payload}){raises} -> {cb.result}'
                cb.explicit.append(f'U: {MD} = downcast[R, _ResultType].Value')
                cb.type = f'_NativeBorrowRef[{cb.payload}, {cb.result}, {cb.error}, C, {kind == "raising"}, o]'
                cb.build = f'{cb.type}(Pointer(to=function))'
            cbs = [cb]
            if other is not None:
                secondary = operation.callbacks[1]
                cbs.append(callback(secondary.mode, other, secondary.argument, second=True))
            params = ([f'T: {MD}', f'Failure: {MD}'] if piped and not inferred_recovery else []) + sum((c.parameters for c in cbs), [])
            explicit = sum((c.explicit for c in cbs), [])
            if explicit:
                params += ['//', *explicit]
            conditions = ([f'Self.Value == {source}'] if piped else [])
            if mode != 'thunk' and not (name in ('attempt_tap', 'flat_tap_err') and kind != 'library'):
                conditions.append(f'{cb.payload} == '+primary.input(t, e, whole=source))
            if piped and name == 'or_else' and kind != 'library':
                conditions.append('R == Result[T, U]')
            conditions += operation.first_constraints(t, e, cb.result,
                value=lambda r: f'downcast[{r}, _ResultType].Value',
                failure=lambda r: f'downcast[{r}, _ResultType].Error')
            if name in ('flat_tap_err', 'attempt_tap') and kind != 'library':
                conditions.append('U == downcast[R, _ResultType].Value')
            if conditional:
                expected = operation.second_result(t, e)
                conditions += [f'{cb.result} == Bool', f'{cbs[1].payload} == '+operation.callbacks[1].input(t, e, whole=source), f'{cbs[1].result} == {expected}']
            result = operation.result(t, e, cb.result, value=lambda r: f'downcast[{r}, _ResultType].Value')
            error = operation.native_error(cb.error, cbs[1].error if conditional else None,
                pure_second=selective and other == 'pure')
            prelude = ''
            builds = ', '.join(c.build for c in cbs)
            if piped:
                body = f'return Piped(rebind_var[{source}](self.value^).{name}({builds}))'
                result = f'Piped[{result}]'
            elif kind != 'library' or (other is not None and other != 'library'):
                body = f'return self^.{name}({builds})'
            elif operation.sequence:
                sequence = SEQUENCING[name]
                adapter, build = sequence.adapt(t, cb.type, builds)
                if sequence.retain:
                    build = f'_ResultRetain[{t}, {e}, {adapter}, {sequence.paired}]({build})'
                body = f'return self^.flat_map({build})'
            elif conditional:
                handler = cbs[1].type if selective else f'_BorrowedUnary[{t}, {cbs[1].type}]'
                handler_value = cbs[1].build if selective else f'{handler}({cbs[1].build})'
                payload = e if selective else t
                body = f'return _conditional_result[{t}, {e}, {cb.type}, {handler}, {payload}, {cbs[1].result}, {cbs[1].error}, {error}, {not selective}, {name != "or_else_if"}, {selective}, _call_transform[{payload}, {handler}]](self^, {cb.build}, {handler_value})'
            elif name == 'tap_err':
                body = f'return self^.map_err(_ObserveOnce[{e}, {cb.type}, False]({builds}))'
            elif name == 'flat_tap_err':
                body = f'return self^.or_else(_ResultRetain[{t}, {e}, {cb.type}, False, False, True]({builds}))'
            elif name == 'attempt_tap':
                body = f'return _ResultRetain[{t}, {e}, {cb.type}, False, True]({builds}).call_once(self^)'
            elif name == 'recover':
                body = f'return _result_transform[{t}, {e}, {t}, {e}, {cb.type}, False, True, True]({builds}, self^)'
            else:
                raise ValueError(f'No Result implementation for {name}')
            if selective and other != 'library':
                if piped:
                    effect = '[Y=Y]' if other == 'raising' else ''
                    body = f'return Piped(rebind_var[{source}](self.value^).{name}{effect}({cb.build}, function))'
                else:
                    handler = cbs[1]
                    context = 'Pointer[G, q]'
                    prelude += f'        def invoke_recovery(var payload: {handler.payload}, var context: {context}) raises {handler.error} capturing -> {handler.result}:\n            return context[](payload^)\n'
                    body = f'return _conditional_result[{t}, {e}, {cb.type}, {context}, {handler.payload}, {handler.result}, {handler.error}, {error}, False, {name == "recover_if"}, True, invoke_recovery](self^, {cb.build}, Pointer(to=function))'
            # Owned Result callbacks already have a native-signature boundary.
            # Recovery selects Err but wraps the replacement in Ok in the same
            # transformation engine used by map/map_err.
            if mode == 'owned' and kind != 'library':
                if piped:
                    effect = '[X=X]' if kind == 'raising' else ''
                    body = f'return Piped(rebind_var[{source}](self.value^).{name}{effect}(function))'
                else:
                    prelude = f'        def invoke_recovery(var payload: {e}, callback: C) raises {error} capturing -> {t}:\n            return rebind_var[{t}](callback(rebind_var[{cb.payload}](payload^)))\n'
                    body = f'return _transform_result[{t}, {e}, {t}, {e}, {error}, False, True, {e}, {t}, C, invoke_recovery, True](self^, function)'
            if piped and name in ('map_err', 'or_else') and kind != 'library':
                # Mojo 1.2 crashes inferring the nested native Result overload.
                # The shared native view preserves the admitted signature and
                # lets Result use its existing library-callback boundary.
                adapter = f'_NativeUnaryRef[{cb.payload}, {cb.result}, {cb.error}, C, {kind == "raising"}, o]'
                body = f'return Piped(rebind_var[{source}](self.value^).{name}({adapter}(Pointer(to=function))))'
            if mode == 'thunk' and kind != 'library':
                if piped:
                    effect = '[X=X]' if kind == 'raising' else ''
                    body = f'return Piped(rebind_var[{source}](self.value^).{name}{effect}(function))'
                else:
                    thunk = f'_NativeThunkRef[{cb.result}, {error}, C, {kind == "raising"}, o]'
                    sequence = SEQUENCING[name]
                    adapter, build = sequence.adapt(t, thunk, f'{thunk}(Pointer(to=function))')
                    wrapper = f'_ResultRetain[{t}, {e}, {adapter}, {sequence.paired}]' if sequence.retain else f'_BorrowedUnary[{t}, {adapter}]'
                    body = f'return self^.flat_map({wrapper}({build}))'
            doc = summary
            if kind == 'library' and other in (None, 'library'):
                doc += '\n\n        '+detail+' Native errors propagate unchanged; they never become stored Err values. Native callbacks are borrowed in place; library callbacks are consumed and use their declared receiver mode.'
                doc += '\n\n        Parameters:\n'
                if piped: doc += '            T: The Result success type, including its origins.\n            Failure: The stored error type, including its origins.\n'
                doc += '            C: The callback type, retaining its receiver, input, result and native error.\n'
                if other: doc += '            G: The selected continuation type, retaining its receiver and native error.\n'
                doc += '\n        Args:\n'
                if selective: doc += '            predicate: The consumed borrowing predicate returning Bool.\n            function: The recovery, consumed and called only for matching errors; it consumes the stored error.\n'
                elif name == 'ensure': doc += '            predicate: The consumed borrowing predicate returning Bool.\n            make_error: The consumed borrowing factory returning the stored error type.\n'
                else: doc += '            function: The callback, consumed and invoked at most once on the selected branch.\n'
                doc += '\n        Returns:\n            '+summary+'\n\n        Raises:\n            The exact callback error; Never for non-raising callbacks. Two callbacks must share a native error type, or one must be non-raising.\n        '
            where = ' where '+' and '.join(conditions) if conditions else ''
            out.append(f'\n    def {name}[{", ".join(params)}](deinit self, {", ".join(c.argument for c in cbs)}) raises {error} -> {result}{where}:\n        """{doc}"""\n{prelude}        {body}\n')
    out.append(outcome_methods(piped))
    if not piped:
        out.append(terminal_methods())
    return ''.join(out)+'\n'




def terminal_methods():
    """Adapt native terminal callbacks to the owned Result implementation."""
    out = []
    for name, mode, argument, _ in RESULT_TERMINALS:
        # Fix closure errors before inference, as selected Pipeline does. A
        # custom closure error uses that existing .raising[X]() context.
        for kind in ('pure', 'never', 'error'):
            cb = callback(mode, 'pure' if kind == 'pure' else 'raising', argument)
            if kind != 'pure':
                cb.explicit = [p for p in cb.explicit if p != f'X: {MD}']
                cb = cb.renamed({'X': 'Never' if kind == 'never' else 'Error'})
            params = cb.parameters + ['//', *cb.explicit]
            conditions = ([f'{cb.payload} == Self.E'] if mode == 'owned' else [])
            conditions.append(f'{cb.result} == Self.T')
            out.append(f'\n    @always_inline\n    def {name}[{", ".join(params)}](deinit self, {cb.argument}) raises {cb.error} -> Self.T where {" and ".join(conditions)}:\n'
                       f'        """Native form of `{name}`; borrow the callback and keep its exact error."""\n'
                       f'        return self^.{name}({cb.build})\n')
        payloads = ['Self.E'] if mode == 'owned' else []
        # Thin signatures infer their error without trait-bound inference. Reuse
        # the shared ABI alternatives for register and memory return values.
        operands = [Operand(p, 'o') for p in payloads]
        for abi in variants(operands):
            params = [f'{p}: {bound}' for p, bound in abi.parameters] + [f'X: {MD}']
            signature = 'def(' + ', '.join(native_argument(p, 'o', thin=True) for p in abi.payloads) + ') raises X thin -> R'
            adapter = native_adapter(mode, payloads, 'R', 'X', f'type_of({argument})', True)
            conditions = [*abi.conditions, 'R == Self.T']
            out.append(f'\n    @always_inline\n    def {name}[{", ".join(params)}](deinit self, {argument}: {signature}) raises X -> Self.T where {" and ".join(conditions)}:\n'
                       f'        """Plain raising form of `{name}`; infer the exact native error."""\n'
                       f'        return self^.{name}({adapter}({argument}))\n')
    return ''.join(out)


def outcome_methods(piped=False):
    """Admission only: owned folds and _transformed own branch semantics."""
    out = []
    t, e = ('T', 'Failure') if piped else ('Self.T', 'Self.E')
    source = f'Result[{t}, {e}]'
    for name, (summary, detail) in OUTCOMES.items():
        operation = RESULT_OPERATIONS[name]
        primary, secondary = operation.callbacks
        for first, second in product(('library', 'pure', 'raising'), repeat=2):
            ok = callback(primary.mode, first, primary.argument)
            err = callback(secondary.mode, second, secondary.argument, second=True)
            # Infer native results independently before constraining equality.
            # Unifying them inside the native signature crashes Mojo 1.2 when
            # a positional family binding considers these Result overloads.
            # U/V remain available by name; C/X/G/Y retain their positions.
            # The source already fixes both input types. Spelling them directly
            # avoids Mojo 1.1 unifying distinct embedded origins while inferring
            # two independently renamed native signatures.
            for c, k, f, payload, arg_parameter in ((ok, first, 'C', t, 'A'), (err, second, 'G', e, 'Q')):
                if k == 'library': continue
                c.parameters = [p for p in c.parameters if not p.startswith(arg_parameter+':')]
                c.payload = payload
                raises = f' raises {c.error}' if k == 'raising' else ''
                c.explicit[-1] = f'{f}: def(var {payload}){raises} -> {c.result}'
            params = ([f'T: {MD}', f'Failure: {MD}'] if piped else []) + ok.parameters + err.parameters
            explicit = ok.explicit + err.explicit
            if name == 'redeem_with' and first != 'library':
                explicit += [f'U: {MD} = downcast[R, _ResultType].Value', f'V: {MD} = downcast[R, _ResultType].Error']
            if explicit: params += ['//', *explicit]
            where = ([f'Self.Value == {source}'] if piped else [])
            if name == 'redeem_with' and first != 'library':
                where.append('R == Result[U, V]')
            if first == 'library': where.append(f'{ok.payload} == {t}')
            if second == 'library': where.append(f'{err.payload} == {e}')
            if name != 'map_both': where.append(f'{ok.result} == {err.result}')
            if first != 'pure' and second != 'pure':
                where.append(operation.error_constraint(ok.error, err.error))
            error = operation.native_error(ok.error, err.error, pure_first=first == 'pure', pure_second=second == 'pure')
            result = operation.result(t, e, ok.result, err.result, value=lambda r: f'downcast[{r}, _ResultType].Value')
            prelude = ''
            if piped:
                effects = (['X=X'] if first == 'raising' else []) + (['Y=Y'] if second == 'raising' else [])
                if name == 'redeem_with' and first != 'library': effects += ['U=U', 'V=V']
                hints = '['+', '.join(effects)+']' if effects else ''
                args = ('on_ok^' if first == 'library' else 'on_ok')+', '+('on_err^' if second == 'library' else 'on_err')
                body = f'return Piped(rebind_var[{result}](rebind_var[{source}](self.value^).{name}{hints}({args})))'
                result = f'Piped[{result}]'
            else:
                contexts, builds, invokes = [], [], []
                for c, k, arg, f, origin, payload in ((ok, first, 'on_ok', 'C', 'o', t), (err, second, 'on_err', 'G', 'q', e)):
                    if k == 'library':
                        contexts.append(f); builds.append(arg+'^'); invokes.append(f'_call_transform[{payload}, {f}]')
                    else:
                        context = f'Pointer[{f}, {origin}]'
                        invoke = 'invoke_'+arg
                        prelude += f'        def {invoke}(var payload: {payload}, var context: {context}) raises {c.error} capturing -> {c.result}:\n            return context[](rebind_var[{c.payload}](payload^))\n'
                        contexts.append(context); builds.append(f'Pointer(to={arg})'); invokes.append(invoke)
                u = f'downcast[{ok.result}, _ResultType].Value' if name == 'redeem_with' else ok.result
                v = f'downcast[{ok.result}, _ResultType].Error' if name == 'redeem_with' else err.result if name == 'map_both' else e
                call = f'_result_both[{t}, {e}, {u}, {v}, {ok.result}, {err.result}, {ok.error}, {err.error}, {error}, {contexts[0]}, {contexts[1]}, {name != "redeem_with"}, {name != "map_both"}, {invokes[0]}, {invokes[1]}](self^, {builds[0]}, {builds[1]})'
                body = f'return rebind_var[{result}]({call})' if name == 'redeem_with' else f'return {call}'
            doc = summary
            if first == second == 'library':
                doc += '\n\n        '+detail+' Execution is immediate. Native handlers are borrowed in place; library handlers are consumed and use their declared receiver mode, including disposal of the skipped handler. Payloads, captures and native raised errors keep their ownership and origins. No Copyable requirement is added.'
                doc += '\n\n        Parameters:\n'
                if piped: doc += '            T: The source success type, including its origins.\n            Failure: The source stored error type, including its origins.\n'
                doc += '            C: The success handler type.\n            G: The error handler type.\n\n        Args:\n            on_ok: The handler consuming the success payload.\n            on_err: The handler consuming the error payload.\n\n        Returns:\n            '+summary+'\n\n        Raises:\n            The selected handler native error, unchanged. Both must share an error type, or one must be non-raising.\n        '
            constraint = ' where '+' and '.join(where) if where else ''
            out.append(f'\n    def {name}[{", ".join(params)}](deinit self, {ok.argument}, {err.argument}) raises {error} -> {result}{constraint}:\n        """{doc}"""\n{prelude}        {body}\n')
    return ''.join(out)
