def emit(name,params,args,result,condition,body,summary,details='',error=None,indent='',docs=True):
    p='['+', '.join(params)+']' if params else ''
    s=f'\n{indent}def {name}{p}({", ".join(args)})'
    if error: s+=f' raises {error}'
    s+=f' -> {result}'
    if condition:s+=' where '+condition
    s+=':\n'+indent+'    """'+summary+'\n'
    if docs:
        if details:s+='\n'+''.join(indent+'    '+line+'\n' for line in details.splitlines())
        named=[v.split(':',1)[0].lstrip('*') for v in params if v!='//']
        if named:
            s+='\n'+indent+'    Parameters:\n'
            s+=''.join(indent+'        '+n+': '+PARAMS.get(n, 'The admitted type parameter.')+'\n' for n in named)
        named=[v.split(':',1)[0].split()[-1].lstrip('*') for v in args if ':' in v]
        if named:
            s+='\n'+indent+'    Args:\n'+''.join(indent+'        '+n+': '+ARGS.get(n,'The operation argument.')+'\n' for n in named)
        s+='\n'+indent+'    Returns:\n'+indent+'        '+result+' with the ownership, timing and empty-input behavior described above.\n'
        if error:s+='\n'+indent+'    Raises:\n'+indent+'        The exact admitted callback or combination error; Never when non-raising.\n'
    s+=indent+'    """\n'+''.join(indent+'    '+x+'\n' for x in body.splitlines())
    return s

def prefixes(mode):
    out=''
    for name,taking in [('take_while',True),('drop_while',False)]:
        desc='Yield the initial matching prefix; consume and discard its first rejection.' if taking else 'Discard the matching prefix; yield the first rejection and stop testing.'
        for kind in ['thin','native','library','view']:
            shared = callback('borrow', 'view', 'predicate') if kind == 'view' else None
            params=list(shared.parameters) if shared else [f'T: {MD}'] if kind!='library' else [f'C: {callable_protocol("borrow", repeatable=True)}']
            if mode=='free':params += [f'V: {MD}']
            cb=shared.type if shared else 'C' if kind=='library' else 'def(T) thin -> Bool' if kind=='thin' else 'F'
            if kind=='native': params+=['//', 'F: _LazyPredicate[T]']
            metadata=callable_metadata('borrow', shared.type if shared else 'C') if kind in ('library','view') else None
            t=f'downcast[{metadata.inputs[0]}, {MD}]' if metadata else 'T'
            it='_Source[V]' if mode=='free' else 'Self.I'
            condition=it+'.Element == '+t
            if metadata:condition+=f' and {metadata.result} == Bool and {metadata.error} == Never'
            args=[shared.argument if shared else 'var predicate: '+cb]+(['var source: V'] if mode=='free' else [])
            result=f'{"Take" if taking else "Drop"}WhileIterator[{t}, {it}, {cb}]'
            build=shared.build if shared else 'predicate'+('' if kind=='thin' else '^')
            call=f'_Prefix[{t}, {it}, {cb}, {taking}]({build}, _source(source^), True, False)' if mode=='free' else f'_{name}({build}, self._iterator^)'
            if mode!='free':args.insert(0,'deinit self'); result=f'Iter[{result}]';call=f'Iter({call})'
            out+=emit(name,params,args,result,condition,'return '+call,desc,'Construction pulls nothing. The stored predicate borrows each candidate and cannot raise.\nExhaustion is fused; abandonment releases captures and the unconsumed source.\nUses constant state and preserves move-only elements and embedded origins.',indent='' if mode=='free' else '    ',docs=kind=='thin')
    return out

def indexed(mode):
    out=''
