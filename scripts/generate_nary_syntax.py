"""Native n-argument boundaries and bounded type inference; execution is shared."""
from native_signatures import native_dispatch, native_invocation, argument

MD = 'Movable & Deinitable'
MAX = 8
START = '# --- n-ary type inference (generated) ---\n'
END = '# --- end n-ary type inference ---\n'
HEADER = '# Generated by scripts/generate_nary_syntax.py; only native type descriptions live here.\n'


def types():
    out = [f'''\nstruct _ProductTypes[I: Applicative, V: {MD}, *Ws: {MD}]:
    # Finite native boundaries describe types through canonical contracts;
    # _ProductRun owns all sequencing, cleanup and errors.
    comptime Run = _ProductRun[Self.I, Self.V, *Self.Ws]
    comptime C0 = MapContract[Self.I, Self.V, _Singleton[Self.I.Element[Self.V]]]
    comptime S0 = Self.C0.Out
    comptime E0 = Self.C0.Error
''']
    for n in range(1, MAX):
        step = f'_AppendTuple[Self.I.Element[Self.Ws[{n-1}]], Self.I.Element[Self.V]' + ''.join(f', Self.I.Element[Self.Ws[{i}]]' for i in range(n-1)) + ']'
        out.append(f'    comptime C{n} = Map2Contract[Self.I, Self.S{n-1}, Self.Ws[{n-1}], {step}]\n')
        out.append(f'    comptime S{n}: {MD} = Self.C{n}.Out if Self.Ws.length >= {n} else Self.S{n-1}\n')
        out.append(f'    comptime E{n}: {MD} = _CommonError[Self.E{n-1}, Self.C{n}.Error] if Self.Ws.length >= {n} else Self.E{n-1}\n')
    out.append(f'    comptime Out = Self.S{MAX-1}\n    comptime Error = Self.E{MAX-1}\n')
    out.append(f'''\nstruct _MapNTypes[I: Applicative, V: {MD}, F: UnaryContract & {MD}, *Ws: {MD}]:
    comptime Product = _ProductTypes[Self.I, Self.V, *Self.Ws]
    comptime Mapping = MapContract[Self.I, Self.Product.Out, Self.F]
    comptime Out = Self.Mapping.Out
    comptime Error = _CommonError[Self.Product.Error, Self.Mapping.Error]
''')
    return ''.join(out)+'\n'


def native():
    out = ['''"""Generated native tuple application boundaries; do not edit by hand.

Mojo distinguishes a fixed native signature from a variadic pack signature.
Each arity adapts that native call to Unary over a tuple; family execution stays
in algebra._nary. Native Tuple.consume_elements moves the inputs into untagged
slots; every slot is consumed before the possibly raising native call.
"""
from std.builtin.rebind import downcast, rebind_var
from std.memory import MaybeUninit
from .protocols import Unary
from .products import _call_pair_as, _OptionalCell
from .native import _NativeOwnedArg, _call_native, _NativeBinaryRef, _Unary, _RaisingUnary, _Binary, _RaisingBinary
''']
    for n in range(1,MAX+1):
        names=[f'A{i}' for i in range(n)]
        params=', '.join(f'{a}: {MD}' for a in names)
        args=', '.join(argument(a, 'o') for a in names)
        ts=', '.join(names)
        pure_sig = f'_Unary[{ts}, R]' if n == 1 else f'_Binary[{ts}, R]' if n == 2 else f'def({args}) -> R'
        raising_sig = f'_RaisingUnary[{ts}, R, X]' if n == 1 else f'_RaisingBinary[{ts}, R, X]' if n == 2 else f'def({args}) raises X -> R'
        out.append(f'\ncomptime _Nary{n}[{params}, R: {MD}] = {pure_sig}\n')
        out.append(f'comptime _RaisingNary{n}[{params}, R: {MD}, X: {MD}] = {raising_sig}\n')
        out.append(f'''\n@fieldwise_init
struct _NativeNary{n}[{params}, R: {MD}, X: {MD}, F: {MD}, raising: Bool, o: ImmOrigin](Unary, ImplicitlyCopyable):
    comptime Arg = Tuple[{', '.join('Self.'+a for a in names)}]
    comptime Out = Self.R
    comptime Error = Self.X
    var function: Pointer[Self.F, Self.o]
    def call(self, var arg: Self.Arg) raises Self.X -> Self.R:
''')
        own=', '.join('Self.'+a for a in names)
        if n == 2:
            out.append('        return _call_pair_as[Self.X](_NativeBinaryRef[Self.A0, Self.A1, Self.R, Self.X, Self.F, Self.raising, Self.o](self.function), arg^)\n')
        else:
            out.extend(f'        var slot{i} = MaybeUninit[Self.A{i}]()\n' for i in range(n))
            captures=', '.join(f'ref slot{i}' for i in range(n))
            out.append(f'        def store[index: Int](var value: Self.Arg.Ts[index]) {{{captures}}}:\n')
            for i in range(n):
                if n == 1:
                    out.append('            slot0.unsafe_ptr().unsafe_write(rebind_var[Self.A0](value^))\n')
                else:
                    branch = f'comptime if index == {i}' if i == 0 else 'else' if i == n-1 else f'elif index == {i}'
                    out.append(f'            {branch}:\n                slot{i}.unsafe_ptr().unsafe_write(rebind_var[Self.A{i}](value^))\n')
            out.append('        arg^.consume_elements(store)\n')
            out.extend(f'        var a{i} = slot{i}^.unsafe_assume_init()\n' for i in range(n))
            invocation = native_invocation(
                "o" * n, ["Self." + name for name in names],
                [f"a{i}" for i in range(n)], result="Self.R", error="Self.X",
                function_type="Self.F", function="self.function[]", raising="Self.raising",
            )
            if invocation is not None:
                out.append(f'        return {invocation}\n')
            else:
                out.append(native_dispatch(
                    "o" * n, ["Self." + name for name in names],
                    [f"a{i}" for i in range(n)], result="Self.R", error="Self.X",
                    function_type="Self.F", function="self.function[]",
                    raising="Self.raising", indent="        ", known_owned=True,
                ))
        out.append(f'''
struct _OwnedNativeNary{n}[{params}, R: {MD}, X: {MD}, F: {MD}, raising: Bool](Unary, Copyable where conforms_to(F, Copyable)):
    # Deferred families retain the pointer value, never a borrow of its local
    # variable. The existing adapter still owns tuple extraction and invocation.
    comptime Arg = Tuple[{own}]
    comptime Out = Self.R
    comptime Error = Self.X
    var _function: _OptionalCell[Self.F]
    def __init__(out self, var function: Self.F):
        self._function = Optional(function^)
    def call(self, var arg: Self.Arg) raises Self.X -> Self.R:
        ref function = self._function.value()
        return _NativeNary{n}[{own}, Self.R, Self.X, Self.F, Self.raising, origin_of(function)](Pointer(to=function)).call(arg^)
''')
    return ''.join(out)
