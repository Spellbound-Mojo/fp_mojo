"""Native n-argument boundaries and bounded type inference; execution is shared."""
from native_signatures import native_dispatch, native_invocation, argument

MD = 'Movable & Deinitable'
MAX = 8
START = '# --- n-ary type inference (generated) ---\n'
END = '# --- end n-ary type inference ---\n'
HEADER = '# Generated by scripts/generate_nary_syntax.py; only native type descriptions live here.\n'


def types():
    out = [f'''\nstruct _ProductTypes[I: Applicative, V: {MD}, *Ws: {MD}]:
    # Finite native boundaries describe types through canonical contracts;
    # _ProductRun owns all sequencing, cleanup and errors.
    comptime Run = _ProductRun[Self.I, Self.V, *Self.Ws]
    comptime C0 = MapContract[Self.I, Self.V, _Singleton[Self.I.Element[Self.V]]]
    comptime S0 = Self.C0.Out
    comptime E0 = Self.C0.Error
''']
    for n in range(1, MAX):
        step = f'_AppendTuple[Self.I.Element[Self.Ws[{n-1}]], Self.I.Element[Self.V]' + ''.join(f', Self.I.Element[Self.Ws[{i}]]' for i in range(n-1)) + ']'
        out.append(f'    comptime C{n} = Map2Contract[Self.I, Self.S{n-1}, Self.Ws[{n-1}], {step}]\n')
        out.append(f'    comptime S{n}: {MD} = Self.C{n}.Out if Self.Ws.length >= {n} else Self.S{n-1}\n')
        out.append(f'    comptime E{n}: {MD} = _CommonError[Self.E{n-1}, Self.C{n}.Error] if Self.Ws.length >= {n} else Self.E{n-1}\n')
    out.append(f'    comptime Out = Self.S{MAX-1}\n    comptime Error = Self.E{MAX-1}\n')
    out.append(f'''\nstruct _MapNTypes[I: Applicative, V: {MD}, F: UnaryContract & {MD}, *Ws: {MD}]:
    comptime Product = _ProductTypes[Self.I, Self.V, *Self.Ws]
    comptime Mapping = MapContract[Self.I, Self.Product.Out, Self.F]
    comptime Out = Self.Mapping.Out
    comptime Error = _CommonError[Self.Product.Error, Self.Mapping.Error]
''')
    return ''.join(out)+'\n'


def native():
    out = ['''"""Generated native tuple application boundaries; do not edit by hand.

Mojo distinguishes a fixed native signature from a variadic pack signature.
Each arity adapts that native call to Unary over a tuple; family execution stays
in algebra._nary. Native Tuple.consume_elements moves the inputs into untagged
slots; every slot is consumed before the possibly raising native call.
"""
from std.builtin.rebind import downcast, rebind_var
from std.memory import MaybeUninit
from .protocols import Unary
from .products import _take_pair, _OptionalCell
from .native import _NativeOwnedArg, _call_native, _call_native_binary, _Unary, _RaisingUnary, _Binary, _RaisingBinary
''']
    for n in range(1,MAX+1):
        names=[f'A{i}' for i in range(n)]
        params=', '.join(f'{a}: {MD}' for a in names)
        args=', '.join(argument(a, 'o') for a in names)
        ts=', '.join(names)
        pure_sig = f'_Unary[{ts}, R]' if n == 1 else f'_Binary[{ts}, R]' if n == 2 else f'def({args}) -> R'
        raising_sig = f'_RaisingUnary[{ts}, R, X]' if n == 1 else f'_RaisingBinary[{ts}, R, X]' if n == 2 else f'def({args}) raises X -> R'
        out.append(f'\ncomptime _Nary{n}[{params}, R: {MD}] = {pure_sig}\n')
        out.append(f'comptime _RaisingNary{n}[{params}, R: {MD}, X: {MD}] = {raising_sig}\n')
        out.append(f'''\n@fieldwise_init
struct _NativeNary{n}[{params}, R: {MD}, X: {MD}, F: {MD}, raising: Bool, o: ImmOrigin](Unary, ImplicitlyCopyable):
    comptime Arg = Tuple[{', '.join('Self.'+a for a in names)}]
    comptime Out = Self.R
    comptime Error = Self.X
    var function: Pointer[Self.F, Self.o]
    def call(self, var arg: Self.Arg) raises Self.X -> Self.R:
''')
        out.extend(f'        var slot{i} = MaybeUninit[Self.A{i}]()\n' for i in range(n))
        if n == 2:
            out.append('        _take_pair(arg^, slot0, slot1)\n')
        else:
            captures=', '.join(f'ref slot{i}' for i in range(n))
            out.append(f'        def store[index: Int](var value: Self.Arg.Ts[index]) {{{captures}}}:\n')
            for i in range(n):
                if n == 1:
                    out.append('            slot0.unsafe_ptr().unsafe_write(rebind_var[Self.A0](value^))\n')
                else:
                    branch = f'comptime if index == {i}' if i == 0 else 'else' if i == n-1 else f'elif index == {i}'
                    out.append(f'            {branch}:\n                slot{i}.unsafe_ptr().unsafe_write(rebind_var[Self.A{i}](value^))\n')
            out.append('        arg^.consume_elements(store)\n')
        out.extend(f'        var a{i} = slot{i}^.unsafe_assume_init()\n' for i in range(n))
        own=', '.join('Self.'+a for a in names)
        invocation = native_invocation(
            "o" * n, ["Self." + name for name in names],
            [f"a{i}" for i in range(n)], result="Self.R", error="Self.X",
            function_type="Self.F", function="self.function[]", raising="Self.raising",
        )
        if invocation is not None:
            out.append(f'        return {invocation}\n')
        else:
            out.append(native_dispatch(
                "o" * n, ["Self." + name for name in names],
                [f"a{i}" for i in range(n)], result="Self.R", error="Self.X",
                function_type="Self.F", function="self.function[]",
                raising="Self.raising", indent="        ", known_owned=True,
            ))
        out.append(f'''
struct _OwnedNativeNary{n}[{params}, R: {MD}, X: {MD}, F: {MD}, raising: Bool](Unary, Copyable where conforms_to(F, Copyable)):
    # Deferred families retain the pointer value, never a borrow of its local
    # variable. The existing adapter still owns tuple extraction and invocation.
    comptime Arg = Tuple[{own}]
    comptime Out = Self.R
    comptime Error = Self.X
    var _function: _OptionalCell[Self.F]
    def __init__(out self, var function: Self.F):
        self._function = Optional(function^)
    def call(self, var arg: Self.Arg) raises Self.X -> Self.R:
        ref function = self._function.value()
        return _NativeNary{n}[{own}, Self.R, Self.X, Self.F, Self.raising, origin_of(function)](Pointer(to=function)).call(arg^)
''')
    return ''.join(out)


def methods(*, result=False, explicit=False, parallel=False):
    # Mojo cannot infer the variadic carrier pack behind an optional positional
    # validation policy. Build its explicit and inferred boundaries separately,
    # retaining product-before-map order and their existing parameter positions.
    policy = 'S'
    sections = [_method_sections(result=result, explicit=explicit, parallel=parallel, policy=policy)]
    if parallel:
        value = 'Self' if result else 'Self.Value'
        sections.append(_method_sections(result=result, explicit=explicit, parallel=True,
                                         policy=f'_ListErrors[{value}]', native=False))
    return ''.join(section[index] for index in range(3) for section in sections)


def _method_sections(*, result, explicit, parallel, policy, native=True):
    value = 'Self' if result else 'Self.Value'
    family = 'I' if explicit else 'ResultFamily[Self.E]' if result else '_InferredApplicative[Self.Value]'
    if parallel:
        family = f'ValidationFamily[{policy}]'
    name = 'par_map_n' if parallel else 'map_n'
    admission_family = 'ResultFamily[Self.E]' if parallel and result else family
    source = 'self^' if result else 'self.value^'
    wrap = (lambda s:s) if result else (lambda s:f'Piped[{s}]')
    ret = (lambda s:s) if result else (lambda s:f'Piped({s})')

    def products(operands):
        arguments = ', '.join([family, value, *operands])
        run = f'_ProductRun[{arguments}]'
        product = f'_ProductTypes[{arguments}].Out' if explicit else f'{family}.Pure[{run}.Payload]'
        admitted = f'_ProductRun[{", ".join([admission_family, value, *operands])}]'
        return run, product, admitted

    def conditions(admitted, *, fixed=False):
        # A fixed tuple exposes arity before native callback inference. Keeping
        # the old variadic native boundary too would reintroduce ambiguity.
        checks = ([] if fixed else [f'Ws.length < {MAX}']) if explicit else [f'{admitted}.NativeInputs']
        if parallel and result:
            checks.append(f'Self.E == {policy}.Value')
        if not result and not explicit:
            element = f'{family}.Element[Self.Value]'
            checks.insert(0, f'Self.Value == {family}.Pure[{element}]')
        return checks

    run, product, admitted = products(['*Ws'])
    perror = f'_ProductTypes[{family}, {value}, *Ws].Error' if explicit else f'({policy}.Error if Ws.length > 0 else Never)' if parallel else 'Never'
    parameters = ['I: Applicative'] if explicit else ['S: Semigroup'] if parallel and policy == 'S' else []
    parameters.append(f'*Ws: {MD}')
    parameter_doc = ('            I: The explicit Applicative family; at most eight operands in total.\n' if explicit else
                     '            S: The error Semigroup; inferred list errors concatenate by default.\n' if parallel and policy == 'S' else '')
    product_result_doc = ('            A Result of a flat tuple in receiver-first order, or accumulated\n'
                          '            stored errors. No additional operands produces a one-element tuple.' if parallel else
                          '            The family of flat tuples in receiver-first order. No additional\n'
                          '            operands produces one-element tuples. List uses Cartesian ordering.')
    product_error_doc = ('            The exact error-combination error; Never with no additional\n'
                         '            operands. Stored Result errors remain data.' if parallel else
                         '            The exact family construction error; stored Result errors remain data.')
    product_method = f'''
    def {'par_product_n' if parallel else 'product_n'}[{', '.join(parameters)}](deinit self, var others: Tuple[*Ws]) raises {perror} -> {wrap(product)} where {' and '.join(conditions(admitted))}:
        """Combine the receiver and additional operands into flat tuples.

        Parameters:
{parameter_doc}            Ws: The exact additional carrier types, including origins.

        Args:
            others: The tuple of already evaluated additional operands, consumed.

        Returns:
{product_result_doc}

        Raises:
{product_error_doc}
        """
        return {ret(f'{run}.run[{product}, {perror}]({source}, others^)')}
'''
    # Library callbacks keep their variadic pack and Unary receiver modes.
    parameters = [f'F: UnaryContract & {MD}', *(['//'] if explicit or (parallel and policy == 'S') else []), *parameters]
    mp = f'_MapNTypes[{family}, {value}, F, *Ws]'
    output = f'{mp}.Out' if explicit else f'{family}.Pure[F.Out]'
    error = f'{mp}.Error' if explicit else f'(_CommonError[{policy}.Error, F.Error] if Ws.length > 0 else F.Error)' if parallel else 'F.Error'
    checks = conditions(admitted)
    if parallel:
        checks.append(f'(_ErrorCompatible[_CommonError[{policy}.Error, F.Error], F.Error] if Ws.length > 0 else True)')
    checks.append(f'F.Arg == {admitted}.Payload')
    call = f'_map_n_as[{family}, {product}, {output}, {error}](function^, {source}, others^)'
    summary = ('Combine independent Results, accumulating their stored errors in order.' if parallel else
               'Combine operands, then map a callback over each flat tuple of payloads.')
    map_result_doc = ('            A Result of the callback output, or all stored errors combined in\n'
                      '            receiver-first order. The callback runs once only if every input is Ok.' if parallel else
                      '            The family of callback results; absence or failure skips the callback.\n'
                      '            List materializes the Cartesian tuples before mapping them in order.')
    library_method = f'''
    def {name}[{', '.join(parameters)}](deinit self, var others: Tuple[*Ws], var function: F) raises {error} -> {wrap(output)} where {' and '.join(checks)}:
        """{summary}

        Native callbacks take one argument per operand, from one to eight.
        Library Unary callbacks consume the whole tuple in their receiver mode.

        Parameters:
            F: The tuple callback, retaining its exact argument, result and error.
{parameter_doc}            Ws: The exact additional carrier types, including origins.

        Args:
            others: The already evaluated additional operands, consumed.
            function: The callback, consumed; native callbacks are borrowed.

        Returns:
{map_result_doc}

        Raises:
            The exact callback or family construction error, without conversion.
        """
        return {ret(call)}
'''
    native_methods = []
    for n in range(1, MAX + 1) if native else ():
        names = ['A'] if n == 1 else ['A', 'B'] if n == 2 else [f'A{i}' for i in range(n)]
        operands = [f'W{i}' for i in range(n - 1)]
        _, product, admitted = products(operands)
        for raising in (False, True):
            error = 'X' if raising else 'Never'
            inferred = [*[f'{a}: {MD}' for a in names], f'R: {MD}', 'o: ImmOrigin']
            explicit_parameters = ['I: Applicative'] if explicit else []
            if raising:
                explicit_parameters.append(f'X: {MD}')
            sig = f'_RaisingNary{n}[{", ".join(names)}, R, X]' if raising else f'_Nary{n}[{", ".join(names)}, R]'
            if n <= 2:
                prefix = '_RaisingUnary' if n == 1 and raising else '_Unary' if n == 1 else '_RaisingBinary' if raising else '_Binary'
                sig = f'{prefix}[{", ".join(names)}, R' + (', X]' if raising else ']')
            explicit_parameters.append('F: ' + sig)
            if parallel:
                # Validation fixes its native callback before the explicit
                # optional policy, unlike the ordinary Applicative boundary.
                inferred.extend(explicit_parameters)
                explicit_parameters = [f'S: Semigroup = _ListErrors[{value}]']
            inferred.extend(f'{operand}: {MD}' for operand in operands)
            parameters = [*inferred, '//', *explicit_parameters]
            cb = f'_NativeNary{n}[{", ".join(names)}, R, {error}, F, {raising}, o]'
            mp = f'_MapNTypes[{", ".join([family, value, cb, *operands])}]'
            output = f'{mp}.Out' if explicit else f'{family}.Pure[R]'
            raised = f'{mp}.Error' if explicit else f'_CommonError[{policy}.Error, {error}]' if parallel and n > 1 else error
            checks = conditions(admitted, fixed=True)
            checks.append(f'{admission_family}.Element[{value}] == {names[0]}')
            checks.extend(f'{admission_family}.Element[{operand}] == {name}' for operand, name in zip(operands, names[1:]))
            if parallel and n > 1:
                checks.append(f'_ErrorCompatible[{raised}, {error}]')
            call = f'_map_n_as[{family}, {product}, {output}, {raised}]({cb}(Pointer(to=function)), {source}, others^)'
            arguments = ['deinit self', f'var others: Tuple[{", ".join(operands)}]', 'ref[o] function: F']
            native_methods.append(f'''
    def {name}[{', '.join(parameters)}]({', '.join(arguments)}) raises {raised} -> {wrap(output)} where {' and '.join(checks)}:
        """Combine {n} operands and call the native callback with separate arguments."""
        return {ret(call)}
''')
    return product_method, library_method, ''.join(native_methods)
