"""Native n-argument boundaries and bounded type inference; execution is shared."""
import re

MD = 'Movable & Deinitable'
MAX = 8
START = '# --- n-ary type inference (generated) ---\n'
END = '# --- end n-ary type inference ---\n'
HEADER = '# Generated by scripts/generate_nary_syntax.py; only native type descriptions live here.\n'


def types():
    out = [f'''\nstruct _ProductTypes[I: Applicative, V: {MD}, *Ws: {MD}]:
    # Mojo 1.1 rejects recursive associated aliases. Name the finite native
    # boundaries here; _ProductRun owns all sequencing, cleanup and errors.
    comptime Run = _ProductRun[Self.I, Self.V, *Self.Ws]
    comptime S0 = Self.I.Mapped[Self.V, _Singleton[Self.I.Element[Self.V]]]
    comptime E0 = Self.I.MapError[Self.V, _Singleton[Self.I.Element[Self.V]]]
''']
    for n in range(1, MAX):
        step = f'_AppendTuple[Self.I.Element[Self.Ws[{n-1}]], Self.I.Element[Self.V]' + ''.join(f', Self.I.Element[Self.Ws[{i}]]' for i in range(n-1)) + ']'
        out.append(f'    comptime S{n}: {MD} = Self.I.Combined[Self.S{n-1}, {step}, _ValueThunk[Self.Ws[{n-1}]]] if Self.Ws.length >= {n} else Self.S{n-1}\n')
        out.append(f'    comptime E{n}: {MD} = _CommonError[Self.E{n-1}, Self.I.CombineError[Self.S{n-1}, {step}, _ValueThunk[Self.Ws[{n-1}]]]] if Self.Ws.length >= {n} else Self.E{n-1}\n')
    out.append(f'    comptime Out = Self.S{MAX-1}\n    comptime Error = Self.E{MAX-1}\n')
    out.append(f'''\nstruct _MapNTypes[I: Applicative, V: {MD}, F: UnaryContract & {MD}, *Ws: {MD}]:
    comptime Product = _ProductTypes[Self.I, Self.V, *Self.Ws]
    comptime Out = Self.I.Mapped[Self.Product.Out, Self.F]
    comptime Error = _CommonError[Self.Product.Error, Self.I.MapError[Self.Product.Out, Self.F]]
''')
    return ''.join(out)+'\n'


def native():
    out = ['''"""Generated native tuple application boundaries; do not edit by hand.

Mojo distinguishes a fixed native signature from a variadic pack signature.
Each arity adapts that native call to Unary over a tuple; family execution stays
in algebra._nary. Native Tuple.consume_elements moves the inputs into untagged
slots; every slot is consumed before the possibly raising native call.
"""
from std.builtin.rebind import downcast, rebind_var
from std.memory import MaybeUninit
from .protocols import Unary
from .products import _take_pair
from .native import _call_native, _call_native_binary, _Unary, _RaisingUnary, _Binary, _RaisingBinary
''']
    for n in range(1,MAX+1):
        names=[f'A{i}' for i in range(n)]
        params=', '.join(f'{a}: {MD}' for a in names)
        args=', '.join('var '+a for a in names)
        ts=', '.join(names)
        pure_sig = f'_Unary[{ts}, R]' if n == 1 else f'_Binary[{ts}, R]' if n == 2 else f'def({args}) -> R'
        raising_sig = f'_RaisingUnary[{ts}, R, X]' if n == 1 else f'_RaisingBinary[{ts}, R, X]' if n == 2 else f'def({args}) raises X -> R'
        out.append(f'\ncomptime _Nary{n}[{params}, R: {MD}] = {pure_sig}\n')
        out.append(f'comptime _RaisingNary{n}[{params}, R: {MD}, X: {MD}] = {raising_sig}\n')
        if n >= 3:
            for raising in (False, True):
                kind = '_raising' if raising else ''
                sig = f'_RaisingNary{n}[{ts}, R, X]' if raising else f'_Nary{n}[{ts}, R]'
                ep = f', X: {MD}' if raising else ''
                raised = ' raises X' if raising else ''
                runtime = ', '.join(f'var a{i}: A{i}' for i in range(n))
                passed = ', '.join(f'a{i}^' for i in range(n))
                out.append(f'\ndef _native_nary{n}{kind}[{params}, R: {MD}{ep}, F: {sig}](function: F, {runtime}){raised} -> R:\n    return function({passed})\n')
        out.append(f'''\n@fieldwise_init
struct _NativeNary{n}[{params}, R: {MD}, X: {MD}, F: {MD}, raising: Bool, o: ImmOrigin](Unary, ImplicitlyCopyable):
    comptime Arg = Tuple[{', '.join('Self.'+a for a in names)}]
    comptime Out = Self.R
    comptime Error = Self.X
    var function: Pointer[Self.F, Self.o]
    def call(self, var arg: Self.Arg) raises Self.X -> Self.R:
''')
        out.extend(f'        var slot{i} = MaybeUninit[Self.A{i}]()\n' for i in range(n))
        if n == 2:
            out.append('        _take_pair(arg^, slot0, slot1)\n')
        else:
            out.append('        def store[index: Int](var value: Self.Arg.Ts[index]) capturing:\n')
            for i in range(n):
                if n == 1:
                    out.append('            slot0.unsafe_ptr().unsafe_write(rebind_var[Self.A0](value^))\n')
                else:
                    branch = f'comptime if index == {i}' if i == 0 else 'else' if i == n-1 else f'elif index == {i}'
                    out.append(f'            {branch}:\n                slot{i}.unsafe_ptr().unsafe_write(rebind_var[Self.A{i}](value^))\n')
            out.append('        arg^.consume_elements[store]()\n')
        out.extend(f'        var a{i} = slot{i}^.unsafe_assume_init()\n' for i in range(n))
        values=', '.join(f'a{i}^' for i in range(n))
        own=', '.join('Self.'+a for a in names)
        if n<=2:
            fn='_call_native' if n==1 else '_call_native_binary'
            out.append(f'        return {fn}[{own}, Self.R, Self.X, Self.F, Self.raising](self.function[], {values})\n')
        else:
            for raising in (True,False):
                out.append('        comptime if Self.raising:\n' if raising else '        else:\n')
                sig=f'_RaisingNary{n}[{own}, Self.R, Self.X]' if raising else f'_Nary{n}[{own}, Self.R]'
                out.append(f'            comptime Fn = downcast[Self.F, {sig}]\n')
                checks=[f'Fn.A{i} == Self.A{i}' for i in range(n)]+['Fn.R == Self.R', 'Fn.X == Self.X' if raising else 'Self.X == Never']
                out.append('            comptime assert '+' and '.join(checks)+'\n')
                suffix = '_raising' if raising else ''
                ep = ', Self.X' if raising else ''
                out.append(f'            return _native_nary{n}{suffix}[{own}, Self.R{ep}, Fn](rebind[Fn](self.function[]), {values})\n')
    return ''.join(out)


def validation_overloads(method, value):
    # Mojo 1.1 cannot infer a variadic pack behind an optional positional
    # policy for owned arguments. Both boundaries delegate to the same runner.
    policy = f'S: Semigroup = _ListErrors[{value}]'
    explicit = method.replace(policy, 'S: Semigroup')
    inferred = method.replace(f'//, {policy}, ', '').replace(f'{policy}, ', '')
    inferred = inferred.replace('            S: The error Semigroup; inferred list errors concatenate by default.\n', '')
    return [explicit, re.sub(r'\bS\b', f'_ListErrors[{value}]', inferred)]


def methods(*, result=False, explicit=False, parallel=False):
    value = 'Self' if result else 'Self.Value'
    family = 'I' if explicit else 'ResultFamily[Self.E]' if result else '_InferredApplicative[Self.Value]'
    if parallel:
        family = 'ValidationFamily[S]'
    name = 'par_map_n' if parallel else 'map_n'
    run = f'_ProductRun[{family}, {value}, *Ws]'
    product = f'_ProductTypes[{family}, {value}, *Ws].Out' if explicit else f'{family}.Pure[{run}.Payload]'
    perror = f'_ProductTypes[{family}, {value}, *Ws].Error' if explicit else '(S.Error if Ws.length > 0 else Never)' if parallel else 'Never'
    admission_family = 'ResultFamily[Self.E]' if parallel and result else family
    admitted = f'_ProductRun[{admission_family}, {value}, *Ws]'
    where = f'Ws.length < {MAX}' if explicit else f'{admitted}.NativeInputs'
    if parallel and result: where += ' and Self.E == S.Value'
    if not result and not explicit:
        element = f'{family}.Element[Self.Value]'
        where = f'Self.Value == {family}.Pure[{element}] and ' + where
    source = 'self^' if result else 'self.value^'
    wrap = (lambda s:s) if result else (lambda s:f'Piped[{s}]')
    ret = (lambda s:s) if result else (lambda s:f'Piped({s})')
    par = f'I: Applicative, *Ws: {MD}' if explicit else f'*Ws: {MD}'
    if parallel:
        par = f'S: Semigroup = _ListErrors[{value}], *Ws: {MD}'
    out = [f'''
    def {'par_product_n' if parallel else 'product_n'}[{par}](deinit self, var others: Tuple[*Ws]) raises {perror} -> {wrap(product)} where {where}:
        """Combine the receiver and additional operands into flat tuples.

        Parameters:
{('            I: The explicit Applicative family; at most eight operands in total.\n' if explicit else '            S: The error Semigroup; inferred list errors concatenate by default.\n' if parallel else '')}            Ws: The exact additional carrier types, including origins.

        Args:
            others: The tuple of already evaluated additional operands, consumed.

        Returns:
            The family of flat tuples in receiver-first order. No additional
            operands produces one-element tuples. List uses Cartesian ordering.

        Raises:
            The exact family construction error; stored Result errors remain data.
        """
        return {ret(f'{run}.run[{product}, {perror}]({source}, others^)')}
''']
    if parallel:
        out = validation_overloads(out[0], value)
    # Library callbacks retain the existing Unary receiver modes over one tuple.
    par = f'F: UnaryContract & {MD}, ' + ('//, ' if explicit or parallel else '') + par
    mp = f'_MapNTypes[{family}, {value}, F, *Ws]'
    output = f'{mp}.Out' if explicit else f'{family}.Pure[F.Out]'
    error = f'{mp}.Error' if explicit else '(_CommonError[S.Error, F.Error] if Ws.length > 0 else F.Error)' if parallel else 'F.Error'
    if parallel:
        where += ' and (_ErrorCompatible[_CommonError[S.Error, F.Error], F.Error] if Ws.length > 0 else True)'
    call = f'_map_n_as[{family}, {product}, {output}, {error}](function^, {source}, others^)'
    library = f'''
    def {name}[{par}](deinit self, var others: Tuple[*Ws], var function: F) raises {error} -> {wrap(output)} where {where} and F.Arg == {admitted}.Payload:
        """Combine operands, then map a callback over each flat tuple of payloads.

        Native callbacks take one argument per operand, from one to eight.
        Library Unary callbacks consume the whole tuple in their receiver mode.

        Parameters:
            F: The tuple callback, retaining its exact argument, result and error.
{('            I: The explicit Applicative family; at most eight operands in total.\n' if explicit else '            S: The error Semigroup; inferred list errors concatenate by default.\n' if parallel else '')}            Ws: The exact additional carrier types, including origins.

        Args:
            others: The already evaluated additional operands, consumed.
            function: The callback, consumed; native callbacks are borrowed.

        Returns:
            The family of callback results; absence or failure skips the callback.
            List materializes the Cartesian tuples before mapping them in order.

        Raises:
            The exact callback or family construction error, without conversion.
        """
        return {ret(call)}
'''
    if parallel:
        out.extend(validation_overloads(library, value))
    else:
        out.append(library)
    if parallel:
        where = where.replace(' and (_ErrorCompatible[_CommonError[S.Error, F.Error], F.Error] if Ws.length > 0 else True)', '')
    for n in range(1,MAX+1):
        names=['A'] if n == 1 else ['A','B'] if n == 2 else [f'A{i}' for i in range(n)]
        for raising in (False,True):
            error='X' if raising else 'Never'
            params=[*[f'{a}: {MD}' for a in names], f'R: {MD}', 'o: ImmOrigin', '//']
            if explicit: params += ['I: Applicative']
            if parallel: params += [f'S: Semigroup = _ListErrors[{value}]']
            if raising: params += [f'X: {MD}']
            sig=f'_RaisingNary{n}[{", ".join(names)}, R, X]' if raising else f'_Nary{n}[{", ".join(names)}, R]'
            if n <= 2:
                prefix = '_RaisingUnary' if n == 1 and raising else '_Unary' if n == 1 else '_RaisingBinary' if raising else '_Binary'
                sig = f'{prefix}[{", ".join(names)}, R' + (', X]' if raising else ']')
            params += ['F: '+sig, f'*Ws: {MD}']
            if parallel:
                params = [p for p in params if p != '//' and not p.startswith(('S:', '*Ws:'))] + ['//', f'S: Semigroup = _ListErrors[{value}]', f'*Ws: {MD}']
            cb=f'_NativeNary{n}[{", ".join(names)}, R, {error}, F, {raising}, o]'
            mp=f'_MapNTypes[{family}, {value}, {cb}, *Ws]'
            output=f'{mp}.Out' if explicit else f'{family}.Pure[R]'
            raised=f'{mp}.Error' if explicit else f'_CommonError[S.Error, {error}]' if parallel and n > 1 else error
            args=f'Tuple[{", ".join(names)}]'
            cond=f'{where} and Ws.length == {n-1} and {admission_family}.Element[{value}] == {names[0]}'
            cond += ''.join(f' and {admission_family}.Element[Ws[{i-1}]] == {names[i]}' for i in range(1,n))
            if parallel and n > 1: cond += f' and _ErrorCompatible[{raised}, {error}]'
            call=f'_map_n_as[{family}, {product}, {output}, {raised}]({cb}(Pointer(to=function)), {source}, others^)'
            out.append(f'''
    def {name}[{', '.join(params)}](deinit self, var others: Tuple[*Ws], ref[o] function: F) raises {raised} -> {wrap(output)} where {cond}:
        """Combine {n} operands and call the native callback with separate arguments."""
        return {ret(call)}
''')
    rendered = ''.join(out)
    if parallel:
        rendered = rendered.replace('            The family of flat tuples in receiver-first order. No additional\n            operands produces one-element tuples. List uses Cartesian ordering.',
            '            A Result of a flat tuple in receiver-first order, or accumulated\n            stored errors. No additional operands produces a one-element tuple.')
        rendered = rendered.replace('            The exact family construction error; stored Result errors remain data.',
            '            The exact error-combination error; Never with no additional\n            operands. Stored Result errors remain data.')
        rendered = rendered.replace('Combine operands, then map a callback over each flat tuple of payloads.',
            'Combine independent Results, accumulating their stored errors in order.')
        rendered = rendered.replace('            The family of callback results; absence or failure skips the callback.\n            List materializes the Cartesian tuples before mapping them in order.',
            '            A Result of the callback output, or all stored errors combined in\n            receiver-first order. The callback runs once only if every input is Ok.')
    return rendered
