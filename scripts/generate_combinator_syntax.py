"""Thin terminal admission signatures shared by free functions and fluent APIs."""
from combinator_docs import document_first_methods
from operation_specs import TERMINALS
from native_signatures import MD, callback, callable_protocol, callable_metadata, native_adapter

START = '# --- terminal syntax (generated) ---\n'
END = '# --- end terminal syntax ---\n'
HEADER = '# Generated by scripts/generate_plain_overloads.py; execution lives in iteration.reductions.\n'


def terminal_methods(mode, carrier=None):
    out = []
    # Numeric addition is native Int/SIMD arithmetic, not a new arithmetic trait.
    # Custom numeric types can use fold_map/combine_all with their own Monoid.
    operations = [('find_map', None), ('fold_map', None), ('combine_all', None),
                  ('min_by', None), ('max_by', None),
                  ('sum', 'Int'), ('sum', 'SIMD'), ('sum_by', 'Int'), ('sum_by', 'SIMD')]
    for name, numeric in operations:
        operation = TERMINALS[name]
        callback_arg = operation.callback
        for kind in (('pure', 'raising', 'library', 'view') if callback_arg else ('none',)):
            native = kind in {'pure', 'raising'}
            borrowing = operation.borrowing
            params, explicit = [], []
            numeric_type = 'Int' if numeric == 'Int' else 'SIMD[dtype, size]'
            if numeric == 'SIMD': params += ['dtype: DType', 'size: SIMDLength']
            if native:
                params += ['P: AnyType' if borrowing else f'A: {MD}', f'R: {MD}', 'o: ImmOrigin']
                element = f'downcast[P, {MD}]' if borrowing else 'A'
                callback_result = 'R'
            elif kind == 'library':
                params += [f'C: {callable_protocol("borrow")} & {MD}' if borrowing else f'F: {callable_protocol("owned")} & {MD}']
                metadata = callable_metadata('borrow' if borrowing else 'owned', 'C' if borrowing else 'F')
                element = f'downcast[{metadata.inputs[0]}, {MD}]' if borrowing else metadata.inputs[0]
                callback_result = metadata.result
            elif kind == 'view':
                view = callback('borrow' if borrowing else 'owned', kind)
                if not borrowing: view = view.renamed({'C': 'F'})
                params += view.parameters
                element = f'downcast[{view.payload}, {MD}]' if borrowing else view.payload
                callback_result = view.result
            else:
                element = numeric_type if name == 'sum' else 'M.Value'
                callback_result = element
            if mode == 'free': params += [f'V: {MD}']
            if carrier: params += list(carrier.parameters)
            if name in {'fold_map', 'combine_all'}: explicit.append('M: Monoid')
            if native:
                if kind == 'raising': explicit.append(f'E: {MD}')
                bound = '_RaisingBorrowing[P, R, E]' if borrowing and kind == 'raising' else '_Borrowing[P, R]' if borrowing else '_RaisingUnary[A, R, E]' if kind == 'raising' else '_Unary[A, R]'
                explicit.append('F: '+bound)
                error = 'E' if kind == 'raising' else 'Never'
                cb = native_adapter('borrow' if borrowing else 'owned', ['P' if borrowing else 'A'], 'R', error, 'F', kind == 'raising', origin='o')
                build, arg = f'{cb}(Pointer(to=function))', 'ref[o] function: F'
            elif kind == 'library':
                error, cb = metadata.error, 'C' if borrowing else 'F'
                build, arg = 'function^', f'var function: {cb}'
            elif kind == 'view':
                error, cb, build, arg = view.error, view.type, view.build, view.argument
            else:
                error, cb, build, arg = 'Never', f'_Same[{element}]', f'_Same[{element}]()', ''
            params += (['//'] if params else []) + explicit
            if mode == 'piped':
                source_type = carrier.value(element)
                condition = f'Self.Value == {source_type}'
                setup = [f'comptime assert Self.Value == {source_type}']
                source = f'rebind_var[{source_type}](self.value^)'
            else:
                setup = []
                source = 'source^' if mode == 'free' else 'self._iterator^'
                condition = f'_Source[V].Element == {element}' if mode == 'free' else f'Self.I.Element == {element}'
            if numeric and callback_arg: condition += f' and {callback_result} == {numeric_type}'
            if borrowing: condition += f' and conforms_to({callback_result}, Comparable & {MD})'
            if borrowing and kind == 'library': condition += ' and RepeatableBorrow[C]'
            if name == 'find_map':
                result, raised = operation.result(element, callback_result, ''), error
                call = operation.invoke('', build, source)
                run = operation.runner(element, cb, '', raised)
            elif borrowing:
                result, raised = operation.result(element, callback_result, ''), error
                call = operation.invoke(f'T={element}, C={cb}, smallest={operation.smallest}', build, source)
                run = operation.runner(element, cb, '', raised)
            else:
                monoid = '_IntSum' if numeric == 'Int' else '_SIMDSum[dtype, size]' if numeric else 'M'
                result = operation.result(element, callback_result, numeric_type if numeric else 'M.Value')
                raised = operation.error(error, None if numeric else 'M.Error')
                call = operation.invoke(f'M={monoid}' + (f', E={error}' if numeric else ''), build, source)
                run = operation.runner(element, cb, monoid, raised)
            if mode == 'piped':
                boundary = {'Dict': '_dict_terminal', 'StringDict': '_string_dict_terminal',
                            'Array': '_array_terminal'}.get(carrier.name, '_run_terminal')
                result, call = f'Piped[{result}]', f'Piped({boundary}({run}({build}), {source}))'
            args = ([arg] if arg else []) + (['var source: V'] if mode == 'free' else [])
            if mode != 'free': args.insert(0,'deinit self')
            indent = '' if mode == 'free' else '    '
            doc = operation.summary
            param_text = '['+', '.join(params)+']' if params else ''
            out.append(f'\n{indent}def {name}{param_text}({", ".join(args)}) raises {raised} -> {result} where {condition}:\n')
            out.append(f'{indent}    """{doc}"""\n')
            out.extend(f'{indent}    {line}\n' for line in setup)
            out.append(f'{indent}    return {call}\n')
    source = ''.join(out) + '\n'
    return document_first_methods(source) if not carrier or carrier.name == 'List' else source
